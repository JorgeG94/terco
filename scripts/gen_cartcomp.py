#!/usr/bin/env python3
"""
Emit the (l, ic) -> (px,py,pz) Cartesian-component table shared by every
hand-written site that used to hand-roll it: `comp` in trc_hgp.F90 and
trc_binkernel.F90 (deliberately duplicated for inlining -- see their own
comments), `cart_pow` in trc_batch.F90, and the AO-value table
`shell_collocate` in src/xc/trc_collocation.F90 reads on the DFT grid.

WHY ONE GENERATOR FOR FOUR SITES
---------------------------------
All four are the SAME data: which (lx,ly,lz) triple sits at local offset `ic`
within a shell of angular momentum `l`. Before this generator they were four
independent copies of the same nested loop (`do lx=l,0,-1; do ly=l-lx,0,-1`),
which is exactly the shape cartorder.py's own module docstring warns about --
"written independently... and nothing checked that the two agreed." Generating
all four from `cartorder.components` removes the duplication without removing
the DELIBERATE one: `comp`'s two copies (trc_hgp.F90, trc_binkernel.F90) still
compile into two separate device routines, because NVHPC will not inline
`!$acc routine seq` across a module boundary (docs/GENERATORS.md). Only the
DATA is single-sourced now, by both #including the same generated body inside
their own subroutine.

THIS IS OUTPUT, NOT INTERNAL
------------------------------
Every one of these four sites places the component AT AN AO OFFSET directly:
`comp`'s `ic` becomes `mu = ao_off(shell) + ic` (or the equivalent for
`cart_pow`'s caller, `digest_sym`), and `shell_collocate`'s `m` is the AO-value
slot every other AO-indexed quantity uses. So the table generated here follows
`--order`, and the compiled file records which one and guards against a
mismatch, the way trc_hrr_cases.inc guards TRC_LMAX (docs/GENERATORS.md's
"stale generated file" trap) -- same idea, a different compile-time constant.

Two shapes come out:

  * `trc_cart_comp.inc` -- a `select case (l*100 + ic)` body, textually
    #included inside each site's own `pure subroutine comp`/`cart_pow(l, ic,
    px, py, pz)`. A branch per call is what the nested loop it replaces cost
    too (early exit on `n == ic`), so this is not a new cost.

  * `trc_collocation_table.inc` -- flat PARAMETER arrays, no branch at all.
    `shell_collocate` runs once per (shell, grid point) and used to derive
    (ix,iy,iz) from loop counters with NO lookup whatsoever; a `select case`
    per grid point per component would be new branching in the hottest loop
    the XC integrator has. A table lookup, one flat loop instead of two
    nested ones, is not.

USAGE
    gen_cartcomp.py --order lexicographic \
        --comp-out src/generated/trc_cart_comp.inc \
        --colloc-out src/generated/trc_collocation_table.inc
"""

import argparse

import cartorder

#: Ceiling both include files are generated to. Fixed rather than following
#: TERCO_LMAX: `shell_collocate` accepts l up to XC_LMAX (trc_collocation.F90,
#: currently 4, "generous on purpose" -- a d shell costs no more there than an
#: s one) independently of the four-centre ceiling, and cartorder's gamess
#: table itself is only transcribed through l=4. 4 is not a guess: it is the
#: actual joint ceiling of every caller this file has.
CEIL = 4


def _guard(order_val):
    return f"""!
! TRC_CART_ORDER GUARD. This table's layout was fixed at generation time by
! --order; TRC_CART_ORDER selects it at compile time (0 = lexicographic, the
! default and libcint's own within-shell order; 1 = gamess). An undefined
! TRC_CART_ORDER reads as 0 in a preprocessor #if, which is what lets the
! default build skip passing any new -D flag at all. If the two disagree,
! AO-indexed output lands in the wrong slot silently -- docs/GENERATORS.md's
! "stale generated file" trap is exactly this failure mode for TRC_LMAX; this
! is the same guard for a different compile-time constant.
!
#if TRC_CART_ORDER != {order_val}
#error "This file was generated for a different TRC_CART_ORDER. Regenerate it."
#endif
"""


def emit_comp_table(order, order_val, cmd):
    o = [f"""!
! (l, ic) -> (px, py, pz): the Cartesian component at local offset `ic`
! (0-based) within a shell of angular momentum l, l = 0..{CEIL}.
!
! GENERATED by {cmd} -- do not edit.
!
! #included inside `comp`'s/`cart_pow`'s OWN subroutine body at every call
! site (trc_hgp.F90, trc_binkernel.F90, trc_batch.F90) rather than called,
! for the reason each site's own comment gives: NVHPC will not inline
! `!$acc routine seq` across a module boundary, so a shared call here would
! reproduce the 2.4x slowdown docs/GENERATORS.md measured for the VRR.
!
{_guard(order_val)}      select case (l*100 + ic)"""]
    for l in range(CEIL + 1):
        for ic, (px, py, pz) in enumerate(cartorder.components(l, order)):
            o.append(f"      case ({l*100 + ic}); px = {px}; py = {py}; pz = {pz}")
    o.append("""      case default
         px = 0; py = 0; pz = 0
      end select""")
    return "\n".join(o) + "\n"


def emit_collocation_table(order, order_val, cmd):
    flat = []
    off = [0]
    for l in range(CEIL + 1):
        for (px, py, pz) in cartorder.components(l, order):
            flat.append((px, py, pz))
        off.append(len(flat))
    n = len(flat)

    def wrapped(values, per_line=16):
        """A Fortran array constructor, continued every `per_line` values --
        free-form Fortran's line limit is 132 columns, and CC_NX/CC_NY/CC_NZ
        at the ceiling (35 entries) ran past it as one line, which nvfortran
        did not merely warn about."""
        parts = [str(v) for v in values]
        lines = [", ".join(parts[i:i + per_line])
                for i in range(0, len(parts), per_line)]
        return (", &\n         ").join(lines)

    cx = wrapped([p[0] for p in flat])
    cy = wrapped([p[1] for p in flat])
    cz = wrapped([p[2] for p in flat])
    offs = wrapped(off)
    return f"""!
! Flat (ix,iy,iz) table for shell_collocate, l = 0..{CEIL}: component `m`
! (1-based) of a shell of angular momentum l is at flat index CC_OFF(l) + m.
!
! GENERATED by {cmd} -- do not edit.
!
! A table, not a `select case`: this runs once per (shell, grid point), and
! the code it replaces derived (ix,iy,iz) from loop counters with no lookup
! at all, so a `select case` per grid point per component would be NEW
! branching in the hottest loop the XC integrator has. #included at MODULE
! scope in trc_collocation.F90, as PARAMETER arrays -- compile-time constants
! need no `!$acc declare create`/`update device`, unlike trc_cart's runtime-
! built tables (trc_cart.F90), which this is not a replacement for: that
! table also carries the VRR's recurrence-direction bookkeeping, which has
! nothing to do with Cartesian order and is untouched by this generator.
!
{_guard(order_val)}      integer, parameter :: CC_NCART = {n}
      integer, parameter :: CC_OFF(0:{CEIL + 1}) = [{offs}]
      integer, parameter :: CC_NX(CC_NCART) = [{cx}]
      integer, parameter :: CC_NY(CC_NCART) = [{cy}]
      integer, parameter :: CC_NZ(CC_NCART) = [{cz}]
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--order", choices=("lexicographic", "gamess"),
                    default="lexicographic")
    ap.add_argument("--comp-out", default="src/generated/trc_cart_comp.inc")
    ap.add_argument("--colloc-out",
                    default="src/generated/trc_collocation_table.inc")
    args = ap.parse_args()
    order_val = 0 if args.order == "lexicographic" else 1
    # Suppressed when default, like every other generator here: the shipped
    # set's header text must not change just because the option now exists,
    # or "regenerates byte for byte with default options" stops being true.
    cmd = "scripts/gen_cartcomp.py"
    if args.order != "lexicographic":
        cmd += f" --order {args.order}"
    with open(args.comp_out, "w") as fh:
        fh.write(emit_comp_table(args.order, order_val, cmd))
    with open(args.colloc_out, "w") as fh:
        fh.write(emit_collocation_table(args.order, order_val, cmd))
    print(f"wrote {args.comp_out} and {args.colloc_out} (order={args.order})")


if __name__ == "__main__":
    main()
