#!/usr/bin/env python3
"""Emit the dispatcher over the Rys per-class kernels `gen_rys.py` wrote.

One call per class to `gen_rys.py` keeps the generator itself simple --
"iterate on ONE class" is how it was built and checked -- so something else
has to collect the classes CMake asked for into the two entry points
`trc_rys_select.F90` (hand-written; parses `TRC_RYS_CLASSES`) needs:

  `rys_has_class(key)`  -- is there a Rys kernel for this class at all,
  `rys_dispatch(key, ...)` -- call it.

`rys_has_class` is what keeps an unrecognised or ungenerated class key from
being an unbuilt reference or, worse, a silent no-op that leaves `jmat`
stale: `trc_rys_select` only ever reaches `rys_dispatch` after checking it.
"""
import argparse
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


gp = _load("gp", os.path.join(HERE, "gen_perclass.py"))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--classes", required=True,
                    help="comma-separated four-digit class tags, e.g. "
                         "2222,2221,1111")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()
    tags = args.classes.split(",")

    keys = []
    use_lines = []
    for tag in tags:
        la, lb, lc, ld = (int(c) for c in tag)
        key = ((la*gp.CLASS_RADIX + lb)*gp.CLASS_RADIX + lc)*gp.CLASS_RADIX + ld
        keys.append((key, tag))
        use_lines.append(f"   use trc_pc_rys{tag}, only: rys{tag}")
    keys.sort()

    # Wrapped, not one line: at TERCO_LMAX=3 the list runs to 242 keys
    # (~1400 characters), which nvfortran rejects as a source line too long.
    case_list = ", &\n               ".join(
        ", ".join(str(k) for k, _ in keys[i:i + 16])
        for i in range(0, len(keys), 16))
    dispatch_cases = "\n".join(
        f"""      case ({key}); call rys{tag}(lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sPA, sPB, sD, &
                          npair, sp_i, sp_j, sp_q, thresh, pcut, jfac, kfac, omega, dsh, nbas, nao, sh_l, ao_off, &
                          nqp, qp_z, qp_c, qp_px, qp_py, qp_pz, &
                          sq_ax, sq_ay, sq_az, sq_abx, sq_aby, sq_abz, sq_n, ndens, dmat, jmat, rank, nranks)"""
        for key, tag in keys)

    out = f"""!
! Dispatcher over the Rys per-class kernels gen_rys.py wrote.
!
! GENERATED by scripts/gen_rys_dispatch.py --classes {args.classes} -- do not edit.
!
module trc_rys_kernels
   use pic_types, only: dp, int64
   use trc_tables, only: LMAX
{chr(10).join(use_lines)}
   implicit none
   private
   public :: rys_dispatch, rys_has_class

contains

   pure logical function rys_has_class(key)
      !! Is there a generated Rys kernel for this class key? `trc_rys_select`
      !! checks this before ever calling `rys_dispatch`, so a class the user
      !! asked for in TRC_RYS_CLASSES but that TERCO_RYS did not generate a
      !! kernel for falls back to HGP instead of landing on an unbuilt
      !! reference or a silent no-op.
      integer, intent(in) :: key
      select case (key)
      case ({case_list})
         rys_has_class = .true.
      case default
         rys_has_class = .false.
      end select
   end function rys_has_class

   subroutine rys_dispatch(key, lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sPA, sPB, sD, &
                          npair, sp_i, sp_j, sp_q, thresh, pcut, jfac, kfac, omega, dsh, nbas, nao, sh_l, ao_off, &
                          nqp, qp_z, qp_c, qp_px, qp_py, qp_pz, &
                          sq_ax, sq_ay, sq_az, sq_abx, sq_aby, sq_abz, sq_n, &
                          ndens, dmat, jmat, rank, nranks)
      integer, intent(in) :: key
{gp.PROLOGUE}
      integer, intent(in) :: rank, nranks
      select case (key)
{dispatch_cases}
      end select
   end subroutine rys_dispatch

end module trc_rys_kernels
"""
    with open(args.output, "w") as fh:
        fh.write(out)
    print(f"  {args.output}: dispatcher for {len(keys)} Rys classes")


if __name__ == "__main__":
    main()
