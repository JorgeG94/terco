#!/usr/bin/env python3
"""Emit the dispatcher over the Rys per-class GRADIENT kernels
`gen_rys_grad.py` wrote. Same role as gen_rys_dispatch.py, for the gradient
driver (`trc_grad.F90`'s `grad_bins`) instead of `trc_rys_select.F90`: there
is no HGP fallback for the gradient, so `grad_bins` calls `rysg_dispatch`
unconditionally for every class run and relies on every one of the 81
classes up to (dd|dd) having a kernel -- `rysg_has_class` exists anyway, as
a cheap defensive check against a class CMake's loop did not actually cover.
"""
import argparse
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


gp = _load("gp", os.path.join(HERE, "gen_perclass.py"))

#: Same shape as gen_perclass.py's PROLOGUE, with qp_a threaded in next to
#: qp_z/qp_c, sh_at/natm threaded in next to sh_l/ao_off, and grad(3, natm)
#! in place of jmat -- see gen_rys_grad.py's own splice for why.
PROLOGUE_G = PROLOGUE = """      integer,  intent(in)    :: lo, hi, nseg, npair, nbas, nao
      integer(int64), intent(in) :: sOff(nseg + 1)
      integer,  intent(in)    :: sA(nseg), sNB(nseg), sOA(nseg), sOB(nseg)
      integer,  intent(in)    :: sPA(nseg), sPB(nseg)
      logical,  intent(in)    :: sD(nseg)
      integer,  intent(in)    :: sp_i(npair), sp_j(npair)
      real(dp), intent(in)    :: sp_q(npair), thresh
      real(dp), intent(in)    :: pcut
      real(dp), intent(in)    :: jfac, kfac
      real(dp), intent(in)    :: dsh(nbas, nbas)
      integer,  intent(in)    :: sh_l(nbas), ao_off(nbas)
      integer,  intent(in)    :: sh_at(nbas), natm
      integer,  intent(in)    :: nqp
      real(dp), intent(in)    :: qp_z(nqp), qp_c(nqp), qp_a(nqp)
      real(dp), intent(in)    :: qp_px(nqp), qp_py(nqp), qp_pz(nqp)
      real(dp), intent(in)    :: sq_ax(npair), sq_ay(npair), sq_az(npair)
      real(dp), intent(in)    :: sq_abx(npair), sq_aby(npair), sq_abz(npair)
      integer,  intent(in)    :: sq_n(npair)
      integer,  intent(in)    :: ndens
      real(dp), intent(in)    :: dmat(ndens, nao, nao)
      real(dp), intent(inout) :: grad(3, natm)"""


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--classes", required=True,
                    help="comma-separated four-digit class tags")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()
    tags = args.classes.split(",")

    keys = []
    use_lines = []
    for tag in tags:
        la, lb, lc, ld = (int(c) for c in tag)
        key = ((la*gp.CLASS_RADIX + lb)*gp.CLASS_RADIX + lc)*gp.CLASS_RADIX + ld
        keys.append((key, tag))
        use_lines.append(f"   use trc_pc_rysg{tag}, only: rysg{tag}, rysg{tag}_screen, rysg{tag}_compact")
    keys.sort()

    case_list = ", ".join(str(k) for k, _ in keys)
    dispatch_cases = "\n".join(
        f"""      case ({key}); call rysg{tag}(lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sPA, sPB, sD, &
                          npair, sp_i, sp_j, sp_q, thresh, pcut, jfac, kfac, dsh, nbas, nao, sh_l, ao_off, sh_at, natm, &
                          nqp, qp_z, qp_c, qp_a, qp_px, qp_py, qp_pz, &
                          sq_ax, sq_ay, sq_az, sq_abx, sq_aby, sq_abz, sq_n, ndens, dmat, grad, rank, nranks)"""
        for key, tag in keys)

    screen_cases = "\n".join(
        f"""      case ({key}); call rysg{tag}_screen(lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sPA, sPB, sD, &
                          npair, sp_i, sp_j, sp_q, thresh, dsh, nbas, sh_at, &
                          out_seg, out_iab, out_icd, nmax, ctr)"""
        for key, tag in keys)

    compact_cases = "\n".join(
        f"""      case ({key}); call rysg{tag}_compact(nout, out_seg, out_iab, out_icd, nseg, sA, sNB, sOA, sOB, sPA, sPB, sD, &
                          npair, sp_i, sp_j, sp_q, pcut, jfac, kfac, nbas, nao, ao_off, sh_at, natm, &
                          nqp, qp_z, qp_c, qp_a, qp_px, qp_py, qp_pz, &
                          sq_ax, sq_ay, sq_az, sq_abx, sq_aby, sq_abz, sq_n, ndens, dmat, grad)"""
        for key, tag in keys)

    out = f"""!
! Dispatcher over the Rys per-class GRADIENT kernels gen_rys_grad.py wrote.
!
! GENERATED by scripts/gen_rys_grad_dispatch.py --classes {args.classes} -- do not edit.
!
! Three entry points, mirroring the three ways `grad_bins` can run a class:
! `rysg_dispatch` (the fused kernel, TRC_GRAD_FUSED=1 only, kept for A/B
! timing) and the ORDERED SURVIVOR COMPACTION pair `rysg_screen_dispatch` /
! `rysg_compact_dispatch` (the default path) -- see scripts/gen_rys_grad.py's
! screen_and_compact_text for the technique.
!
module trc_rys_grad_kernels
   use, intrinsic :: iso_fortran_env, only: int64
   use trc_boys, only: dp
   use trc_tables, only: LMAX
{chr(10).join(use_lines)}
   implicit none
   private
   public :: rysg_dispatch, rysg_has_class
   public :: rysg_screen_dispatch, rysg_compact_dispatch

contains

   pure logical function rysg_has_class(key)
      !! Is there a generated Rys gradient kernel for this class key? There
      !! is no HGP gradient fallback, so a class `grad_bins` meets without
      !! one is a configuration error, not a silently skipped contribution --
      !! callers that care check this before dispatching.
      integer, intent(in) :: key
      select case (key)
      case ({case_list})
         rysg_has_class = .true.
      case default
         rysg_has_class = .false.
      end select
   end function rysg_has_class

   subroutine rysg_dispatch(key, lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sPA, sPB, sD, &
                          npair, sp_i, sp_j, sp_q, thresh, pcut, jfac, kfac, dsh, nbas, nao, sh_l, ao_off, sh_at, natm, &
                          nqp, qp_z, qp_c, qp_a, qp_px, qp_py, qp_pz, &
                          sq_ax, sq_ay, sq_az, sq_abx, sq_aby, sq_abz, sq_n, &
                          ndens, dmat, grad, rank, nranks)
      integer, intent(in) :: key
{PROLOGUE_G}
      integer, intent(in) :: rank, nranks
      select case (key)
{dispatch_cases}
      end select
   end subroutine rysg_dispatch

   subroutine rysg_screen_dispatch(key, lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sPA, sPB, sD, &
                          npair, sp_i, sp_j, sp_q, thresh, dsh, nbas, sh_at, &
                          out_seg, out_iab, out_icd, nmax, ctr)
      !! ORDERED SURVIVOR COMPACTION, screen pass: decode + the three
      !! quartet-level screens only, appending survivors to a dense list.
      !! See scripts/gen_rys_grad.py's screen_and_compact_text.
      integer, intent(in) :: key
      integer,  intent(in)    :: lo, hi, nseg, npair, nbas, nmax
      integer(int64), intent(in) :: sOff(nseg + 1)
      integer,  intent(in)    :: sA(nseg), sNB(nseg), sOA(nseg), sOB(nseg)
      integer,  intent(in)    :: sPA(nseg), sPB(nseg)
      logical,  intent(in)    :: sD(nseg)
      integer,  intent(in)    :: sp_i(npair), sp_j(npair)
      real(dp), intent(in)    :: sp_q(npair), thresh
      real(dp), intent(in)    :: dsh(nbas, nbas)
      integer,  intent(in)    :: sh_at(nbas)
      integer,  intent(inout) :: out_seg(nmax), out_iab(nmax), out_icd(nmax)
      integer(int64), intent(inout) :: ctr(1)
      select case (key)
{screen_cases}
      end select
   end subroutine rysg_screen_dispatch

   subroutine rysg_compact_dispatch(key, nout, out_seg, out_iab, out_icd, nseg, sA, sNB, sOA, sOB, sPA, sPB, sD, &
                          npair, sp_i, sp_j, sp_q, pcut, jfac, kfac, nbas, nao, ao_off, sh_at, natm, &
                          nqp, qp_z, qp_c, qp_a, qp_px, qp_py, qp_pz, &
                          sq_ax, sq_ay, sq_az, sq_abx, sq_aby, sq_abz, sq_n, &
                          ndens, dmat, grad)
      !! ORDERED SURVIVOR COMPACTION, compact pass: the same integral body
      !! as `rysg_dispatch`'s fused kernel, run over the dense survivor
      !! list `rysg_screen_dispatch` produced.
      integer, intent(in) :: key
      integer(int64), intent(in) :: nout
      integer,  intent(in)    :: out_seg(*), out_iab(*), out_icd(*)
      integer,  intent(in)    :: nseg, npair, nbas, nao
      integer,  intent(in)    :: sA(nseg), sNB(nseg), sOA(nseg), sOB(nseg)
      integer,  intent(in)    :: sPA(nseg), sPB(nseg)
      logical,  intent(in)    :: sD(nseg)
      integer,  intent(in)    :: sp_i(npair), sp_j(npair)
      real(dp), intent(in)    :: sp_q(npair), pcut, jfac, kfac
      integer,  intent(in)    :: ao_off(nbas), sh_at(nbas), natm
      integer,  intent(in)    :: nqp
      real(dp), intent(in)    :: qp_z(nqp), qp_c(nqp), qp_a(nqp)
      real(dp), intent(in)    :: qp_px(nqp), qp_py(nqp), qp_pz(nqp)
      real(dp), intent(in)    :: sq_ax(npair), sq_ay(npair), sq_az(npair)
      real(dp), intent(in)    :: sq_abx(npair), sq_aby(npair), sq_abz(npair)
      integer,  intent(in)    :: sq_n(npair)
      integer,  intent(in)    :: ndens
      real(dp), intent(in)    :: dmat(ndens, nao, nao)
      real(dp), intent(inout) :: grad(3, natm)
      select case (key)
{compact_cases}
      end select
   end subroutine rysg_compact_dispatch

end module trc_rys_grad_kernels
"""
    with open(args.output, "w") as fh:
        fh.write(out)
    print(f"  {args.output}: dispatcher for {len(keys)} Rys gradient classes")


if __name__ == "__main__":
    main()
