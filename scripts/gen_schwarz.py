#!/usr/bin/env python3
"""Emit the Rys-quadrature diagonal Schwarz kernel, trc_schwarz_rys.F90.

WHY
---
The Cauchy-Schwarz bound Q(i,j) = sqrt(max_{ab} |(ij|ij)_{ab,ab}|) only ever
needs the DIAGONAL of a shell pair's Gram block: for the positive
semi-definite matrix M[(a,b),(a',b')] = (ab|a'b'), |M_xy| <= sqrt(M_xx M_yy)
<= max_x M_xx, so the block's largest absolute element sits on the diagonal.
`trc_hgp.F90`'s `hgp_quartet` computes the WHOLE (ab|ab) block -- na*na
integrals -- on one thread to get that one number; for a (gg|gg) pair that
is 50625 integrals (15^4) serialised behind one thread's VRR scratch, which
on a GH200 cost 3.5 s per call on a 700-shell water cluster, four calls a
run.

This kernel computes only the na diagonal elements, one thread per
(shell pair, Cartesian component pair), so a (gg) pair launches 225 threads
instead of one. The maths is otherwise ordinary Rys quadrature, spliced from
the same algebra `gen_rys.py` uses for the four-centre Fock build (see that
script's own "THE ALGEBRA" section) with the ket forced to equal the bra
shell pair: for the diagonal element (ab|ab), the ket's first centre is the
bra's A, the ket's second centre is the bra's B, and the ket primitive-pair
list is the bra's own -- so there is no separate ket primitive-pair table,
and no VRR scratch sized per quartet: just a 2D Rys table (at most 9x9 per
axis, LMAX=4) and a two-term horizontal transfer extracting the one (ax,bx|
ax,bx)-type corner each thread needs, not the whole Cartesian block.

THE ROOT COUNT IS RUNTIME, THE ROOT TABLES ARE NOT
----------------------------------------------------
`gen_rys.py` picks nroots = (la+lb+lc+ld)/2 + 1 at GENERATION time, one
kernel per class, so it only ever needs ONE `trc_rys_table{n}` module. Here
la and lb are properties of whatever shell pair is live in a given basis, so
nroots = la+lb+1 is a RUNTIME value, 1..9 at the LMAX=4 ceiling this kernel
is sized for (independent of TERCO_LMAX: a Schwarz bound has to exist for
whatever class the build supports, including the classes the four-centre
path routes to Rys rather than HGP). The only way to keep the Rys root
lookup call-free in that situation is a `select case (nroots)` over all 9
inlined lookups (`rys_inline.py`'s `roots_inline_body`, same one every
per-class Rys kernel uses) -- the piece this generator exists to produce.
Everything around it (the 2D recurrence, the horizontal transfer) has no
per-class literal to bake in, so it is written once as ordinary runtime
Fortran loops, not templated.

USAGE
    gen_schwarz.py -o src/generated/schwarz/trc_schwarz_rys.F90

The output lives in its own subdirectory, like the Rys root tables
(src/CMakeLists.txt), so src/CMakeLists.txt's non-recursive `file(GLOB
... "${_gen_dir}/*.F90")` -- which feeds the TERCO_LMAX-dependent build
tree at a non-default ceiling -- never picks it up either there or in the
committed src/generated: it is wired in directly, unconditionally, next to
eri/trc_rys_select.F90.
"""
import argparse
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


ri = _load("ri", os.path.join(HERE, "rys_inline.py"))

#: The ceiling this kernel is sized for -- fixed, not TERCO_LMAX: a g shell
#: pair (la = lb = 4) needs ltot = la + lb = 8 and nroots = 9, the largest
#: either table lookup or the 2D-table/HRR scratch below has to hold, and a
#: Schwarz bound has to exist for every class the build supports, not just
#: the ones TERCO_LMAX's four-centre Fock path currently reaches.
LCEIL = 4
LTOT_MAX = 2*LCEIL
NROOTS_MAX = LTOT_MAX + 1


def roots_dispatch(indent):
    """`select case (nroots)`, one inlined lookup per n = 1..NROOTS_MAX,
    each exactly `rys_inline.py`'s `roots_inline_body` -- the same text
    every per-class Rys kernel splices in, just reached through a runtime
    branch here instead of being the only branch."""
    pad = " "*indent
    lines = [f"{pad}select case (nroots)"]
    for n in range(1, NROOTS_MAX + 1):
        lines.append(f"{pad}case ({n})")
        lines.append(ri.roots_inline_body(n, "tval", indent + 3).rstrip("\n"))
    lines.append(f"{pad}case default")
    lines.append(f"{pad}   ru = 0.0_dp")
    lines.append(f"{pad}   rw = 0.0_dp")
    lines.append(f"{pad}end select")
    return "\n".join(lines) + "\n"


def roots_uses():
    return "".join(ri.roots_table_use(n) for n in range(1, NROOTS_MAX + 1))


MODULE_TEMPLATE = '''\
!
! GENERATED by scripts/gen_schwarz.py -- do not edit.
!
! The Rys-quadrature diagonal Schwarz kernel: computes (ab|ab) for one
! Cartesian component pair of one live shell pair, with the ket forced
! equal to the bra pair (A=C, B=D, the bra's own primitive-pair list reused
! as the ket's). See this generator's module docstring for why: the
! Cauchy-Schwarz bound only ever needs the diagonal of a shell pair's Gram
! block, and this kernel computes exactly that, one GPU thread per
! (pair, component pair) rather than one thread per pair holding the whole
! block.
!
! THREAD MAPPING. `schwarz_rys_batch`'s do-concurrent is flattened over a
! single index spanning every (pair, component) assignment in the chunk
! (t_i/t_j/t_c, built by the caller, `trc_screen.F90`'s
! `screen_schwarz_bounds_rys`) rather than nested over (pair, component): a `do
! concurrent` whose OUTER extent varies per iteration and is small drops
! the last slice on some nvfortran versions (see the project's own notes on
! this), so the outer/inner pair is precomputed on the host instead and the
! kernel launches over the flat total.
!
! SCRATCH. Per thread: the Rys roots/weights (ru/rw, sized {nroots_max}),
! three 2D Rys tables gx/gy/gz (sized ({ltot_max}+1)x({ltot_max}+1), the
! LMAX={lceil} ceiling -- a (gg) pair needs ltot = la+lb = {ltot_max} and
! {nroots_max} roots, which is the most this kernel's arrays are ever
! asked to hold, regardless of TERCO_LMAX), and a handful of scalars. No
! VRR scratch sized per quartet, unlike `trc_hgp.F90`'s `hgp_quartet`: the
! horizontal transfer below extracts the single (ax,bx|ax,bx)-type corner
! each thread needs straight from the 2D table instead of building the
! whole Cartesian block first.
!
module trc_schwarz_rys
   use pic_types, only: dp
   use trc_cart, only: ncum_of, cnx, cny, cnz
   ! The Rys root/weight tables, all nine root counts: nroots = la+lb+1 is a
   ! runtime value (see the module header), so every table this kernel might
   ! need is brought in here, once, rather than selected at generation time
   ! the way a per-class gen_rys.py kernel's single `use` is.
{roots_uses_mod}
   implicit none
   private

   public :: schwarz_rys_batch

   real(dp), parameter :: TWO_PI_2_5 = 34.986836655249725_dp

   !: The ceiling this kernel is sized for; see the module header.
   integer, parameter :: SCHWARZ_LCEIL = {lceil}
   integer, parameter :: SCHWARZ_LTOT_MAX = {ltot_max}
   integer, parameter :: SCHWARZ_NROOTS_MAX = {nroots_max}

contains

   !
   ! Threads lo..hi of a flat (pair, component-pair) launch. t_i(k)/t_j(k)
   ! are the k-th thread's shell pair (i >= j); t_c(k) is its component
   ! pair within that pair's na = ncart(li)*ncart(lj) block, 1-based,
   ! ia-major: c = (ia-1)*ncart(lj) + ib, matching how the caller sizes
   ! t_off (trc_screen.F90). out(k) receives |[(ab|ab)]| for that one
   ! component; the caller reduces max(out) over each pair's slice and
   ! takes the square root to get Q.
   !
   subroutine schwarz_rys_batch(lo, hi, nthread, nbas, nhpp, &
                                t_i, t_j, t_c, sh_l, &
                                hp_off, hp_n, hp_p, hp_r, hp_ra, hp_rb, hp_c, out)
      integer,  intent(in)    :: lo, hi, nthread, nbas, nhpp
      integer,  intent(in)    :: t_i(nthread), t_j(nthread), t_c(nthread)
      integer,  intent(in)    :: sh_l(nbas)
      integer,  intent(in)    :: hp_off(nbas*nbas), hp_n(nbas*nbas)
      real(dp), intent(in)    :: hp_p(nhpp), hp_r(nhpp, 3), hp_ra(nhpp, 3), hp_rb(nhpp, 3), hp_c(nhpp)
      real(dp), intent(inout) :: out(nthread)
      integer :: k
      do concurrent(k = lo:hi)
         call schwarz_rys_item(k, nthread, nbas, nhpp, t_i, t_j, t_c, sh_l, &
                               hp_off, hp_n, hp_p, hp_r, hp_ra, hp_rb, hp_c, out)
      end do
   end subroutine schwarz_rys_batch

   !
   ! One thread's work: decode its (pair, component) assignment, then the
   ! Rys double primitive-pair loop (bra AND ket both from this pair's own
   ! hp_* list -- see the module header), accumulating (ab|ab) over every
   ! root and primitive-pair combination.
   !
   pure subroutine schwarz_rys_item(k, nthread, nbas, nhpp, t_i, t_j, t_c, sh_l, &
                                    hp_off, hp_n, hp_p, hp_r, hp_ra, hp_rb, hp_c, out)
      !$acc routine seq
      integer,  intent(in)    :: k, nthread, nbas, nhpp
      integer,  intent(in)    :: t_i(nthread), t_j(nthread), t_c(nthread)
      integer,  intent(in)    :: sh_l(nbas)
      integer,  intent(in)    :: hp_off(nbas*nbas), hp_n(nbas*nbas)
      real(dp), intent(in)    :: hp_p(nhpp), hp_r(nhpp, 3), hp_ra(nhpp, 3), hp_rb(nhpp, 3), hp_c(nhpp)
      real(dp), intent(inout) :: out(nthread)

      ! `jj`, not `j`: the inlined Rys root lookup below (roots_decls)
      ! declares its own Chebyshev-degree loop counter `j`, and the two
      ! must not collide (rys_inline.py's own NAME COLLISIONS section).
      integer :: i, jj, la, lb, key, offab, nab, c, ia, ib, nb, ga, gb
      integer :: ax, ay, az, bx, by, bz, ltot, nroots
      integer :: kp, kq, rt
      real(dp) :: abx, aby, abz
      real(dp) :: zeta, eta, zpe, rho
      real(dp) :: pax, pay, paz, pqx, pqy, pqz, qcx, qcy, qcz
      real(dp) :: tval, pref
      real(dp) :: u2, dinv, b00r, b10r, bp01r, f00
      real(dp) :: c00x, c00y, c00z, cp0x, cp0y, cp0z
      real(dp) :: ru(SCHWARZ_NROOTS_MAX), rw(SCHWARZ_NROOTS_MAX)
      real(dp) :: gx(0:SCHWARZ_LTOT_MAX, 0:SCHWARZ_LTOT_MAX)
      real(dp) :: gy(0:SCHWARZ_LTOT_MAX, 0:SCHWARZ_LTOT_MAX)
      real(dp) :: gz(0:SCHWARZ_LTOT_MAX, 0:SCHWARZ_LTOT_MAX)
      real(dp) :: hxv, hyv, hzv, val
{roots_decls}
      i = t_i(k)
      jj = t_j(k)
      la = sh_l(i)
      lb = sh_l(jj)
      key = (i - 1)*nbas + jj
      offab = hp_off(key)
      nab = hp_n(key)

      ! Decode this thread's Cartesian component pair, ia-major, into the
      ! shell-local (nx,ny,nz) triples trc_cart's global tables carry past
      ! the shell's own offset (ncum_of(l-1); 0 for l=0, where there is
      ! nothing before it). Same convention trc_hgp.F90's digestion reads.
      nb = (lb + 1)*(lb + 2)/2
      c = t_c(k)
      ia = (c - 1)/nb + 1
      ib = c - (ia - 1)*nb
      if (la == 0) then
         ga = 0
      else
         ga = ncum_of(la - 1)
      end if
      if (lb == 0) then
         gb = 0
      else
         gb = ncum_of(lb - 1)
      end if
      ax = cnx(ga + ia); ay = cny(ga + ia); az = cnz(ga + ia)
      bx = cnx(gb + ib); by = cny(gb + ib); bz = cnz(gb + ib)

      ltot = la + lb
      nroots = ltot + 1

      ! AB is the same vector on the bra and the ket (the ket's centres are
      ! the bra's own A, B): computed once from the first primitive pair,
      ! same as trc_hgp.F90's splice does for abx/cdx (pp_ra/pp_rb are
      ! per-SHELL-PAIR, not per primitive, so any pair in the range reads
      ! the same value).
      abx = hp_ra(offab + 1, 1) - hp_rb(offab + 1, 1)
      aby = hp_ra(offab + 1, 2) - hp_rb(offab + 1, 2)
      abz = hp_ra(offab + 1, 3) - hp_rb(offab + 1, 3)

      val = 0.0_dp
      do kp = offab + 1, offab + nab
         zeta = hp_p(kp)
         pax = hp_r(kp, 1) - hp_ra(kp, 1)
         pay = hp_r(kp, 2) - hp_ra(kp, 2)
         paz = hp_r(kp, 3) - hp_ra(kp, 3)
         do kq = offab + 1, offab + nab
            eta = hp_p(kq)
            zpe = zeta + eta
            rho = zeta*eta/zpe
            pqx = hp_r(kp, 1) - hp_r(kq, 1)
            pqy = hp_r(kp, 2) - hp_r(kq, 2)
            pqz = hp_r(kp, 3) - hp_r(kq, 3)
            ! Q - C: the ket's first centre C is the bra's own A (the ket
            ! pair equals the bra pair), so this is Q - A, read from THIS
            ! primitive pair's own product centre (kq), not kp's.
            qcx = hp_r(kq, 1) - hp_ra(kq, 1)
            qcy = hp_r(kq, 2) - hp_ra(kq, 2)
            qcz = hp_r(kq, 3) - hp_ra(kq, 3)
            tval = rho*(pqx*pqx + pqy*pqy + pqz*pqz)
            ! theta = 1, omega = 0: Q never needs the range-separated
            ! bound (trc_screen.F90's module header), so no RANGE
            ! SEPARATION rescale of pref/u2 here, unlike gen_rys.py's Fock
            ! splice.
            pref = TWO_PI_2_5/(zeta*eta*sqrt(zpe))*hp_c(kp)*hp_c(kq)

{roots_dispatch}
            do rt = 1, nroots
               u2 = ru(rt)/(1.0_dp - ru(rt))*rho
               dinv = 1.0_dp/(zeta*eta + u2*(zeta + eta))
               b00r = 0.5_dp*u2*dinv
               b10r = 0.5_dp*(eta + u2)*dinv
               bp01r = 0.5_dp*(zeta + u2)*dinv
               f00 = pref*rw(rt)
               c00x = pax - u2*eta*dinv*pqx
               c00y = pay - u2*eta*dinv*pqy
               c00z = paz - u2*eta*dinv*pqz
               cp0x = qcx + u2*zeta*dinv*pqx
               cp0y = qcy + u2*zeta*dinv*pqy
               cp0z = qcz + u2*zeta*dinv*pqz

               ! The 2D Rys table, one axis at a time -- same recurrence as
               ! rys_inline.py's rys2d_inline_body, with runtime bounds
               ! (ltot is a shell-pair property, not a class constant here).
               call schwarz_rys_g2d(ltot, c00x, cp0x, b00r, b10r, bp01r, 1.0_dp, gx)
               call schwarz_rys_g2d(ltot, c00y, cp0y, b00r, b10r, bp01r, 1.0_dp, gy)
               call schwarz_rys_g2d(ltot, c00z, cp0z, b00r, b10r, bp01r, f00, gz)

               ! The horizontal transfer, extracting only the (ax,bx|ax,bx)
               ! corner this thread needs rather than the whole class.
               hxv = schwarz_rys_hrr_diag(ax, bx, abx, gx)
               hyv = schwarz_rys_hrr_diag(ay, by, aby, gy)
               hzv = schwarz_rys_hrr_diag(az, bz, abz, gz)

               val = val + hxv*hyv*hzv
            end do
         end do
      end do

      out(k) = abs(val)
   end subroutine schwarz_rys_item

   !
   ! One axis of the 2D Rys recurrence (rys_inline.py's rys2d_inline_body,
   ! unrolled form there -- this is its array/runtime-loop twin, since ni =
   ! nk = ltot is a shell-pair property rather than a class constant). g00
   ! is 1 on x and y, and the accumulated weight*prefactor (f00) on z, so
   ! the overall scale factor is carried exactly once.
   !
   pure subroutine schwarz_rys_g2d(ltot, c00, cp00, b00, b10, bp01, g00, g)
      !$acc routine seq
      integer,  intent(in)  :: ltot
      real(dp), intent(in)  :: c00, cp00, b00, b10, bp01, g00
      real(dp), intent(out) :: g(0:SCHWARZ_LTOT_MAX, 0:SCHWARZ_LTOT_MAX)
      integer :: n, m

      g(0, 0) = g00
      if (ltot >= 1) g(1, 0) = c00*g(0, 0)
      do n = 1, ltot - 1
         g(n + 1, 0) = real(n, dp)*b10*g(n - 1, 0) + c00*g(n, 0)
      end do
      if (ltot >= 1) g(0, 1) = cp00*g(0, 0)
      do n = 1, ltot
         g(n, 1) = real(n, dp)*b00*g(n - 1, 0) + cp00*g(n, 0)
      end do
      do m = 1, ltot - 1
         g(0, m + 1) = real(m, dp)*bp01*g(0, m - 1) + cp00*g(0, m)
         do n = 1, ltot
            g(n, m + 1) = real(n, dp)*b00*g(n - 1, m) &
                          + real(m, dp)*bp01*g(n, m - 1) + cp00*g(n, m)
         end do
      end do
   end subroutine schwarz_rys_g2d

   !
   ! The horizontal transfer's diagonal corner: (ea,eb|ea,eb) for one axis,
   ! from the 2D table `g` and the shift AB (ket uses the same AB, since
   ! the ket pair equals the bra pair -- see the module header). Same
   ! two-stage binomial expansion as rys_inline.py's hrr_inline_body
   !
   !   (a,b|c,d) = sum_t C(b,t) AB^(b-t) sum_u C(d,u) AB^(d-u) g(a+t, c+u)
   !
   ! specialised to a = c = ea, b = d = eb: only the one (a,b,c,d) corner
   ! this thread's component needs is formed, not the whole class table.
   !
   pure function schwarz_rys_hrr_diag(ea, eb, ab, g) result(hval)
      !$acc routine seq
      integer,  intent(in) :: ea, eb
      real(dp), intent(in) :: ab
      real(dp), intent(in) :: g(0:SCHWARZ_LTOT_MAX, 0:SCHWARZ_LTOT_MAX)
      real(dp) :: hval
      real(dp) :: abp(0:SCHWARZ_LCEIL), t1(0:SCHWARZ_LCEIL)
      integer :: p, t, u

      abp(0) = 1.0_dp
      do p = 1, eb
         abp(p) = abp(p - 1)*ab
      end do

      do u = 0, eb
         t1(u) = 0.0_dp
         do t = 0, eb
            t1(u) = t1(u) + schwarz_rys_binom(eb, t)*abp(eb - t)*g(ea + t, ea + u)
         end do
      end do

      hval = 0.0_dp
      do u = 0, eb
         hval = hval + schwarz_rys_binom(eb, u)*abp(eb - u)*t1(u)
      end do
   end function schwarz_rys_hrr_diag

   !
   ! Binomial coefficient, n and k both at most SCHWARZ_LCEIL (4): the HRR's
   ! shift never exceeds a single shell's own angular momentum.
   !
   pure function schwarz_rys_binom(n, k) result(c)
      !$acc routine seq
      integer, intent(in) :: n, k
      real(dp) :: c
      integer :: m
      real(dp) :: num, den

      if (k < 0 .or. k > n) then
         c = 0.0_dp
      else
         num = 1.0_dp
         den = 1.0_dp
         do m = 1, k
            num = num*real(n - m + 1, dp)
            den = den*real(m, dp)
         end do
         c = num/den
      end if
   end function schwarz_rys_binom

end module trc_schwarz_rys
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--output", required=True,
                     help="e.g. src/generated/schwarz/trc_schwarz_rys.F90 -- this "
                          "file is committed, like the Rys root tables, since it "
                          "has no TERCO_LMAX dependence to regenerate for")
    args = ap.parse_args()

    uses = roots_uses()
    decls = ri.roots_decls()
    dispatch = roots_dispatch(12)

    text = MODULE_TEMPLATE.format(
        lceil=LCEIL, ltot_max=LTOT_MAX, nroots_max=NROOTS_MAX,
        roots_uses_mod=uses.rstrip("\n"),
        roots_decls=decls.rstrip("\n"),
        roots_dispatch=dispatch.rstrip("\n"),
    )

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w") as f:
        f.write(text)
    print(f"{args.output}: {len(text.splitlines())} lines, nroots 1..{NROOTS_MAX}")


if __name__ == "__main__":
    main()
