   ! libxc's compositions where terco has one; ExchCXX's own table for
   ! everything else. Names are case-insensitive. A functional this build
   ! cannot run yet is still returned, ok = .true., with `missing` set.
   !
   function xc_functional_by_name(name, f) result(ok)
      character(len=*), intent(in) :: name
      type(trc_xc_functional_t), intent(out) :: f
      logical :: ok
      character(len=24) :: key
      integer :: i

      key = name
      do i = 1, len_trim(key)
         if (key(i:i) >= "A" .and. key(i:i) <= "Z") key(i:i) = achar(iachar(key(i:i)) + 32)
      end do
      f%name = key
      ok = .true.
      select case (trim(key))
      case ("lda_x", "slater")
         call set(f, XC_FAMILY_LDA, [XC_K_SLATER_EXCHANGE], [1.0_dp])
      case ("svwn", "lda", "svwn5")
         call set(f, XC_FAMILY_LDA, [XC_K_SLATER_EXCHANGE, XC_K_VWN], [1.0_dp, 1.0_dp])
      case ("svwn_rpa")
         call set(f, XC_FAMILY_LDA, [XC_K_SLATER_EXCHANGE, XC_K_VWN_RPA], [1.0_dp, 1.0_dp])
      case ("pbe")
         call set(f, XC_FAMILY_GGA, [XC_K_PBE_X, XC_K_PBE_C], [1.0_dp, 1.0_dp])
      case ("blyp")
         call set(f, XC_FAMILY_GGA, [XC_K_B88, XC_K_LYP], [1.0_dp, 1.0_dp])
      case ("pbe0")
         call set(f, XC_FAMILY_GGA, [XC_K_PBE_X, XC_K_PBE_C], [0.75_dp, 1.0_dp])
         f%exx = 0.25_dp
      case ("b3lyp")
         ! libxc HYB_GGA_XC_B3LYP: VWN_RPA in the correlation
         call set(f, XC_FAMILY_GGA, [XC_K_SLATER_EXCHANGE, XC_K_B88, XC_K_VWN_RPA, XC_K_LYP], &
            [0.08_dp, 0.72_dp, 0.19_dp, 0.81_dp])
         f%exx = 0.2_dp
      case ("b3lyp5")
         ! libxc HYB_GGA_XC_B3LYP5 and ExchCXX's B3LYP: VWN5
         call set(f, XC_FAMILY_GGA, [XC_K_SLATER_EXCHANGE, XC_K_B88, XC_K_VWN, XC_K_LYP], &
