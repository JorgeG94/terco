   pure subroutine ecp_type1_rad_ang(rad_ang, lmax, r, rad_all)
      !! Angular contraction of the type-1 (local) radial integrals.
      !! `rad_all` arrives indexed (total degree, lambda), `rad_ang` comes
      !! out over the three Cartesian powers, (lmax+1)^3, fixed to
      !! (2*ECP_ORB_LMAX+1)^3.
      !$acc routine seq
      integer, intent(in) :: lmax
      real(dp), intent(in) :: r(3)
      real(dp), intent(in) :: rad_all(0:(2*ECP_ORB_LMAX + 1)*(2*ECP_ORB_LMAX + 1) - 1)
      real(dp), intent(out) :: rad_ang(0:(2*ECP_ORB_LMAX + 1)**3 - 1)

      real(dp) :: unitr(3)
      real(dp) :: omega_nuc(0:CART_CUM - 1)
      real(dp) :: omega_scratch(0:ECP_ANG_NCART_MAX - 1)
      integer :: d1, d2, d3, i, j, k, n, lmb, need_even, pr, ps, pt
      real(dp) :: acc

      call unit_direction(r, unitr)

      do i = 0, lmax
         call ecp_ang_nuc_in_cart(omega_scratch, i, unitr)
         do n = 0, cart_len(i) - 1
            omega_nuc(OFFSET_CART(i) + n) = omega_scratch(n)
         end do
      end do

      d1 = lmax + 1
      d2 = d1*d1
      d3 = d2*d1
      rad_ang(0:d3 - 1) = 0.0_dp

      do i = 0, lmax
         do j = 0, lmax - i
            do k = 0, lmax - i - j
               need_even = mod(i + j + k, 2)
               do lmb = need_even, lmax, 2
                  acc = 0.0_dp
                  do n = 0, cart_len(lmb) - 1
                     ps = CART_POW_Y(n)
                     pt = CART_POW_Z(n)
                     pr = lmb - ps - pt
                     acc = acc + omega_nuc(OFFSET_CART(lmb) + n) &
                           *ecp_int_unit_xyz(i + pr, j + ps, k + pt)
                  end do
                  rad_ang(i*d2 + j*d1 + k) = rad_ang(i*d2 + j*d1 + k) &
                                             + rad_all((i + j + k)*d1 + lmb)*acc
               end do
            end do
         end do
      end do
   end subroutine ecp_type1_rad_ang

