               jab(1 + ia + 6*ib) = 0.0_dp
            end do
         end do
         do id = 0, 0
            do ic = 0, 2
               dcd(1 + ic + 3*id) = dmat(idens, lamk + ic, sigl + id)
               jcd(1 + ic + 3*id) = 0.0_dp
            end do
         end do
         do ic = 0, 2
            do ia = 0, 5
               dac(1 + ia + 6*ic) = dmat(idens, mui + ia, lamk + ic)
               kac(1 + ia + 6*ic) = 0.0_dp
            end do
         end do
         do id = 0, 0
            do ia = 0, 5
               dad(1 + ia + 6*id) = dmat(idens, mui + ia, sigl + id)
