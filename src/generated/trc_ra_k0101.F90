!
! One module per class, matching src/generated/trc_pc_k0101.F90: the item
! routine stays in the same file as its driver so it inlines (the whole
! reason the HGP kernels do this too, see docs/GENERATORS.md), and the
! dispatcher is host code free to cross modules.
!
! No TRC_CART_ORDER guard: every class here is s/p (FRAME.md section 5 --
! d is not implemented), and lexicographic and gamess are the SAME order for
! s and p, so this file's layout is provably order-invariant regardless of
! --order. (--order is still accepted and threaded to `Derivation` above,
! so a future kind above p would be generated correctly rather than silently
! defaulting.)
!
module trc_ra_k0101
   use, intrinsic :: iso_fortran_env, only: int64
   use trc_boys, only: dp, boys_eval, BOYS_MMAX, boys_table, &
                         BOYS_NCHEB, BOYS_NGRID, BOYS_TMAX, &
                         BOYS_DT, BOYS_DTINV
   use trc_tables, only: LMAX
   implicit none
   private
   public :: ras0101

   real(dp), parameter :: TWO_PI_2_5 = 34.986836655249725_dp

contains
   subroutine ras0101(lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sD, &
                      npair, sp_i, sp_j, sp_q, thresh, pcut, jfac, kfac, dsh, nbas, npp, nao, sh_l, ao_off, &
                      pp_off, pp_n, pp_p, pp_r, pp_ra, pp_rb, pp_c, pp_cs, &
                      ndens, dmat, jmat, rank, nranks)
      integer,  intent(in)    :: lo, hi, nseg, npair, nbas, npp, nao
      integer(int64), intent(in) :: sOff(nseg + 1)
      integer,  intent(in)    :: sA(nseg), sNB(nseg), sOA(nseg), sOB(nseg)
      logical,  intent(in)    :: sD(nseg)
      integer,  intent(in)    :: sp_i(npair), sp_j(npair)
      real(dp), intent(in)    :: sp_q(npair), thresh
      !! Cutoff for the primitive-quartet prescreen: a primitive quartet
      !! whose prefactor cannot reach this is skipped before the Boys
      !! function. It is a fraction of `thresh`, and a runtime argument
      !! rather than a literal so the fraction can be measured against the
      !! energy it costs instead of guessed once.
      real(dp), intent(in)    :: pcut
      !! Coulomb and exchange scalings. Per call, so they fold into the six
      !! atomic updates and the digestion stays folded -- separating J and K
      !! into two matrices to scale them would give back FOCK6's 22%.
      real(dp), intent(in)    :: jfac, kfac
      real(dp), intent(in)    :: dsh(nbas, nbas)
      integer,  intent(in)    :: sh_l(nbas), ao_off(nbas)
      integer,  intent(in)    :: pp_off(nbas*nbas), pp_n(nbas*nbas)
      real(dp), intent(in)    :: pp_p(npp), pp_r(npp, 3), pp_ra(npp, 3)
      real(dp), intent(in)    :: pp_rb(npp, 3), pp_c(npp)
      !! pp_c with the first column's coefficients folded in: what the
      !! scalar kernel multiplies, so a segmented basis pays nothing.
      real(dp), intent(in)    :: pp_cs(npp)
      integer,  intent(in)    :: ndens
      real(dp), intent(in)    :: dmat(ndens, nao, nao)
      real(dp), intent(inout) :: jmat(ndens, nao, nao)
      integer, intent(in) :: rank, nranks
      integer(int64) :: g0, g1, nr, i
      !
      ! LAUNCH GEOMETRY.  `do concurrent` gives nvfortran the whole say, and it
      ! picks 128 threads per block.  Handing the block size back to the
      ! compiler is the point rather than a compromise: the claim this library
      ! is making is that standard Fortran reaches competitive throughput, and
      ! a tuned launch geometry behind a directive would be quietly conceding
      ! it.  Per-class kernels are what recover the occupancy anyway -- ptxas
      ! budgets registers for one (la,lb,lc,ld) instead of for the worst class.
      !
      ! RANKS.  The work list is sorted, so rank r of n taking every n-th item
      ! from r is a static split that balances by construction, and every
      ! rank walks the same list -- the reduction of the result across ranks
      ! happens in the Fock driver, not here.  One rank is rank 0 of 1.
      g0 = sOff(lo) + 1 + rank
      g1 = sOff(hi + 1)
      nr = 0
      if (g1 >= g0) nr = (g1 - g0)/nranks + 1
      do concurrent(i=1:nr)
         call rasi0101(g0 + (i - 1)*nranks, lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sD, &
                       npair, sp_i, sp_j, sp_q, thresh, pcut, jfac, kfac, dsh, nbas, npp, nao, sh_l, ao_off, &
                       pp_off, pp_n, pp_p, pp_r, pp_ra, pp_rb, pp_c, pp_cs, ndens, dmat, jmat)
      end do
   end subroutine ras0101


   pure subroutine rasi0101(gt, lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sD, &
                      npair, sp_i, sp_j, sp_q, thresh, pcut, jfac, kfac, dsh, nbas, npp, nao, sh_l, ao_off, &
                      pp_off, pp_n, pp_p, pp_r, pp_ra, pp_rb, pp_c, pp_cs, &
                      ndens, dmat, jmat)
      !$acc routine seq
      integer(int64), intent(in) :: gt
      integer,  intent(in)    :: lo, hi, nseg, npair, nbas, npp, nao
      integer(int64), intent(in) :: sOff(nseg + 1)
      integer,  intent(in)    :: sA(nseg), sNB(nseg), sOA(nseg), sOB(nseg)
      logical,  intent(in)    :: sD(nseg)
      integer,  intent(in)    :: sp_i(npair), sp_j(npair)
      real(dp), intent(in)    :: sp_q(npair), thresh
      !! Cutoff for the primitive-quartet prescreen: a primitive quartet
      !! whose prefactor cannot reach this is skipped before the Boys
      !! function. It is a fraction of `thresh`, and a runtime argument
      !! rather than a literal so the fraction can be measured against the
      !! energy it costs instead of guessed once.
      real(dp), intent(in)    :: pcut
      !! Coulomb and exchange scalings. Per call, so they fold into the six
      !! atomic updates and the digestion stays folded -- separating J and K
      !! into two matrices to scale them would give back FOCK6's 22%.
      real(dp), intent(in)    :: jfac, kfac
      real(dp), intent(in)    :: dsh(nbas, nbas)
      integer,  intent(in)    :: sh_l(nbas), ao_off(nbas)
      integer,  intent(in)    :: pp_off(nbas*nbas), pp_n(nbas*nbas)
      real(dp), intent(in)    :: pp_p(npp), pp_r(npp, 3), pp_ra(npp, 3)
      real(dp), intent(in)    :: pp_rb(npp, 3), pp_c(npp)
      !! pp_c with the first column's coefficients folded in: what the
      !! scalar kernel multiplies, so a segmented basis pays nothing.
      real(dp), intent(in)    :: pp_cs(npp)
      integer,  intent(in)    :: ndens
      real(dp), intent(in)    :: dmat(ndens, nao, nao)
      real(dp), intent(inout) :: jmat(ndens, nao, nao)

      integer :: p, q, mid, seg, t, iab, icd, si, sj, sk, sl
      integer(int64) :: nsa, u, kx
      real(dp) :: qcut
      integer :: keyab, keycd, offab, offcd, nab, ncd
      logical :: same_ab, same_cd, same_pair
      logical :: dij, dkl, dpq
      integer :: mui, nuj, lamk, sigl
      integer :: kp, kq, idens, ia, ib, ic, id, idx
      real(dp) :: sc, wq
      real(dp) :: abx, aby, abz, cdx, cdy, cdz, rab, rcd
      real(dp) :: zhx, zhy, zhz, xhx, xhy, xhz, yhx, yhy, yhz
      real(dp) :: wx, wy, wz, wn, dotcz, rot(3, 3)
      real(dp) :: cl1, cl2, cl3, dl1, dl3, Rs, Rc, cy
      real(dp) :: zeta, eta, zpe, alpha, tval, bnd, pref
      real(dp) :: ip, za, zb, zq, iq, yc, yd, ax, az, kabv, kcdv, w, m2a, t1, t2, t3
      real(dp) :: zq2
      real(dp) :: f(0:BOYS_MMAX)
      integer  :: bi, bj, bbase
      real(dp) :: bx, bx2, b0, b1, b2, btt, bet
      real(dp) :: gb(2)
      real(dp) :: sacc(8)
      real(dp) :: kmv(5)
      real(dp) :: racc(12)
      real(dp) :: cmv(7)
      real(dp) :: bn(0:2)
      real(dp) :: bz(3)
      real(dp) :: vbuf(9)
      real(dp) :: jab(3), jcd(3), kac(1)
      real(dp) :: kad(3), kbc(3), kbd(9)
      real(dp) :: dab(3), dcd(3), dac(1)
      real(dp) :: dad(3), dbc(3), dbd(9)

      ! locate the segment
         p = lo; q = hi
         do while (p < q)
            mid = (p + q + 1)/2
            if (sOff(mid) < gt) then
               p = mid
            else
               q = mid - 1
            end if
         end do
         seg = p
         t = int(gt - sOff(seg))

         ! KET-UNIFORM DECODE. The bra pair index runs fastest, so the 32
         ! threads of a warp hold 32 bra pairs against ONE ket pair, and the
         ! loads of the inner primitive loop -- the ket side -- are the same
         ! address across the warp: one L1 transaction, broadcast. With the
         ! ket index fastest, as this was, every thread pulled its own ket
         ! record per primitive quartet and Nsight Compute had (ss|ss) at 96%
         ! of L1 throughput with a 28% hit rate. The bra loads now diverge
         ! instead, once per bra primitive rather than once per quartet.
         ! On a symmetric segment the pairs are enumerated column by column,
         ! iab >= icd, with the same closed form inverted.
         if (sD(seg)) then
            nsa = int(sA(seg), int64)
            u = int(t - 1, int64)
            kx = int((real(2*nsa + 1, dp) - sqrt(real(2*nsa + 1, dp)**2 - 8.0_dp*real(u, dp)))/2.0_dp, int64)
            if (kx < 0) kx = 0
            do while (kx > 0)
               if ((kx*(2*nsa + 1) - kx*kx)/2 <= u) exit
               kx = kx - 1
            end do
            do while (((kx + 1)*(2*nsa + 1) - (kx + 1)*(kx + 1))/2 <= u)
               kx = kx + 1
            end do
            icd = int(kx) + 1
            iab = icd + int(u - (kx*(2*nsa + 1) - kx*kx)/2)
         else
            icd = (t - 1)/sA(seg) + 1
            iab = t - (icd - 1)*sA(seg)
         end if


         ! exact Schwarz, per quartet.  The host bin-pair test is only
         ! decade-granular (`int(-log10 Q)` clamped to 9) and therefore admits
         ! up to two decades too much; at RNA3 that was 46% of all quartets.
         qcut = sp_q(sOA(seg) + iab)*sp_q(sOB(seg) + icd)
         if (qcut <= thresh) return

         si = sp_i(sOA(seg) + iab); sj = sp_j(sOA(seg) + iab)
         sk = sp_i(sOB(seg) + icd); sl = sp_j(sOB(seg) + icd)

         ! Density-weighted screen.  What actually enters the Fock matrix is
         ! Q_ab Q_cd times a density block, so a quartet whose integrals are
         ! above threshold still contributes nothing if every density block it
         ! multiplies is negligible.  The J terms carry a factor 4 from the
         ! Coulomb degeneracy, the K terms 1.  For a converged density on an
         ! extended molecule this is where most of the screening comes from --
         ! with a flat model density it correctly fires on nothing.
         if (qcut*max(4.0_dp*dsh(si, sj), 4.0_dp*dsh(sk, sl), &
                      dsh(si, sk), dsh(si, sl), &
                      dsh(sj, sk), dsh(sj, sl)) <= thresh) return

         same_ab = (si == sj); same_cd = (sk == sl)
         same_pair = sD(seg) .and. (iab == icd)


         keyab = (si - 1)*nbas + sj
         keycd = (sk - 1)*nbas + sl
         offab = pp_off(keyab); nab = pp_n(keyab)
         offcd = pp_off(keycd); ncd = pp_n(keycd)

         ! === the frame (FRAME.md section 1) ===
         ! ab = B - A, the bra pair's own direction; z falls back to the lab
         ! axis when A == B (rab = 0), which happens whenever two shells on
         ! the same atom are paired -- routine, not rare.
         abx = pp_rb(offcd + 1, 1) - pp_ra(offcd + 1, 1)
         aby = pp_rb(offcd + 1, 2) - pp_ra(offcd + 1, 2)
         abz = pp_rb(offcd + 1, 3) - pp_ra(offcd + 1, 3)
         rab = sqrt(abx*abx + aby*aby + abz*abz)
         if (rab > 0.0_dp) then
            zhx = abx/rab; zhy = aby/rab; zhz = abz/rab
         else
            zhx = 0.0_dp; zhy = 0.0_dp; zhz = 1.0_dp
         end if
         cdx = pp_rb(offab + 1, 1) - pp_ra(offab + 1, 1)
         cdy = pp_rb(offab + 1, 2) - pp_ra(offab + 1, 2)
         cdz = pp_rb(offab + 1, 3) - pp_ra(offab + 1, 3)
         rcd = sqrt(cdx*cdx + cdy*cdy + cdz*cdz)
         ! x spans what of CD is perpendicular to z; falls back to the lab
         ! axis least aligned with z when CD is parallel to AB (or C == D,
         ! another same-atom case rather than a rare one) -- FRAME.md's
         ! 1e-12*max(rcd,1) threshold, taken from libfint verbatim.
         dotcz = cdx*zhx + cdy*zhy + cdz*zhz
         wx = cdx - dotcz*zhx; wy = cdy - dotcz*zhy; wz = cdz - dotcz*zhz
         wn = sqrt(wx*wx + wy*wy + wz*wz)
         if (wn > 1.0e-12_dp*max(rcd, 1.0_dp)) then
            xhx = wx/wn; xhy = wy/wn; xhz = wz/wn
         else
            ! z is a unit vector, so at least one lab axis has |component|
            ! <= 1/sqrt(3); projecting z out of THAT axis is never zero, so
            ! this branch's own division needs no further check (FRAME.md).
            if (abs(zhx) <= abs(zhy) .and. abs(zhx) <= abs(zhz)) then
               wx = 1.0_dp - zhx*zhx; wy = -zhx*zhy; wz = -zhx*zhz
            else if (abs(zhy) <= abs(zhz)) then
               wx = -zhy*zhx; wy = 1.0_dp - zhy*zhy; wz = -zhy*zhz
            else
               wx = -zhz*zhx; wy = -zhz*zhy; wz = 1.0_dp - zhz*zhz
            end if
            wn = sqrt(wx*wx + wy*wy + wz*wz)
            xhx = wx/wn; xhy = wy/wn; xhz = wz/wn
         end if
         yhx = zhy*xhz - zhz*xhy
         yhy = zhz*xhx - zhx*xhz
         yhz = zhx*xhy - zhy*xhx
         ! rot's COLUMNS are the local axes in lab coordinates (FRAME.md
         ! section 1); section 5 rotates each `p` slot back with it.
         rot(1,1) = xhx; rot(2,1) = xhy; rot(3,1) = xhz
         rot(1,2) = yhx; rot(2,2) = yhy; rot(3,2) = yhz
         rot(1,3) = zhx; rot(2,3) = zhy; rot(3,3) = zhz
         cl1 = xhx*(pp_ra(offab + 1, 1) - pp_ra(offcd + 1, 1)) &
             + xhy*(pp_ra(offab + 1, 2) - pp_ra(offcd + 1, 2)) &
             + xhz*(pp_ra(offab + 1, 3) - pp_ra(offcd + 1, 3))
         cl2 = yhx*(pp_ra(offab + 1, 1) - pp_ra(offcd + 1, 1)) &
             + yhy*(pp_ra(offab + 1, 2) - pp_ra(offcd + 1, 2)) &
             + yhz*(pp_ra(offab + 1, 3) - pp_ra(offcd + 1, 3))
         cl3 = zhx*(pp_ra(offab + 1, 1) - pp_ra(offcd + 1, 1)) &
             + zhy*(pp_ra(offab + 1, 2) - pp_ra(offcd + 1, 2)) &
             + zhz*(pp_ra(offab + 1, 3) - pp_ra(offcd + 1, 3))
         dl1 = xhx*(pp_rb(offab + 1, 1) - pp_ra(offcd + 1, 1)) &
             + xhy*(pp_rb(offab + 1, 2) - pp_ra(offcd + 1, 2)) &
             + xhz*(pp_rb(offab + 1, 3) - pp_ra(offcd + 1, 3))
         dl3 = zhx*(pp_rb(offab + 1, 1) - pp_ra(offcd + 1, 1)) &
             + zhy*(pp_rb(offab + 1, 2) - pp_ra(offcd + 1, 2)) &
             + zhz*(pp_rb(offab + 1, 3) - pp_ra(offcd + 1, 3))
         Rs = dl1 - cl1
         Rc = dl3 - cl3
         cy = cl2


         ! === per-quartet integral core (FRAME.md sections 2-4, 10) ===
         !
         ! Derivation's ket outside, bra inside (README_TERCO.md section
         ! 2.4): the level-1 accumulators below are per DERIVATION-BRA
         ! primitive (kq) and do not depend on which Cartesian component is
         ! being built, so putting that loop innermost is what keeps a
         ! (pp|pp) inner loop to a few dozen multiply-adds -- the same order
         ! libfint's own rotaxis emitter uses (scripts/rotaxis_mmd/emit.py:
         ! emit_kernel). `ket_inner` picks which PHYSICAL pair plays the
         ! derivation's bra vs ket role (FRAME.md section 10); the role
         ! structure itself (bra always inner) never changes.
         !
         racc(1) = 0.0_dp
         racc(2) = 0.0_dp
         racc(3) = 0.0_dp
         racc(4) = 0.0_dp
         racc(5) = 0.0_dp
         racc(6) = 0.0_dp
         racc(7) = 0.0_dp
         racc(8) = 0.0_dp
         racc(9) = 0.0_dp
         racc(10) = 0.0_dp
         racc(11) = 0.0_dp
         racc(12) = 0.0_dp
         do kp = offab + 1, offab + nab
            zeta = pp_p(kp)
            ! PRIMITIVE-QUARTET PRESCREEN, adapted from the HGP kernel's `bnd`
            ! bound: the pair lists are sorted by |c|/p descending
            ! (build_pairs_hgp), so `bnd` bounds every remaining inner-loop
            ! primitive using THIS outer primitive's weight, testing it
            ! against the best inner primitive (offcd + 1) before entering
            ! that loop at all, then EXITing it the first time a weaker one
            ! fails -- the same two-part test the HGP kernel runs, on
            ! whichever physical pair is outer here.
            bnd = TWO_PI_2_5*abs(pp_cs(kp))/(zeta*sqrt(zeta))
            if (bnd*abs(pp_cs(offcd + 1))/pp_p(offcd + 1) <= pcut) cycle
            iq = 0.5_dp/zeta
            ! yc, yd = c/q, d/q (FRAME.md section 3) are recovered by
            ! projecting the derivation-ket pair centre onto its own
            ! separation, since terco's pp_p carries only q = c + d, not c
            ! and d separately. That ratio is 0/0 when the two ket-role
            ! centres coincide (routine for two shells on one atom); yd is
            ! then set to an arbitrary finite value instead, provably safe
            ! because FRAME.md section 0's derivation shows every term
            ! carrying a yc or yd power also carries a matching Rs or Rc
            ! power from the SAME Hermite coefficient (introduced only
            ! together), and Rs = Rc = 0 exactly in that degenerate case --
            ! so the term vanishes via the constant factor regardless of
            ! what yd is, PROVIDED yd is finite: 0.0*NaN is NaN, and the
            ! whole point of this branch is to keep that finite.
            if (rcd > 0.0_dp) then
               yd = sqrt((pp_r(kp,1) - pp_ra(kp,1))**2 + (pp_r(kp,2) - pp_ra(kp,2))**2 &
                       + (pp_r(kp,3) - pp_ra(kp,3))**2)/rcd
            else
               yd = 0.5_dp
            end if
            yc = 1.0_dp - yd
            ax = cl1 + yd*Rs
            az = cl3 + yd*Rc
            kcdv = TWO_PI_2_5*pp_cs(kp)/zeta
            sacc(1) = 0.0_dp
            sacc(2) = 0.0_dp
            sacc(3) = 0.0_dp
            sacc(4) = 0.0_dp
            sacc(5) = 0.0_dp
            sacc(6) = 0.0_dp
            sacc(7) = 0.0_dp
            sacc(8) = 0.0_dp
            do kq = offcd + 1, offcd + ncd
               eta = pp_p(kq)
               if (bnd*abs(pp_cs(kq))/eta <= pcut) exit
               zpe = zeta + eta
               ! The exact (ss|ss)-type bound: bit-for-bit the HGP kernel's
               ! own `pref`, since kab*kcd*B_0 regroups to the identical
               ! product (FRAME.md section 4) -- same cutoff, same meaning,
               ! and symmetric in zeta/eta so unaffected by which is outer.
               pref = TWO_PI_2_5/(zeta*eta*sqrt(zpe))*pp_cs(kp)*pp_cs(kq)
               if (abs(pref) <= pcut) cycle
               ip = 0.5_dp/eta
               za = zhx*(pp_r(kq,1) - pp_ra(kq,1)) + zhy*(pp_r(kq,2) - pp_ra(kq,2)) &
                  + zhz*(pp_r(kq,3) - pp_ra(kq,3))
               zb = za - rab
               zq = za - az
               alpha = zeta*eta/zpe
               tval = alpha*(ax*ax + cy*cy + zq*zq)

                  if (tval >= BOYS_TMAX) then
                  btt = 1.0_dp/tval
                  f(0) = 0.88622692545275801365_dp*sqrt(btt)
                  bet = 0.0_dp
                  f(1) = 1.0_dp*f(0)*(0.5_dp*btt)
                  f(2) = 3.0_dp*f(1)*(0.5_dp*btt)
               else
                  bi = int(tval*BOYS_DTINV)
                  bi = min(bi, BOYS_NGRID - 1)
                  bx = 2.0_dp*(tval - real(bi, dp)*BOYS_DT)*BOYS_DTINV - 1.0_dp
                  bx2 = 2.0_dp*bx
                  bbase = bi*(BOYS_MMAX + 1)*(BOYS_NCHEB + 1)
                  bj = bbase + 2*(BOYS_NCHEB + 1)
                  b1 = boys_table(bj + BOYS_NCHEB + 1)
                  b2 = 0.0_dp
                  b0 = bx2*b1 - b2 + boys_table(bj + 5); b2 = b1; b1 = b0
                  b0 = bx2*b1 - b2 + boys_table(bj + 4); b2 = b1; b1 = b0
                  b0 = bx2*b1 - b2 + boys_table(bj + 3); b2 = b1; b1 = b0
                  b0 = bx2*b1 - b2 + boys_table(bj + 2); b2 = b1; b1 = b0
                  f(2) = bx*b1 - b2 + boys_table(bj + 1)
                  bet = exp(-tval)
                  btt = 2.0_dp*tval
                  f(1) = (btt*f(2) + bet)*(0.3333333333333333_dp)
                  f(0) = (btt*f(1) + bet)*(1.0_dp)
               end if

               ! kabv is folded into the Boys ladder's overall scale HERE,
               ! once per derivation-bra primitive, rather than multiplied
               ! into every one of the 8 level-1 accumulators below
               ! (coordinator review item 2): bn(n) = kabv * (-2 alpha)^n
               ! F_n(T) / sqrt(zpe) is exactly kabv*B_n, so every
               ! accumulation that used to read "kabv*...*bn(n)..." now
               ! reads "...*bn(n)..." for the identical value.
               kabv = pp_cs(kq)/eta
               w = kabv/sqrt(zpe)
               bn(0) = w*f(0)
               m2a = -2.0_dp*alpha
               w = w*m2a
               bn(1) = w*f(1)
               w = w*m2a
               bn(2) = w*f(2)
               zq2 = zq*zq
               bz(1) = bn(1)*zq
               bz(2) = bn(2)*zq
               bz(3) = bn(2)*zq2
               gb(1) = ip
               gb(2) = zb
               sacc(1) = sacc(1) + gb(1)*bn(1)
               sacc(2) = sacc(2) + gb(1)*bn(2)
               sacc(3) = sacc(3) + gb(2)*bn(0)
               sacc(4) = sacc(4) + gb(1)*bz(1)
               sacc(5) = sacc(5) + gb(2)*bn(1)
               sacc(6) = sacc(6) + gb(1)*bz(2)
               sacc(7) = sacc(7) + gb(2)*bz(1)
               sacc(8) = sacc(8) + gb(1)*bz(3)
            end do   ! kq (derivation-bra primitive)

            kmv(1) = kcdv*yc*ax
            kmv(2) = kcdv*iq*ax*ax
            kmv(3) = kcdv*iq
            kmv(4) = kcdv*yc
            kmv(5) = kcdv*iq*ax
            racc(1) = racc(1) + kmv(1)*sacc(1)
            racc(2) = racc(2) + kmv(2)*sacc(2) + kmv(3)*sacc(1)
            racc(3) = racc(3) + kmv(4)*sacc(1)
            racc(4) = racc(4) + kmv(5)*sacc(2)
            racc(5) = racc(5) + kmv(4)*(sacc(3) + sacc(4))
            racc(6) = racc(6) + kmv(5)*(sacc(5) + sacc(6))
            racc(7) = racc(7) + kmv(3)*sacc(1)
            racc(8) = racc(8) + kmv(3)*sacc(2)
            racc(9) = racc(9) + kmv(3)*(sacc(5) + sacc(6))
            racc(10) = racc(10) + kmv(5)*sacc(6)
            racc(11) = racc(11) + kmv(3)*sacc(6)
            racc(12) = racc(12) + kmv(3)*(sacc(1) + sacc(7) + sacc(8))
         end do   ! kp (derivation-ket primitive)

         ! === quartet assembly, straight into vbuf (level 3) ===
         ! comp_i's target vbuf slot is relabelled at generation time
         ! (component_vbuf_map, FRAME.md section 10) -- no runtime permutation.
         cmv(1) = Rs
         cmv(2) = 1.0_dp
         cmv(3) = Rs*cy
         cmv(4) = cy
         cmv(5) = cy*cy
         cmv(6) = Rc
         cmv(7) = Rc*cy
            vbuf(1) = cmv(1)*racc(1) - racc(2)
            vbuf(4) = cmv(3)*racc(3) - cmv(4)*racc(4)
            vbuf(7) = -cmv(1)*racc(5) + racc(6)
            vbuf(2) = -cmv(4)*racc(4)
            vbuf(5) = -racc(7) - cmv(5)*racc(8)
            vbuf(8) = cmv(4)*racc(9)
            vbuf(3) = racc(10) + cmv(6)*racc(1)
            vbuf(6) = cmv(4)*racc(11) + cmv(7)*racc(3)
            vbuf(9) = -racc(12) - cmv(6)*racc(5)

         ! === rotate every p slot back to the lab frame (FRAME.md section 5) ===
         t1 = vbuf(1); t2 = vbuf(2); t3 = vbuf(3)
         vbuf(1) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(2) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(3) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3
         t1 = vbuf(4); t2 = vbuf(5); t3 = vbuf(6)
         vbuf(4) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(5) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(6) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3
         t1 = vbuf(7); t2 = vbuf(8); t3 = vbuf(9)
         vbuf(7) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(8) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(9) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3
         t1 = vbuf(1); t2 = vbuf(4); t3 = vbuf(7)
         vbuf(1) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(4) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(7) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3
         t1 = vbuf(2); t2 = vbuf(5); t3 = vbuf(8)
         vbuf(2) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(5) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(8) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3
         t1 = vbuf(3); t2 = vbuf(6); t3 = vbuf(9)
         vbuf(3) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(6) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(9) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3

         ! Single column on every side: the canonical enumeration and the
         ! degeneracy weights are the pair-level ones.
         dij = .not. same_ab
         dkl = .not. same_cd
         dpq = .not. same_pair
         mui = ao_off(si); nuj = ao_off(sj); lamk = ao_off(sk); sigl = ao_off(sl)


#ifdef TRC_NO_DIGEST
         !
         ! Evaluation only, for like-for-like comparison against published
         ! numbers that were measured with digestion removed (the libERI paper
         ! edits QUICK's source to strip it, so its Tables 2 and 3 are ERI
         ! evaluation alone).  Every integral is still formed -- the whole VRR
         ! and HRR run and every component of vbuf is read, so nothing is
         ! dead-code eliminated -- but the density loads and the atomic
         ! scatters into the Fock matrix are gone.  The guard is opaque to the
         ! compiler and never fires, so jmat is untouched and the ANSWER IS
         ! DELIBERATELY WRONG.  Timing only.
         !
         sc = 0.0_dp
         do idx = 1, 9
            sc = sc + vbuf(idx)
         end do
         if (sc == huge(1.0_dp)) jmat(1, 1, 1) = sc
#else
         !
         ! BLOCK-ACCUMULATED DIGESTION.
         !
         ! The previous form did six atomic updates and six scattered `dmat`
         ! loads PER CARTESIAN COMPONENT.  For (pp|pp) that is 81 components x
         ! 6 = 486 of each, per quartet, even though only six small BLOCKS of
         ! jmat and six of dmat are ever touched.
         !
         ! gpu4pyscf's rys_contract_jk.cu does it the other way round: pull the
         ! density blocks into registers once (`load_dm`), contract every
         ! component against them there (`dot_dm`), and write each output block
         ! out once.  Same arithmetic, an order of magnitude less traffic --
         ! 54 loads and 54 atomics for (pp|pp) instead of 486.
         !
         ! The degeneracy factors are per-quartet, so they collapse into one
         ! scalar applied as the components are consumed.
         !
         wq = 1.0_dp
         if (.not. dij) wq = wq*0.5_dp
         if (.not. dkl) wq = wq*0.5_dp
         if (.not. dpq) wq = wq*0.5_dp

         !
         ! BATCHED OVER DENSITIES.
         !
         ! The integral is formed once, in `vbuf`, and contracted against every
         ! density in the batch. In the coupled-perturbed equations that is the
         ! difference between one integral pass and a hundred: the dynamic
         ! polarizabilities need nine perturbations times twelve imaginary
         ! frequencies, each a Fock build on a different response density.
         !
         ! The density loop is OUTSIDE the block accumulators, not inside, and
         ! that is the whole trick. The six blocks are zeroed, filled and
         ! written per density, so REGISTER PRESSURE DOES NOT GROW WITH THE
         ! BATCH -- holding N sets of blocks at once would have cost 54 more
         ! doubles per density at (pp|pp) and 216 at (dd|dd), on a kernel
         ! already spilling. Cost is `eval + ndens*digest`, and the ceiling is
         ! one over the digestion fraction.
         !
         do idens = 1, ndens

         do ib = 0, 2
            do ia = 0, 0
               dab(1 + ia + 1*ib) = dmat(idens, mui + ia, nuj + ib)
               jab(1 + ia + 1*ib) = 0.0_dp
            end do
         end do
         do id = 0, 2
            do ic = 0, 0
               dcd(1 + ic + 1*id) = dmat(idens, lamk + ic, sigl + id)
               jcd(1 + ic + 1*id) = 0.0_dp
            end do
         end do
         do ic = 0, 0
            do ia = 0, 0
               dac(1 + ia + 1*ic) = dmat(idens, mui + ia, lamk + ic)
               kac(1 + ia + 1*ic) = 0.0_dp
            end do
         end do
         do id = 0, 2
            do ia = 0, 0
               dad(1 + ia + 1*id) = dmat(idens, mui + ia, sigl + id)
               kad(1 + ia + 1*id) = 0.0_dp
            end do
         end do
         do ic = 0, 0
            do ib = 0, 2
               dbc(1 + ib + 3*ic) = dmat(idens, nuj + ib, lamk + ic)
               kbc(1 + ib + 3*ic) = 0.0_dp
            end do
         end do
         do id = 0, 2
            do ib = 0, 2
               dbd(1 + ib + 3*id) = dmat(idens, nuj + ib, sigl + id)
               kbd(1 + ib + 3*id) = 0.0_dp
            end do
         end do

         idx = 0
         do id = 0, 2
         do ic = 0, 0
         do ib = 0, 2
         do ia = 0, 0
            idx = idx + 1
            sc = wq*vbuf(idx)
            jab(1 + ia + 1*ib) = jab(1 + ia + 1*ib) &
                                    + 4.0_dp*jfac*sc*dcd(1 + ic + 1*id)
            jcd(1 + ic + 1*id) = jcd(1 + ic + 1*id) &
                                    + 4.0_dp*jfac*sc*dab(1 + ia + 1*ib)
            kac(1 + ia + 1*ic) = kac(1 + ia + 1*ic) &
                                    - kfac*sc*dbd(1 + ib + 3*id)
            kad(1 + ia + 1*id) = kad(1 + ia + 1*id) &
                                    - kfac*sc*dbc(1 + ib + 3*ic)
            kbc(1 + ib + 3*ic) = kbc(1 + ib + 3*ic) &
                                    - kfac*sc*dad(1 + ia + 1*id)
            kbd(1 + ib + 3*id) = kbd(1 + ib + 3*id) &
                                    - kfac*sc*dac(1 + ia + 1*ic)
         end do
         end do
         end do
         end do

         do ib = 0, 2
            do ia = 0, 0
               !$acc atomic update
               jmat(idens, mui + ia, nuj + ib) = jmat(idens, mui + ia, nuj + ib) &
                                          + jab(1 + ia + 1*ib)
            end do
         end do
         do id = 0, 2
            do ic = 0, 0
               !$acc atomic update
               jmat(idens, lamk + ic, sigl + id) = jmat(idens, lamk + ic, sigl + id) &
                                            + jcd(1 + ic + 1*id)
            end do
         end do
         do ic = 0, 0
            do ia = 0, 0
               !$acc atomic update
               jmat(idens, mui + ia, lamk + ic) = jmat(idens, mui + ia, lamk + ic) &
                                           + kac(1 + ia + 1*ic)
            end do
         end do
         do id = 0, 2
            do ia = 0, 0
               !$acc atomic update
               jmat(idens, mui + ia, sigl + id) = jmat(idens, mui + ia, sigl + id) &
                                           + kad(1 + ia + 1*id)
            end do
         end do
         do ic = 0, 0
            do ib = 0, 2
               !$acc atomic update
               jmat(idens, nuj + ib, lamk + ic) = jmat(idens, nuj + ib, lamk + ic) &
                                           + kbc(1 + ib + 3*ic)
            end do
         end do
         do id = 0, 2
            do ib = 0, 2
               !$acc atomic update
               jmat(idens, nuj + ib, sigl + id) = jmat(idens, nuj + ib, sigl + id) &
                                           + kbd(1 + ib + 3*id)
            end do
         end do

         end do   ! idens
#endif

   end subroutine rasi0101
