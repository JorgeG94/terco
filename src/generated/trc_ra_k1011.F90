   pure subroutine rasi1011(gt, lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sD, &
                      npair, sp_i, sp_j, sp_q, thresh, pcut, jfac, kfac, dsh, nbas, npp, nao, sh_l, ao_off, &
                      pp_off, pp_n, pp_p, pp_r, pp_ra, pp_rb, pp_c, pp_cs, &
                      ndens, dmat, jmat)
      !$acc routine seq
      integer(int64), intent(in) :: gt
      integer,  intent(in)    :: lo, hi, nseg, npair, nbas, npp, nao
      integer(int64), intent(in) :: sOff(nseg + 1)
      integer,  intent(in)    :: sA(nseg), sNB(nseg), sOA(nseg), sOB(nseg)
      logical,  intent(in)    :: sD(nseg)
      integer,  intent(in)    :: sp_i(npair), sp_j(npair)
      real(dp), intent(in)    :: sp_q(npair), thresh
      !! Cutoff for the primitive-quartet prescreen: a primitive quartet
      !! whose prefactor cannot reach this is skipped before the Boys
      !! function. It is a fraction of `thresh`, and a runtime argument
      !! rather than a literal so the fraction can be measured against the
      !! energy it costs instead of guessed once.
      real(dp), intent(in)    :: pcut
      !! Coulomb and exchange scalings. Per call, so they fold into the six
      !! atomic updates and the digestion stays folded -- separating J and K
      !! into two matrices to scale them would give back FOCK6's 22%.
      real(dp), intent(in)    :: jfac, kfac
      real(dp), intent(in)    :: dsh(nbas, nbas)
      integer,  intent(in)    :: sh_l(nbas), ao_off(nbas)
      integer,  intent(in)    :: pp_off(nbas*nbas), pp_n(nbas*nbas)
      real(dp), intent(in)    :: pp_p(npp), pp_r(npp, 3), pp_ra(npp, 3)
      real(dp), intent(in)    :: pp_rb(npp, 3), pp_c(npp)
      !! pp_c with the first column's coefficients folded in: what the
      !! scalar kernel multiplies, so a segmented basis pays nothing.
      real(dp), intent(in)    :: pp_cs(npp)
      integer,  intent(in)    :: ndens
      real(dp), intent(in)    :: dmat(ndens, nao, nao)
      real(dp), intent(inout) :: jmat(ndens, nao, nao)

      integer :: p, q, mid, seg, t, iab, icd, si, sj, sk, sl
      integer(int64) :: nsa, u, kx
      real(dp) :: qcut
      integer :: keyab, keycd, offab, offcd, nab, ncd
      logical :: same_ab, same_cd, same_pair
      logical :: dij, dkl, dpq
      integer :: mui, nuj, lamk, sigl
      integer :: kp, kq, idens, ia, ib, ic, id, idx
      real(dp) :: sc, wq
      real(dp) :: abx, aby, abz, cdx, cdy, cdz, rab, rcd
      real(dp) :: zhx, zhy, zhz, xhx, xhy, xhz, yhx, yhy, yhz
      real(dp) :: wx, wy, wz, wn, dotcz, rot(3, 3)
      real(dp) :: cl1, cl2, cl3, dl1, dl3, Rs, Rc, cy
      real(dp) :: zeta, eta, zpe, alpha, tval, bnd, pref
      real(dp) :: ip, za, zb, zq, iq, yc, yd, ax, az, kabv, kcdv, w, m2a, t1, t2, t3
      real(dp) :: zq2, zq3
      real(dp) :: f(0:BOYS_MMAX)
      integer  :: bi, bj, bbase
      real(dp) :: bx, bx2, b0, b1, b2, btt, bet
      real(dp) :: gb(2)
      real(dp) :: sacc(15)
      real(dp) :: kmv(14)
      real(dp) :: racc(48)
      real(dp) :: cmv(16)
      real(dp) :: bn(0:3)
      real(dp) :: bz(6)
      real(dp) :: vbuf(27)
      real(dp) :: jab(3), jcd(9), kac(9)
      real(dp) :: kad(9), kbc(3), kbd(3)
      real(dp) :: dab(3), dcd(9), dac(9)
      real(dp) :: dad(9), dbc(3), dbd(3)

      ! locate the segment
         p = lo; q = hi
         do while (p < q)
            mid = (p + q + 1)/2
            if (sOff(mid) < gt) then
               p = mid
            else
               q = mid - 1
            end if
         end do
         seg = p
         t = int(gt - sOff(seg))

         ! KET-UNIFORM DECODE. The bra pair index runs fastest, so the 32
         ! threads of a warp hold 32 bra pairs against ONE ket pair, and the
         ! loads of the inner primitive loop -- the ket side -- are the same
         ! address across the warp: one L1 transaction, broadcast. With the
         ! ket index fastest, as this was, every thread pulled its own ket
         ! record per primitive quartet and Nsight Compute had (ss|ss) at 96%
         ! of L1 throughput with a 28% hit rate. The bra loads now diverge
         ! instead, once per bra primitive rather than once per quartet.
         ! On a symmetric segment the pairs are enumerated column by column,
         ! iab >= icd, with the same closed form inverted.
         if (sD(seg)) then
            nsa = int(sA(seg), int64)
            u = int(t - 1, int64)
            kx = int((real(2*nsa + 1, dp) - sqrt(real(2*nsa + 1, dp)**2 - 8.0_dp*real(u, dp)))/2.0_dp, int64)
            if (kx < 0) kx = 0
            do while (kx > 0)
               if ((kx*(2*nsa + 1) - kx*kx)/2 <= u) exit
               kx = kx - 1
            end do
            do while (((kx + 1)*(2*nsa + 1) - (kx + 1)*(kx + 1))/2 <= u)
               kx = kx + 1
            end do
            icd = int(kx) + 1
            iab = icd + int(u - (kx*(2*nsa + 1) - kx*kx)/2)
         else
            icd = (t - 1)/sA(seg) + 1
            iab = t - (icd - 1)*sA(seg)
         end if


         ! exact Schwarz, per quartet.  The host bin-pair test is only
         ! decade-granular (`int(-log10 Q)` clamped to 9) and therefore admits
         ! up to two decades too much; at RNA3 that was 46% of all quartets.
         qcut = sp_q(sOA(seg) + iab)*sp_q(sOB(seg) + icd)
         if (qcut <= thresh) return

         si = sp_i(sOA(seg) + iab); sj = sp_j(sOA(seg) + iab)
         sk = sp_i(sOB(seg) + icd); sl = sp_j(sOB(seg) + icd)

         ! Density-weighted screen.  What actually enters the Fock matrix is
         ! Q_ab Q_cd times a density block, so a quartet whose integrals are
         ! above threshold still contributes nothing if every density block it
         ! multiplies is negligible.  The J terms carry a factor 4 from the
         ! Coulomb degeneracy, the K terms 1.  For a converged density on an
         ! extended molecule this is where most of the screening comes from --
         ! with a flat model density it correctly fires on nothing.
         if (qcut*max(4.0_dp*dsh(si, sj), 4.0_dp*dsh(sk, sl), &
                      dsh(si, sk), dsh(si, sl), &
                      dsh(sj, sk), dsh(sj, sl)) <= thresh) return

         same_ab = (si == sj); same_cd = (sk == sl)
         same_pair = sD(seg) .and. (iab == icd)


         keyab = (si - 1)*nbas + sj
         keycd = (sk - 1)*nbas + sl
         offab = pp_off(keyab); nab = pp_n(keyab)
         offcd = pp_off(keycd); ncd = pp_n(keycd)

         ! === the frame (FRAME.md section 1) ===
         ! ab = B - A, the bra pair's own direction; z falls back to the lab
         ! axis when A == B (rab = 0), which happens whenever two shells on
         ! the same atom are paired -- routine, not rare.
         abx = pp_rb(offab + 1, 1) - pp_ra(offab + 1, 1)
         aby = pp_rb(offab + 1, 2) - pp_ra(offab + 1, 2)
         abz = pp_rb(offab + 1, 3) - pp_ra(offab + 1, 3)
         rab = sqrt(abx*abx + aby*aby + abz*abz)
         if (rab > 0.0_dp) then
            zhx = abx/rab; zhy = aby/rab; zhz = abz/rab
         else
            zhx = 0.0_dp; zhy = 0.0_dp; zhz = 1.0_dp
         end if
         cdx = pp_rb(offcd + 1, 1) - pp_ra(offcd + 1, 1)
         cdy = pp_rb(offcd + 1, 2) - pp_ra(offcd + 1, 2)
         cdz = pp_rb(offcd + 1, 3) - pp_ra(offcd + 1, 3)
         rcd = sqrt(cdx*cdx + cdy*cdy + cdz*cdz)
         ! x spans what of CD is perpendicular to z; falls back to the lab
         ! axis least aligned with z when CD is parallel to AB (or C == D,
         ! another same-atom case rather than a rare one) -- FRAME.md's
         ! 1e-12*max(rcd,1) threshold, taken from libfint verbatim.
         dotcz = cdx*zhx + cdy*zhy + cdz*zhz
         wx = cdx - dotcz*zhx; wy = cdy - dotcz*zhy; wz = cdz - dotcz*zhz
         wn = sqrt(wx*wx + wy*wy + wz*wz)
         if (wn > 1.0e-12_dp*max(rcd, 1.0_dp)) then
            xhx = wx/wn; xhy = wy/wn; xhz = wz/wn
         else
            ! z is a unit vector, so at least one lab axis has |component|
            ! <= 1/sqrt(3); projecting z out of THAT axis is never zero, so
            ! this branch's own division needs no further check (FRAME.md).
            if (abs(zhx) <= abs(zhy) .and. abs(zhx) <= abs(zhz)) then
               wx = 1.0_dp - zhx*zhx; wy = -zhx*zhy; wz = -zhx*zhz
            else if (abs(zhy) <= abs(zhz)) then
               wx = -zhy*zhx; wy = 1.0_dp - zhy*zhy; wz = -zhy*zhz
            else
               wx = -zhz*zhx; wy = -zhz*zhy; wz = 1.0_dp - zhz*zhz
            end if
            wn = sqrt(wx*wx + wy*wy + wz*wz)
            xhx = wx/wn; xhy = wy/wn; xhz = wz/wn
         end if
         yhx = zhy*xhz - zhz*xhy
         yhy = zhz*xhx - zhx*xhz
         yhz = zhx*xhy - zhy*xhx
         ! rot's COLUMNS are the local axes in lab coordinates (FRAME.md
         ! section 1); section 5 rotates each `p` slot back with it.
         rot(1,1) = xhx; rot(2,1) = xhy; rot(3,1) = xhz
         rot(1,2) = yhx; rot(2,2) = yhy; rot(3,2) = yhz
         rot(1,3) = zhx; rot(2,3) = zhy; rot(3,3) = zhz
         cl1 = xhx*(pp_ra(offcd + 1, 1) - pp_ra(offab + 1, 1)) &
             + xhy*(pp_ra(offcd + 1, 2) - pp_ra(offab + 1, 2)) &
             + xhz*(pp_ra(offcd + 1, 3) - pp_ra(offab + 1, 3))
         cl2 = yhx*(pp_ra(offcd + 1, 1) - pp_ra(offab + 1, 1)) &
             + yhy*(pp_ra(offcd + 1, 2) - pp_ra(offab + 1, 2)) &
             + yhz*(pp_ra(offcd + 1, 3) - pp_ra(offab + 1, 3))
         cl3 = zhx*(pp_ra(offcd + 1, 1) - pp_ra(offab + 1, 1)) &
             + zhy*(pp_ra(offcd + 1, 2) - pp_ra(offab + 1, 2)) &
             + zhz*(pp_ra(offcd + 1, 3) - pp_ra(offab + 1, 3))
         dl1 = xhx*(pp_rb(offcd + 1, 1) - pp_ra(offab + 1, 1)) &
             + xhy*(pp_rb(offcd + 1, 2) - pp_ra(offab + 1, 2)) &
             + xhz*(pp_rb(offcd + 1, 3) - pp_ra(offab + 1, 3))
         dl3 = zhx*(pp_rb(offcd + 1, 1) - pp_ra(offab + 1, 1)) &
             + zhy*(pp_rb(offcd + 1, 2) - pp_ra(offab + 1, 2)) &
             + zhz*(pp_rb(offcd + 1, 3) - pp_ra(offab + 1, 3))
         Rs = dl1 - cl1
         Rc = dl3 - cl3
         cy = cl2


         ! === per-quartet integral core (FRAME.md sections 2-4) ===
         !
         ! Ket outside, bra inside (README_TERCO.md section 2.4): the level-1
         ! accumulators below are per BRA primitive and do not depend on which
         ! Cartesian component is being built, so putting the bra loop
         ! innermost is what keeps a (pp|pp) inner loop to a few dozen
         ! multiply-adds. This is the SAME order libfint's own rotaxis
         ! emitter uses (scripts/rotaxis_mmd/emit.py:emit_kernel).
         !
         racc(1) = 0.0_dp
         racc(2) = 0.0_dp
         racc(3) = 0.0_dp
         racc(4) = 0.0_dp
         racc(5) = 0.0_dp
         racc(6) = 0.0_dp
         racc(7) = 0.0_dp
         racc(8) = 0.0_dp
         racc(9) = 0.0_dp
         racc(10) = 0.0_dp
         racc(11) = 0.0_dp
         racc(12) = 0.0_dp
         racc(13) = 0.0_dp
         racc(14) = 0.0_dp
         racc(15) = 0.0_dp
         racc(16) = 0.0_dp
         racc(17) = 0.0_dp
         racc(18) = 0.0_dp
         racc(19) = 0.0_dp
         racc(20) = 0.0_dp
         racc(21) = 0.0_dp
         racc(22) = 0.0_dp
         racc(23) = 0.0_dp
         racc(24) = 0.0_dp
         racc(25) = 0.0_dp
         racc(26) = 0.0_dp
         racc(27) = 0.0_dp
         racc(28) = 0.0_dp
         racc(29) = 0.0_dp
         racc(30) = 0.0_dp
         racc(31) = 0.0_dp
         racc(32) = 0.0_dp
         racc(33) = 0.0_dp
         racc(34) = 0.0_dp
         racc(35) = 0.0_dp
         racc(36) = 0.0_dp
         racc(37) = 0.0_dp
         racc(38) = 0.0_dp
         racc(39) = 0.0_dp
         racc(40) = 0.0_dp
         racc(41) = 0.0_dp
         racc(42) = 0.0_dp
         racc(43) = 0.0_dp
         racc(44) = 0.0_dp
         racc(45) = 0.0_dp
         racc(46) = 0.0_dp
         racc(47) = 0.0_dp
         racc(48) = 0.0_dp
         do kq = offcd + 1, offcd + ncd
            eta = pp_p(kq)
            ! PRIMITIVE-QUARTET PRESCREEN, adapted from the HGP kernel's `bnd`
            ! bound to this loop's swapped order: the pair lists are sorted by
            ! |c|/p descending (build_pairs_hgp), so `bnd` bounds every
            ! remaining bra primitive using THIS ket's weight, and testing it
            ! against the best bra (offab + 1) before entering the bra loop
            ! at all, then EXITing that loop the first time a weaker bra fails
            ! it, is the same two-part test the HGP kernel runs -- just with
            ! bra and ket swapped, because here the ket is the outer loop.
            bnd = TWO_PI_2_5*abs(pp_cs(kq))/(eta*sqrt(eta))
            if (bnd*abs(pp_cs(offab + 1))/pp_p(offab + 1) <= pcut) cycle
            iq = 0.5_dp/eta
            ! yc, yd = c/q, d/q (FRAME.md section 3) are recovered by
            ! projecting the ket pair centre Q = pp_r(kq,:) onto CD, since
            ! terco's pp_p carries only q = c + d, not c and d separately.
            ! Q - C = yd*(D - C), so |Q - C|/rcd = yd exactly whenever
            ! rcd > 0. When C == D (rcd == 0, routine for two shells on one
            ! atom) that ratio is 0/0; yd is then set to an arbitrary finite
            ! value instead; it is provably safe because FRAME.md section 0's
            ! derivation shows every term carrying a yc or yd power also
            ! carries a matching Rs or Rc power from the SAME Hermite
            ! coefficient (they are only ever introduced together), and
            ! Rs = Rc = 0 exactly whenever C == D -- so the term vanishes via
            ! the constant factor regardless of what yd is, PROVIDED yd is
            ! finite: 0.0*NaN is NaN, and the whole point of this branch is to
            ! keep that finite so a degenerate frame does not poison the sum.
            if (rcd > 0.0_dp) then
               yd = sqrt((pp_r(kq,1) - pp_ra(kq,1))**2 + (pp_r(kq,2) - pp_ra(kq,2))**2 &
                       + (pp_r(kq,3) - pp_ra(kq,3))**2)/rcd
            else
               yd = 0.5_dp
            end if
            yc = 1.0_dp - yd
            ax = cl1 + yd*Rs
            az = cl3 + yd*Rc
            kcdv = TWO_PI_2_5*pp_cs(kq)/eta
            sacc(1) = 0.0_dp
            sacc(2) = 0.0_dp
            sacc(3) = 0.0_dp
            sacc(4) = 0.0_dp
            sacc(5) = 0.0_dp
            sacc(6) = 0.0_dp
            sacc(7) = 0.0_dp
            sacc(8) = 0.0_dp
            sacc(9) = 0.0_dp
            sacc(10) = 0.0_dp
            sacc(11) = 0.0_dp
            sacc(12) = 0.0_dp
            sacc(13) = 0.0_dp
            sacc(14) = 0.0_dp
            sacc(15) = 0.0_dp
            do kp = offab + 1, offab + nab
               zeta = pp_p(kp)
               if (bnd*abs(pp_cs(kp))/zeta <= pcut) exit
               zpe = zeta + eta
               ! The exact (ss|ss)-type bound: bit-for-bit the HGP kernel's
               ! own `pref`, since kab*kcd*B_0 regroups to the identical
               ! product (FRAME.md section 4) -- same cutoff, same meaning.
               pref = TWO_PI_2_5/(zeta*eta*sqrt(zpe))*pp_cs(kp)*pp_cs(kq)
               if (abs(pref) <= pcut) cycle
               ip = 0.5_dp/zeta
               za = zhx*(pp_r(kp,1) - pp_ra(kp,1)) + zhy*(pp_r(kp,2) - pp_ra(kp,2)) &
                  + zhz*(pp_r(kp,3) - pp_ra(kp,3))
               zb = za - rab
               zq = za - az
               alpha = zeta*eta/zpe
               tval = alpha*(ax*ax + cy*cy + zq*zq)

                  if (tval >= BOYS_TMAX) then
                  btt = 1.0_dp/tval
                  f(0) = 0.88622692545275801365_dp*sqrt(btt)
                  bet = 0.0_dp
                  f(1) = 1.0_dp*f(0)*(0.5_dp*btt)
                  f(2) = 3.0_dp*f(1)*(0.5_dp*btt)
                  f(3) = 5.0_dp*f(2)*(0.5_dp*btt)
               else
                  bi = int(tval*BOYS_DTINV)
                  bi = min(bi, BOYS_NGRID - 1)
                  bx = 2.0_dp*(tval - real(bi, dp)*BOYS_DT)*BOYS_DTINV - 1.0_dp
                  bx2 = 2.0_dp*bx
                  bbase = bi*(BOYS_MMAX + 1)*(BOYS_NCHEB + 1)
                  bj = bbase + 3*(BOYS_NCHEB + 1)
                  b1 = boys_table(bj + BOYS_NCHEB + 1)
                  b2 = 0.0_dp
                  b0 = bx2*b1 - b2 + boys_table(bj + 5); b2 = b1; b1 = b0
                  b0 = bx2*b1 - b2 + boys_table(bj + 4); b2 = b1; b1 = b0
                  b0 = bx2*b1 - b2 + boys_table(bj + 3); b2 = b1; b1 = b0
                  b0 = bx2*b1 - b2 + boys_table(bj + 2); b2 = b1; b1 = b0
