               v(3,1) = qcy*v(1,1) + wqy*v(1,0)
               v(4,1) = qcz*v(1,1) + wqz*v(1,0)

            do k = 1, 4
               g(k) = g(k) + v(k,1)
            end do
         end do

               out(1) = out(1) + g(2)
               out(2) = out(2) + g(3)
               out(3) = out(3) + g(4)
      end do

