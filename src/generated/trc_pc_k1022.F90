         do id = 0, 5
         do ic = 0, 5
         do ib = 0, 0
         do ia = 0, 2
            idx = idx + 1
            sc = wq*vbuf(idx)
            jab(1 + ia + 3*ib) = jab(1 + ia + 3*ib) &
                                    + 4.0_dp*jfac*sc*dcd(1 + ic + 6*id)
