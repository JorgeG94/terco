            end do
         end do
         do id = 0, 5
            do ic = 0, 5
               dcd(1 + ic + 6*id) = dmat(idens, lamk + ic, sigl + id)
               jcd(1 + ic + 6*id) = 0.0_dp
            end do
         end do
         do ic = 0, 5
            do ia = 0, 2
