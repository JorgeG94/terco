                  rlt = (2.0_dp*xc - (2*iv - 1)*RYS_WIDTH9)/RYS_WIDTH9
                  t2 = 2.0_dp*rlt
                  do s = 1, 2*RYS_NROOTS9
                     base = ((iv - 1)*2*RYS_NROOTS9 + (s - 1))*(RYS_DEGREE9 + 1)
                     d0 = 0.0_dp
                     d1 = 0.0_dp
                     do j = RYS_DEGREE9, 1, -1
                        tmp = d0
                        d0 = t2*d0 - d1 + RYS_C9(base + j + 1)
                        d1 = tmp
                     end do
                     tmp = rlt*d0 - d1 + RYS_C9(base + 1)
                     if (s <= RYS_NROOTS9) then
                        ru(s) = tmp
                     else
                        rw(s - RYS_NROOTS9) = tmp
                     end if
                  end do
               end if
            case default
               ru = 0.0_dp
               rw = 0.0_dp
            end select
            do rt = 1, nroots
               u2 = ru(rt)/(1.0_dp - ru(rt))*rho
               dinv = 1.0_dp/(zeta*eta + u2*(zeta + eta))
               b00r = 0.5_dp*u2*dinv
               b10r = 0.5_dp*(eta + u2)*dinv
               bp01r = 0.5_dp*(zeta + u2)*dinv
               f00 = pref*rw(rt)
               c00x = pax - u2*eta*dinv*pqx
               c00y = pay - u2*eta*dinv*pqy
               c00z = paz - u2*eta*dinv*pqz
               cp0x = qcx + u2*zeta*dinv*pqx
               cp0y = qcy + u2*zeta*dinv*pqy
               cp0z = qcz + u2*zeta*dinv*pqz

               ! The 2D Rys table, one axis at a time -- same recurrence as
               ! rys_inline.py's rys2d_inline_body, with runtime bounds
               ! (ltot is a shell-pair property, not a class constant here).
               call schwarz_rys_g2d(ltot, c00x, cp0x, b00r, b10r, bp01r, 1.0_dp, gx)
               call schwarz_rys_g2d(ltot, c00y, cp0y, b00r, b10r, bp01r, 1.0_dp, gy)
               call schwarz_rys_g2d(ltot, c00z, cp0z, b00r, b10r, bp01r, f00, gz)

               ! The horizontal transfer, extracting only the (ax,bx|ax,bx)
               ! corner this thread needs rather than the whole class.
               hxv = schwarz_rys_hrr_diag(ax, bx, abx, gx)
               hyv = schwarz_rys_hrr_diag(ay, by, aby, gy)
               hzv = schwarz_rys_hrr_diag(az, bz, abz, gz)

               val = val + hxv*hyv*hzv
            end do
         end do
      end do

      out(k) = abs(val)
   end subroutine schwarz_rys_item

   !
   ! One axis of the 2D Rys recurrence (rys_inline.py's rys2d_inline_body,
   ! unrolled form there -- this is its array/runtime-loop twin, since ni =
   ! nk = ltot is a shell-pair property rather than a class constant). g00
   ! is 1 on x and y, and the accumulated weight*prefactor (f00) on z, so
   ! the overall scale factor is carried exactly once.
   !
   pure subroutine schwarz_rys_g2d(ltot, c00, cp00, b00, b10, bp01, g00, g)
      !$acc routine seq
      integer,  intent(in)  :: ltot
      real(dp), intent(in)  :: c00, cp00, b00, b10, bp01, g00
      real(dp), intent(out) :: g(0:SCHWARZ_LTOT_MAX, 0:SCHWARZ_LTOT_MAX)
      integer :: n, m

      g(0, 0) = g00
      if (ltot >= 1) g(1, 0) = c00*g(0, 0)
      do n = 1, ltot - 1
         g(n + 1, 0) = real(n, dp)*b10*g(n - 1, 0) + c00*g(n, 0)
      end do
      if (ltot >= 1) g(0, 1) = cp00*g(0, 0)
      do n = 1, ltot
         g(n, 1) = real(n, dp)*b00*g(n - 1, 0) + cp00*g(n, 0)
      end do
      do m = 1, ltot - 1
         g(0, m + 1) = real(m, dp)*bp01*g(0, m - 1) + cp00*g(0, m)
         do n = 1, ltot
            g(n, m + 1) = real(n, dp)*b00*g(n - 1, m) &
                          + real(m, dp)*bp01*g(n, m - 1) + cp00*g(n, m)
         end do
      end do
   end subroutine schwarz_rys_g2d

   !
   ! The horizontal transfer's diagonal corner: (ea,eb|ea,eb) for one axis,
   ! from the 2D table `g` and the shift AB (ket uses the same AB, since
   ! the ket pair equals the bra pair -- see the module header). Same
   ! two-stage binomial expansion as rys_inline.py's hrr_inline_body
   !
   !   (a,b|c,d) = sum_t C(b,t) AB^(b-t) sum_u C(d,u) AB^(d-u) g(a+t, c+u)
   !
   ! specialised to a = c = ea, b = d = eb: only the one (a,b,c,d) corner
   ! this thread's component needs is formed, not the whole class table.
   !
   pure function schwarz_rys_hrr_diag(ea, eb, ab, g) result(hval)
      !$acc routine seq
      integer,  intent(in) :: ea, eb
      real(dp), intent(in) :: ab
      real(dp), intent(in) :: g(0:SCHWARZ_LTOT_MAX, 0:SCHWARZ_LTOT_MAX)
      real(dp) :: hval
      real(dp) :: abp(0:SCHWARZ_LCEIL), t1(0:SCHWARZ_LCEIL)
      integer :: p, t, u

      abp(0) = 1.0_dp
      do p = 1, eb
         abp(p) = abp(p - 1)*ab
      end do

      do u = 0, eb
         t1(u) = 0.0_dp
         do t = 0, eb
            t1(u) = t1(u) + schwarz_rys_binom(eb, t)*abp(eb - t)*g(ea + t, ea + u)
         end do
      end do

      hval = 0.0_dp
      do u = 0, eb
         hval = hval + schwarz_rys_binom(eb, u)*abp(eb - u)*t1(u)
      end do
   end function schwarz_rys_hrr_diag

   !
   ! Binomial coefficient, n and k both at most SCHWARZ_LCEIL (4): the HRR's
   ! shift never exceeds a single shell's own angular momentum.
   !
   pure function schwarz_rys_binom(n, k) result(c)
      !$acc routine seq
      integer, intent(in) :: n, k
      real(dp) :: c
      integer :: m
      real(dp) :: num, den

      if (k < 0 .or. k > n) then
         c = 0.0_dp
      else
         num = 1.0_dp
         den = 1.0_dp
         do m = 1, k
            num = num*real(n - m + 1, dp)
            den = den*real(m, dp)
         end do
         c = num/den
      end if
   end function schwarz_rys_binom

end module trc_schwarz_rys
