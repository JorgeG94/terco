   integer, parameter :: cnx0_2c44(15) = [4, 3, 3, 2, 2, 2, 1, 1, 1, 1, 0, 0, 0, 0, 0]
   integer, parameter :: cnx1_2c44(1) = [0]
   integer, parameter :: cnx2_2c44(15) = [4, 3, 3, 2, 2, 2, 1, 1, 1, 1, 0, 0, 0, 0, 0]
