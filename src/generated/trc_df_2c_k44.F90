                   na, ord_a, nc, ord_c, nao, sh_ao, jmat)
      end do
   end subroutine df_2c_k44

   pure subroutine df_2c_i44(t, nshell, maxnp, sh_np, sh_e, sh_c, sh_r, &
                         na, ord_a, nc, ord_c, nao, sh_ao, jmat)
      !$acc routine seq
      integer(int64), intent(in) :: t
      integer,  intent(in)    :: nshell, maxnp, na, nc, nao
      integer,  intent(in)    :: sh_np(nshell), sh_ao(nshell)
      real(dp), intent(in)    :: sh_e(maxnp, nshell), sh_c(maxnp, nshell)
      real(dp), intent(in)    :: sh_r(3, nshell)
      integer,  intent(in)    :: ord_a(na), ord_c(nc)
      real(dp), intent(inout) :: jmat(nao, nao)

      integer  :: ii, jj, a, c, mu, nu
      real(dp) :: blk(225)

      ii = ord_a(int(mod(t, int(na, int64))) + 1)
      jj = ord_c(int(t/na) + 1)
      call df_2c44(sh_np(ii), sh_e(:, ii), sh_c(:, ii), sh_r(:, ii), &
                 sh_np(jj), sh_e(:, jj), sh_c(:, jj), sh_r(:, jj), blk)
      ! `blk` is addressed by the SAME affine formula the kernel's own
      ! digestion used to fill it (slot = 1 + ia + na*ic, emit_class's
      ! else-branch above) rather than a running counter incremented once
      ! per iteration: nvfortran 26.5 fails "Missing increment value" on
      ! `!$acc routine seq` translation of a nested loop that increments a
      ! counter and uses it as another array's subscript while ALSO writing
      ! a two-index array through loop-derived indices (mu, nu) -- confirmed
      ! with a four-line reproducer outside this project, bisected down to
      ! exactly that combination. An affine index from the loop variables
      ! sidesteps it and costs nothing: na is a compile-time literal here.
      do c = 0, 14
         nu = sh_ao(jj) + c
         do a = 0, 14
            mu = sh_ao(ii) + a
            jmat(mu, nu) = blk(1 + a + 15*c)
         end do
      end do
   end subroutine df_2c_i44

   pure subroutine df_2c44(nprim_a, ea, ca, ra, nprim_c, ec, cc_, rc, out)
      !! (a|c) class (40|4) -- Rys quadrature,
      !! 5 roots, loop form.
      !$acc routine seq
      integer,  intent(in)  :: nprim_a, nprim_c
      real(dp), intent(in)  :: ea(nprim_a), ca(nprim_a), ra(3)
      real(dp), intent(in)  :: ec(nprim_c), cc_(nprim_c), rc(3)
      real(dp), intent(out) :: out(225)

      integer  :: ip, kp, oz
      real(dp) :: zeta, eta, zpe, rho, kab, pref
      real(dp) :: px, py, pz, pqx, pqy, pqz, tval
      real(dp) :: pax, pay, paz, qcx, qcy, qcz
      real(dp) :: ru(5), rw(5)
      real(dp) :: u2, dinv, b00r, b10r, bp01r, f00
      real(dp) :: c00x, c00y, c00z, cp0x, cp0y, cp0z
      real(dp) :: rlt, t2, d0, d1, tmp, fr, fw, xc
      integer  :: iv, s, j, base
      real(dp) :: gx(0:4, 0:4), gy(0:4, 0:4), gz(0:4, 0:4)
      real(dp) :: hx(0:4, 0:0, 0:4, 0:0)
      real(dp) :: hy(0:4, 0:0, 0:4, 0:0)
      real(dp) :: hz(0:4, 0:0, 0:4, 0:0)
      integer  :: rr, aa, bb, cc, idx
      integer  :: i, k, a, b, c
      real(dp) :: ab2, cd2
      real(dp) :: ht(0:4, 0:0, 0:4)

      do oz = 1, 225
         out(oz) = 0.0_dp
      end do

      do ip = 1, nprim_a
         zeta = ea(ip)
         kab = ca(ip)
         px = ra(1); py = ra(2); pz = ra(3)
         pax = 0.0_dp; pay = 0.0_dp; paz = 0.0_dp

         do kp = 1, nprim_c
            eta = ec(kp)
            zpe = zeta + eta
            rho = zeta*eta/zpe
            ! The ket is a single shell, so Q = C and QC = 0 -- same as
            ! emit_class's HGP body; ld = 0 throughout, so there is no ket
            ! HRR either.
            qcx = 0.0_dp; qcy = 0.0_dp; qcz = 0.0_dp
            pqx = px - rc(1); pqy = py - rc(2); pqz = pz - rc(3)
            tval = rho*(pqx*pqx + pqy*pqy + pqz*pqz)
            ! K_cd = 1: a single Gaussian has no product exponential.
            pref = TWO_PI_2_5/(zeta*eta*sqrt(zpe))*kab*cc_(kp)

            ! Rys root/weight lookup, inlined from trc_rys_roots5_tab -- same
            ! table, interval and Chebyshev evaluation; the early return there
            ! becomes this if/else (a return here would exit the whole kernel).
            if (tval >= RYS_XMAX5) then
               fr = 1.0_dp/tval
               fw = sqrt(fr)
               do s = 1, RYS_NROOTS5
                  ru(s) = RYS_ASY_R5(s)*fr
                  rw(s) = RYS_ASY_W5(s)*fw
               end do
            else
               xc = max(tval, 0.0_dp)
               iv = min(int(xc/RYS_WIDTH5) + 1, RYS_NINT5)
               rlt = (2.0_dp*xc - (2*iv - 1)*RYS_WIDTH5)/RYS_WIDTH5
               t2 = 2.0_dp*rlt
               do s = 1, 2*RYS_NROOTS5
                  base = ((iv - 1)*2*RYS_NROOTS5 + (s - 1))*(RYS_DEGREE5 + 1)
                  d0 = 0.0_dp
                  d1 = 0.0_dp
                  do j = RYS_DEGREE5, 1, -1
                     tmp = d0
                     d0 = t2*d0 - d1 + RYS_C5(base + j + 1)
                     d1 = tmp
                  end do
                  tmp = rlt*d0 - d1 + RYS_C5(base + 1)
                  if (s <= RYS_NROOTS5) then
                     ru(s) = tmp
                  else
                     rw(s - RYS_NROOTS5) = tmp
                  end if
               end do
            end if

            do rr = 1, 5
               u2 = ru(rr)/(1.0_dp - ru(rr))*rho
               dinv = 1.0_dp/(zeta*eta + u2*(zeta + eta))
               b00r  = 0.5_dp*u2*dinv
               b10r  = 0.5_dp*(eta + u2)*dinv
               bp01r = 0.5_dp*(zeta + u2)*dinv
               f00 = pref*rw(rr)
               c00x = pax - u2*eta*dinv*pqx
               c00y = pay - u2*eta*dinv*pqy
               c00z = paz - u2*eta*dinv*pqz
               cp0x = qcx + u2*zeta*dinv*pqx
               cp0y = qcy + u2*zeta*dinv*pqy
               cp0z = qcz + u2*zeta*dinv*pqz

               gx(0, 0) = 1.0_dp
               gx(1, 0) = c00x*1.0_dp
               do i = 1, 3
                  gx(i + 1, 0) = real(i, dp)*b10r*gx(i - 1, 0) + c00x*gx(i, 0)
               end do
               gx(0, 1) = cp0x*1.0_dp
               do i = 1, 4
                  gx(i, 1) = real(i, dp)*b00r*gx(i - 1, 0) + cp0x*gx(i, 0)
               end do
               do k = 1, 3
                  gx(0, k + 1) = real(k, dp)*bp01r*gx(0, k - 1) + cp0x*gx(0, k)
                  do i = 1, 4
                     gx(i, k + 1) = real(i, dp)*b00r*gx(i - 1, k) &
                                 + real(k, dp)*bp01r*gx(i, k - 1) + cp0x*gx(i, k)
                  end do
               end do

               gy(0, 0) = 1.0_dp
               gy(1, 0) = c00y*1.0_dp
               do i = 1, 3
                  gy(i + 1, 0) = real(i, dp)*b10r*gy(i - 1, 0) + c00y*gy(i, 0)
               end do
               gy(0, 1) = cp0y*1.0_dp
               do i = 1, 4
                  gy(i, 1) = real(i, dp)*b00r*gy(i - 1, 0) + cp0y*gy(i, 0)
               end do
               do k = 1, 3
                  gy(0, k + 1) = real(k, dp)*bp01r*gy(0, k - 1) + cp0y*gy(0, k)
                  do i = 1, 4
                     gy(i, k + 1) = real(i, dp)*b00r*gy(i - 1, k) &
                                 + real(k, dp)*bp01r*gy(i, k - 1) + cp0y*gy(i, k)
                  end do
               end do

               gz(0, 0) = f00
               gz(1, 0) = c00z*f00
               do i = 1, 3
                  gz(i + 1, 0) = real(i, dp)*b10r*gz(i - 1, 0) + c00z*gz(i, 0)
               end do
               gz(0, 1) = cp0z*f00
               do i = 1, 4
                  gz(i, 1) = real(i, dp)*b00r*gz(i - 1, 0) + cp0z*gz(i, 0)
               end do
               do k = 1, 3
                  gz(0, k + 1) = real(k, dp)*bp01r*gz(0, k - 1) + cp0z*gz(0, k)
                  do i = 1, 4
                     gz(i, k + 1) = real(i, dp)*b00r*gz(i - 1, k) &
                                 + real(k, dp)*bp01r*gz(i, k - 1) + cp0z*gz(i, k)
                  end do
               end do

               ab2 = 0.0_dp*0.0_dp
               cd2 = 0.0_dp*0.0_dp
               do a = 0, 4
                  do c = 0, 4
                     ht(a, 0, c) = gx(a + 0, c)
                  end do
               end do
               do a = 0, 4
                  do b = 0, 0
                     do c = 0, 4
                        hx(a, b, c, 0) = ht(a, b, c + 0)
                     end do
                  end do
               end do

               ab2 = 0.0_dp*0.0_dp
               cd2 = 0.0_dp*0.0_dp
               do a = 0, 4
                  do c = 0, 4
                     ht(a, 0, c) = gy(a + 0, c)
                  end do
               end do
               do a = 0, 4
                  do b = 0, 0
                     do c = 0, 4
                        hy(a, b, c, 0) = ht(a, b, c + 0)
                     end do
                  end do
               end do

               ab2 = 0.0_dp*0.0_dp
               cd2 = 0.0_dp*0.0_dp
               do a = 0, 4
                  do c = 0, 4
                     ht(a, 0, c) = gz(a + 0, c)
                  end do
               end do
               do a = 0, 4
                  do b = 0, 0
                     do c = 0, 4
                        hz(a, b, c, 0) = ht(a, b, c + 0)
                     end do
                  end do
               end do


               idx = 0
               do cc = 1, 15
                  do bb = 1, 1
                     do aa = 1, 15
                        idx = idx + 1
                        out(idx) = out(idx) &
                           + hx(cnx0_2c44(aa), cnx1_2c44(bb), cnx2_2c44(cc), 0) &
                           * hy(cny0_2c44(aa), cny1_2c44(bb), cny2_2c44(cc), 0) &
                           * hz(cnz0_2c44(aa), cnz1_2c44(bb), cnz2_2c44(cc), 0)
                     end do
                  end do
               end do
            end do

         end do
      end do
   end subroutine df_2c44

end module trc_df_2c_k44
