               + 1.0_dp*oo2e*(v(1,1) - re*v(1,0))
            v(18,1) = qcx*v(8,1) + wqx*v(8,0)
            v(20,1) = paz*v(14,1) + wpz*v(14,0) &
               + 1.0_dp*oo2z*(v(11,1) - rz*v(11,0))
