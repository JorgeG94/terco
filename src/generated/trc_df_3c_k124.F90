   pure subroutine df_3c124(npp, ppz, ppk, ppp, ppa, abx, aby, abz, nprim_c, ec, cc_, rc, out)
      !! (ab|c) class (12|4) -- Rys quadrature,
      !! 4 roots, loop form.
      !$acc routine seq
      integer,  intent(in)  :: npp, nprim_c
      real(dp), intent(in)  :: ppz(npp), ppk(npp), ppp(3, npp), ppa(3, npp)
      real(dp), intent(in)  :: abx, aby, abz
      real(dp), intent(in)  :: ec(nprim_c), cc_(nprim_c), rc(3)
      real(dp), intent(out) :: out(270)

      integer  :: ip, kp, oz
      real(dp) :: zeta, eta, zpe, rho, kab, pref
      real(dp) :: px, py, pz, pqx, pqy, pqz, tval
      real(dp) :: pax, pay, paz, qcx, qcy, qcz
      real(dp) :: ru(4), rw(4)
      real(dp) :: u2, dinv, b00r, b10r, bp01r, f00
      real(dp) :: c00x, c00y, c00z, cp0x, cp0y, cp0z
      real(dp) :: rlt, t2, d0, d1, tmp, fr, fw, xc
      integer  :: iv, s, j, base
      real(dp) :: gx(0:3, 0:4), gy(0:3, 0:4), gz(0:3, 0:4)
      real(dp) :: hx(0:1, 0:2, 0:4, 0:0)
      real(dp) :: hy(0:1, 0:2, 0:4, 0:0)
      real(dp) :: hz(0:1, 0:2, 0:4, 0:0)
      integer  :: rr, aa, bb, cc, idx
      integer  :: i, k, a, b, c
      real(dp) :: ab2, cd2
      real(dp) :: ht(0:1, 0:2, 0:4)

      do oz = 1, 270
         out(oz) = 0.0_dp
      end do

      do ip = 1, npp
         zeta = ppz(ip)
         kab  = ppk(ip)
         px = ppp(1, ip); py = ppp(2, ip); pz = ppp(3, ip)
         pax = ppa(1, ip); pay = ppa(2, ip); paz = ppa(3, ip)

         do kp = 1, nprim_c
            eta = ec(kp)
            zpe = zeta + eta
            rho = zeta*eta/zpe
            ! The ket is a single shell, so Q = C and QC = 0 -- same as
            ! emit_class's HGP body; ld = 0 throughout, so there is no ket
            ! HRR either.
            qcx = 0.0_dp; qcy = 0.0_dp; qcz = 0.0_dp
            pqx = px - rc(1); pqy = py - rc(2); pqz = pz - rc(3)
            tval = rho*(pqx*pqx + pqy*pqy + pqz*pqz)
            ! K_cd = 1: a single Gaussian has no product exponential.
            pref = TWO_PI_2_5/(zeta*eta*sqrt(zpe))*kab*cc_(kp)

            ! Rys root/weight lookup, inlined from trc_rys_roots4_tab -- same
            ! table, interval and Chebyshev evaluation; the early return there
            ! becomes this if/else (a return here would exit the whole kernel).
            if (tval >= RYS_XMAX4) then
               fr = 1.0_dp/tval
               fw = sqrt(fr)
               do s = 1, RYS_NROOTS4
                  ru(s) = RYS_ASY_R4(s)*fr
                  rw(s) = RYS_ASY_W4(s)*fw
               end do
            else
               xc = max(tval, 0.0_dp)
               iv = min(int(xc/RYS_WIDTH4) + 1, RYS_NINT4)
               rlt = (2.0_dp*xc - (2*iv - 1)*RYS_WIDTH4)/RYS_WIDTH4
               t2 = 2.0_dp*rlt
               do s = 1, 2*RYS_NROOTS4
                  base = ((iv - 1)*2*RYS_NROOTS4 + (s - 1))*(RYS_DEGREE4 + 1)
                  d0 = 0.0_dp
                  d1 = 0.0_dp
                  do j = RYS_DEGREE4, 1, -1
                     tmp = d0
                     d0 = t2*d0 - d1 + RYS_C4(base + j + 1)
                     d1 = tmp
                  end do
                  tmp = rlt*d0 - d1 + RYS_C4(base + 1)
                  if (s <= RYS_NROOTS4) then
                     ru(s) = tmp
                  else
                     rw(s - RYS_NROOTS4) = tmp
                  end if
               end do
            end if

            do rr = 1, 4
               u2 = ru(rr)/(1.0_dp - ru(rr))*rho
               dinv = 1.0_dp/(zeta*eta + u2*(zeta + eta))
               b00r  = 0.5_dp*u2*dinv
               b10r  = 0.5_dp*(eta + u2)*dinv
               bp01r = 0.5_dp*(zeta + u2)*dinv
               f00 = pref*rw(rr)
               c00x = pax - u2*eta*dinv*pqx
               c00y = pay - u2*eta*dinv*pqy
               c00z = paz - u2*eta*dinv*pqz
               cp0x = qcx + u2*zeta*dinv*pqx
               cp0y = qcy + u2*zeta*dinv*pqy
               cp0z = qcz + u2*zeta*dinv*pqz

               gx(0, 0) = 1.0_dp
               gx(1, 0) = c00x*1.0_dp
               do i = 1, 2
                  gx(i + 1, 0) = real(i, dp)*b10r*gx(i - 1, 0) + c00x*gx(i, 0)
               end do
               gx(0, 1) = cp0x*1.0_dp
               do i = 1, 3
                  gx(i, 1) = real(i, dp)*b00r*gx(i - 1, 0) + cp0x*gx(i, 0)
               end do
               do k = 1, 3
                  gx(0, k + 1) = real(k, dp)*bp01r*gx(0, k - 1) + cp0x*gx(0, k)
                  do i = 1, 3
                     gx(i, k + 1) = real(i, dp)*b00r*gx(i - 1, k) &
                                 + real(k, dp)*bp01r*gx(i, k - 1) + cp0x*gx(i, k)
                  end do
               end do

               gy(0, 0) = 1.0_dp
               gy(1, 0) = c00y*1.0_dp
               do i = 1, 2
                  gy(i + 1, 0) = real(i, dp)*b10r*gy(i - 1, 0) + c00y*gy(i, 0)
               end do
               gy(0, 1) = cp0y*1.0_dp
               do i = 1, 3
                  gy(i, 1) = real(i, dp)*b00r*gy(i - 1, 0) + cp0y*gy(i, 0)
               end do
               do k = 1, 3
                  gy(0, k + 1) = real(k, dp)*bp01r*gy(0, k - 1) + cp0y*gy(0, k)
                  do i = 1, 3
                     gy(i, k + 1) = real(i, dp)*b00r*gy(i - 1, k) &
                                 + real(k, dp)*bp01r*gy(i, k - 1) + cp0y*gy(i, k)
                  end do
               end do

               gz(0, 0) = f00
               gz(1, 0) = c00z*f00
               do i = 1, 2
                  gz(i + 1, 0) = real(i, dp)*b10r*gz(i - 1, 0) + c00z*gz(i, 0)
               end do
               gz(0, 1) = cp0z*f00
               do i = 1, 3
                  gz(i, 1) = real(i, dp)*b00r*gz(i - 1, 0) + cp0z*gz(i, 0)
               end do
               do k = 1, 3
                  gz(0, k + 1) = real(k, dp)*bp01r*gz(0, k - 1) + cp0z*gz(0, k)
                  do i = 1, 3
                     gz(i, k + 1) = real(i, dp)*b00r*gz(i - 1, k) &
                                 + real(k, dp)*bp01r*gz(i, k - 1) + cp0z*gz(i, k)
                  end do
               end do

               ab2 = abx*abx
               cd2 = 0.0_dp*0.0_dp
               do a = 0, 1
                  do c = 0, 4
                     ht(a, 0, c) = gx(a + 0, c)
                     ht(a, 1, c) = abx*gx(a + 0, c) + gx(a + 1, c)
                     ht(a, 2, c) = ab2*gx(a + 0, c) + 2.0_dp*abx*gx(a + 1, c) + gx(a + 2, c)
                  end do
               end do
               do a = 0, 1
                  do b = 0, 2
                     do c = 0, 4
                        hx(a, b, c, 0) = ht(a, b, c + 0)
                     end do
                  end do
               end do

               ab2 = aby*aby
               cd2 = 0.0_dp*0.0_dp
               do a = 0, 1
                  do c = 0, 4
                     ht(a, 0, c) = gy(a + 0, c)
                     ht(a, 1, c) = aby*gy(a + 0, c) + gy(a + 1, c)
                     ht(a, 2, c) = ab2*gy(a + 0, c) + 2.0_dp*aby*gy(a + 1, c) + gy(a + 2, c)
                  end do
               end do
               do a = 0, 1
                  do b = 0, 2
                     do c = 0, 4
                        hy(a, b, c, 0) = ht(a, b, c + 0)
                     end do
                  end do
               end do

               ab2 = abz*abz
               cd2 = 0.0_dp*0.0_dp
               do a = 0, 1
                  do c = 0, 4
                     ht(a, 0, c) = gz(a + 0, c)
                     ht(a, 1, c) = abz*gz(a + 0, c) + gz(a + 1, c)
                     ht(a, 2, c) = ab2*gz(a + 0, c) + 2.0_dp*abz*gz(a + 1, c) + gz(a + 2, c)
                  end do
               end do
               do a = 0, 1
                  do b = 0, 2
                     do c = 0, 4
                        hz(a, b, c, 0) = ht(a, b, c + 0)
                     end do
                  end do
               end do


               idx = 0
               do cc = 1, 15
                  do bb = 1, 6
                     do aa = 1, 3
                        idx = idx + 1
                        out(idx) = out(idx) &
                           + hx(cnx0_3c124(aa), cnx1_3c124(bb), cnx2_3c124(cc), 0) &
                           * hy(cny0_3c124(aa), cny1_3c124(bb), cny2_3c124(cc), 0) &
                           * hz(cnz0_3c124(aa), cnz1_3c124(bb), cnz2_3c124(cc), 0)
                     end do
                  end do
               end do
            end do

         end do
      end do
   end subroutine df_3c124

end module trc_df_3c_k124
