                          natm, nlane, ky, ny1, ny3, ytens, jc, nqc, qoff, cq, dens, gp)
      case (2); call dfg_3c_k002(nsh, nao, sh_ao, sh_at, sh_r, npq, q_a, q_b, q_o, q_n, &
                          npp, pd, nsx, mnx, ax_np, ax_ao, ax_at, ax_e, ax_c, ax_r, nac, ord_a, &
                          natm, nlane, ky, ny1, ny3, ytens, jc, nqc, qoff, cq, dens, gp)
      case (3); call dfg_3c_k003(nsh, nao, sh_ao, sh_at, sh_r, npq, q_a, q_b, q_o, q_n, &
                          npp, pd, nsx, mnx, ax_np, ax_ao, ax_at, ax_e, ax_c, ax_r, nac, ord_a, &
                          natm, nlane, ky, ny1, ny3, ytens, jc, nqc, qoff, cq, dens, gp)
      case (4); call dfg_3c_k004(nsh, nao, sh_ao, sh_at, sh_r, npq, q_a, q_b, q_o, q_n, &
                          npp, pd, nsx, mnx, ax_np, ax_ao, ax_at, ax_e, ax_c, ax_r, nac, ord_a, &
                          natm, nlane, ky, ny1, ny3, ytens, jc, nqc, qoff, cq, dens, gp)
      case (5); call dfg_3c_k100(nsh, nao, sh_ao, sh_at, sh_r, npq, q_a, q_b, q_o, q_n, &
