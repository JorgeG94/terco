                          natm, nlane, ky, ny1, ny3, ytens, jc, nqc, qoff, cq, dens, gp)
      case (1); call dfg_3c_k001(nsh, nao, sh_ao, sh_at, sh_r, npq, q_a, q_b, q_o, q_n, &
