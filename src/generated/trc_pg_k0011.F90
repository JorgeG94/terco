   attributes(global) subroutine pg0011(g0, gend, nranks, lo, hi, nseg, sOff, sA, sNB, sOA, sOB, sD, npair, sp_i, sp_j, sp_q, thresh, jfac, kfac, dsh, nbas, npp, nao, sh_l, ao_off, pp_off, pp_n, pp_p, pp_r, pp_ra, pp_rb, pp_c, pp_cs, pp_ki, pp_kj, ncoltot, ncoef, ps_np, ps_ncol, ps_soff, ps_coff, col_ao, ps_coef, boys_d, ndens, dmat, jmat)
      integer, value :: nranks, lo, hi, nseg, npair, nbas, npp, nao, ncoltot, ncoef, ndens
      integer(kind=8), value :: g0, gend
      real(dp), value :: thresh, jfac, kfac
      integer(kind=8), device :: sOff(nseg + 1)
      integer,  device :: sA(nseg), sNB(nseg), sOA(nseg), sOB(nseg)
      logical,  device :: sD(nseg)
      integer,  device :: sp_i(npair), sp_j(npair)
      real(dp), device :: sp_q(npair)
      real(dp), device :: dsh(nbas, nbas)
      integer,  device :: sh_l(nbas), ao_off(nbas)
      integer,  device :: pp_off(nbas*nbas), pp_n(nbas*nbas)
      real(dp), device :: pp_p(npp), pp_r(npp, 3), pp_ra(npp, 3)
      real(dp), device :: pp_rb(npp, 3), pp_c(npp)
      real(dp), device :: pp_cs(npp)
      integer,  device :: pp_ki(npp), pp_kj(npp)
      integer,  device :: ps_np(nbas), ps_ncol(nbas), ps_soff(nbas), ps_coff(nbas)
      integer,  device :: col_ao(ncoltot)
      real(dp), device :: ps_coef(ncoef)
      real(dp), device :: boys_d(*)
      real(dp), device :: dmat(ndens, nao, nao)
      real(dp), device :: jmat(ndens, nao, nao)

      real(dp), shared :: Vs(PG_XC, PG_T), Ws(PG_T, PG_NCC), Gs(10, PG_GB)
      integer(kind=8) :: gt
      integer :: p, q, mid, seg, t, iab, icd, si, sj, sk, sl
      integer(kind=8) :: nsa, u, kx
      real(dp) :: qcut, pcut
      integer :: keyab, keycd, offab, offcd, nab, ncd
      integer :: kp, kq, kq0, d, x, x0, xc, cur, ia, ib, ic, id, idx, idens
      integer :: mu, nu, lam, sig, mui, nuj, lamk, sigl
      logical :: dij, dkl, dpq, have, ok
      real(dp) :: zeta, eta, zpe, rho, tval, pref, wc, wmax, acc, aold
      real(dp) :: pqx, pqy, pqz, pax, pay, paz, qcx, qcy, qcz
      real(dp) :: wpx, wpy, wpz, wqx, wqy, wqz
      real(dp) :: oo2z, oo2e, oo2ze, rz, re, sc, vv
      real(dp) :: abx, aby, abz, cdx, cdy, cdz
      real(dp) :: f(0:BOYS_MMAX)
      integer  :: bi, bj, bbase
      real(dp) :: bx, bx2, b0, b1, b2, btt, bet
      real(dp) :: v(10, 0:1), g1(10), vbuf(9)
      real(dp) :: wq
      integer  :: nca, ncb, nccl, ncdl, npi, npj, npk, npl, ncab, nccd
      integer  :: ki, kj, kk, kl, ia2, ib2, ic2, id2, iabc, icdc
      logical  :: same_ab, same_cd, same_pair
      integer  :: tau, cdc, ncdc, ntc, ntcl, abc, nabc, ab0, cd0, a, c, j, e, l, ncomb, cb0, nbt, combo
      real(dp) :: cab(PG_NCAB), tcown(PG_NTC), gown(PG_NG)
      integer  :: offa(PG_NCAB), offb(PG_NCAB), offc(PG_NCC), offd(PG_NCC)
      real(dp) :: jab(1), jcd(9), kac(3)
      real(dp) :: kad(3), kbc(3), kbd(3)
      real(dp) :: dab(1), dcd(9), dac(3)
      real(dp) :: dad(3), dbc(3), dbd(3)

      tau = threadIdx%x
      gt = g0 + int(blockIdx%x - 1, 8)*int(nranks, 8)
      if (gt > gend) return
         ! locate the segment (every thread alike)
         p = lo; q = hi
         do while (p < q)
            mid = (p + q + 1)/2
            if (sOff(mid) < gt) then
               p = mid
            else
               q = mid - 1
            end if
         end do
         seg = p
         t = int(gt - sOff(seg))

         ! KET-UNIFORM DECODE. The bra pair index runs fastest, so the 32
         ! threads of a warp hold 32 bra pairs against ONE ket pair, and the
         ! loads of the inner primitive loop -- the ket side -- are the same
         ! address across the warp: one L1 transaction, broadcast. With the
         ! ket index fastest, as this was, every thread pulled its own ket
         ! record per primitive quartet and Nsight Compute had (ss|ss) at 96%
         ! of L1 throughput with a 28% hit rate. The bra loads now diverge
         ! instead, once per bra primitive rather than once per quartet.
         ! On a symmetric segment the pairs are enumerated column by column,
         ! iab >= icd, with the same closed form inverted.
         if (sD(seg)) then
            nsa = int(sA(seg), 8)
            u = int(t - 1, 8)
            kx = int((real(2*nsa + 1, dp) - sqrt(real(2*nsa + 1, dp)**2 - 8.0_dp*real(u, dp)))/2.0_dp, 8)
            if (kx < 0) kx = 0
            do while (kx > 0)
               if ((kx*(2*nsa + 1) - kx*kx)/2 <= u) exit
               kx = kx - 1
            end do
            do while (((kx + 1)*(2*nsa + 1) - (kx + 1)*(kx + 1))/2 <= u)
               kx = kx + 1
            end do
            icd = int(kx) + 1
            iab = icd + int(u - (kx*(2*nsa + 1) - kx*kx)/2)
         else
            icd = (t - 1)/sA(seg) + 1
            iab = t - (icd - 1)*sA(seg)
         end if

         ! exact Schwarz, per quartet.  The host bin-pair test is only
         ! decade-granular (`int(-log10 Q)` clamped to 9) and therefore admits
         ! up to two decades too much; at RNA3 that was 46% of all quartets.
         qcut = sp_q(sOA(seg) + iab)*sp_q(sOB(seg) + icd)
         if (qcut <= thresh) return
         pcut = thresh*1.0e-3_dp

         si = sp_i(sOA(seg) + iab); sj = sp_j(sOA(seg) + iab)
         sk = sp_i(sOB(seg) + icd); sl = sp_j(sOB(seg) + icd)

         ! Density-weighted screen.  What actually enters the Fock matrix is
         ! Q_ab Q_cd times a density block, so a quartet whose integrals are
         ! above threshold still contributes nothing if every density block it
         ! multiplies is negligible.  The J terms carry a factor 4 from the
         ! Coulomb degeneracy, the K terms 1.  For a converged density on an
         ! extended molecule this is where most of the screening comes from --
         ! with a flat model density it correctly fires on nothing.
         if (qcut*max(4.0_dp*dsh(si, sj), 4.0_dp*dsh(sk, sl), &
                      dsh(si, sk), dsh(si, sl), &
                      dsh(sj, sk), dsh(sj, sl)) <= thresh) return

         same_ab = (si == sj); same_cd = (sk == sl)
         same_pair = sD(seg) .and. (iab == icd)

         keyab = (si - 1)*nbas + sj
         keycd = (sk - 1)*nbas + sl
         offab = pp_off(keyab); nab = pp_n(keyab)
         offcd = pp_off(keycd); ncd = pp_n(keycd)
         nca = ps_ncol(si); ncb = ps_ncol(sj); nccl = ps_ncol(sk); ncdl = ps_ncol(sl)
         npi = ps_np(si); npj = ps_np(sj); npk = ps_np(sk); npl = ps_np(sl)

         abx = pp_ra(offab + 1, 1) - pp_rb(offab + 1, 1)
         aby = pp_ra(offab + 1, 2) - pp_rb(offab + 1, 2)
         abz = pp_ra(offab + 1, 3) - pp_rb(offab + 1, 3)
         cdx = pp_ra(offcd + 1, 1) - pp_rb(offcd + 1, 1)
         cdy = pp_ra(offcd + 1, 2) - pp_rb(offcd + 1, 2)
         cdz = pp_ra(offcd + 1, 3) - pp_rb(offcd + 1, 3)


         ncab = nca*ncb; nccd = nccl*ncdl
         !
         ! COLUMN GRID CHUNKS, to the register budget: a thread owns at most
         ! PG_NTC ket-contracted entries and PG_NG bra-folded ones. Most
         ! classes fit in one pass; the rest repeat the primitive loops per
         ! chunk, which is still far fewer VRR evaluations than one per
         ! column combination.
         !
         cdc = max(1, min(nccd, (PG_NTC*PG_T)/10))
         ntcl = (10*cdc + PG_T - 1)/PG_T
         abc = max(1, min(ncab, PG_NG/ntcl))
         cur = 0
         do cd0 = 1, nccd, cdc
            ncdc = min(cdc, nccd - cd0 + 1)
            ntc = 10*ncdc
            ntcl = (ntc + PG_T - 1)/PG_T
            do c = 1, ncdc
               icdc = cd0 + c - 1
               ic2 = mod(icdc - 1, nccl) + 1; id2 = (icdc - 1)/nccl + 1
               offc(c) = ps_coff(sk) + (ic2 - 1)*npk
               offd(c) = ps_coff(sl) + (id2 - 1)*npl
            end do
            do ab0 = 1, ncab, abc
               nabc = min(abc, ncab - ab0 + 1)
               do a = 1, nabc
                  iabc = ab0 + a - 1
                  ia2 = mod(iabc - 1, nca) + 1; ib2 = (iabc - 1)/nca + 1
                  offa(a) = ps_coff(si) + (ia2 - 1)*npi
                  offb(a) = ps_coff(sj) + (ib2 - 1)*npj
               end do
               do j = 1, PG_NG
                  gown(j) = 0.0_dp
               end do

               do kp = offab + 1, offab + nab
                  zeta = pp_p(kp)
                  ki = pp_ki(kp); kj = pp_kj(kp)
                  wmax = 0.0_dp
                  do a = 1, nabc
                     cab(a) = ps_coef(offa(a) + ki)*ps_coef(offb(a) + kj)
                     wmax = max(wmax, abs(cab(a)))
                  end do
                  do j = 1, PG_NTC
                     tcown(j) = 0.0_dp
                  end do

                  do kq0 = offcd + 1, offcd + ncd, PG_T
                     ! The previous chunk's reduction reads Ws; nobody may
                     ! overwrite a row until every thread is past it.
                     call syncthreads()
                     kq = kq0 + tau - 1
                     have = kq <= offcd + ncd
                     if (have) then
                        eta = pp_p(kq)
                        kk = pp_ki(kq); kl = pp_kj(kq)
                        zpe = zeta + eta
                        pref = TWO_PI_2_5/(zeta*eta*sqrt(zpe))*pp_c(kp)*pp_c(kq)
                     else
                        eta = 1.0_dp; kk = 1; kl = 1; zpe = 1.0_dp; pref = 0.0_dp
                     end if
                     ! ket column weights of this lane's pair, and the
                     ! prescreen on the largest weight either side can give.
                     acc = 0.0_dp
                     do c = 1, ncdc
                        wc = ps_coef(offc(c) + kk)*ps_coef(offd(c) + kl)
                        if (.not. have) wc = 0.0_dp
                        Ws(tau, c) = wc
                        acc = max(acc, abs(wc))
                     end do
                     if (abs(pref)*wmax*acc <= pcut) have = .false.
                     if (have) then
                        rho = zeta*eta/zpe
                        pqx = pp_r(kp, 1) - pp_r(kq, 1)
                        pqy = pp_r(kp, 2) - pp_r(kq, 2)
                        pqz = pp_r(kp, 3) - pp_r(kq, 3)
                        pax = pp_r(kp, 1) - pp_ra(kp, 1)
                        pay = pp_r(kp, 2) - pp_ra(kp, 2)
                        paz = pp_r(kp, 3) - pp_ra(kp, 3)
                        qcx = pp_r(kq, 1) - pp_ra(kq, 1)
                        qcy = pp_r(kq, 2) - pp_ra(kq, 2)
                        qcz = pp_r(kq, 3) - pp_ra(kq, 3)
                        wc = (zeta*pp_r(kp, 1) + eta*pp_r(kq, 1))/zpe
                        wpx = wc - pp_r(kp, 1); wqx = wc - pp_r(kq, 1)
                        wc = (zeta*pp_r(kp, 2) + eta*pp_r(kq, 2))/zpe
                        wpy = wc - pp_r(kp, 2); wqy = wc - pp_r(kq, 2)
                        wc = (zeta*pp_r(kp, 3) + eta*pp_r(kq, 3))/zpe
                        wpz = wc - pp_r(kp, 3); wqz = wc - pp_r(kq, 3)
                        tval = rho*(pqx*pqx + pqy*pqy + pqz*pqz)
                  if (tval >= BOYS_TMAX) then
                  btt = sqrt(tval)
                  f(0) = 0.88622692545275801365_dp*erf(btt)/btt
                  bet = exp(-tval)
                  f(1) = (1.0_dp*f(0) - bet)*(0.5_dp/tval)
                  f(2) = (3.0_dp*f(1) - bet)*(0.5_dp/tval)
               else
                  bi = int(tval*BOYS_DTINV)
                  if (bi >= BOYS_NGRID) bi = BOYS_NGRID - 1
                  bx = 2.0_dp*(tval - real(bi, dp)*BOYS_DT)*BOYS_DTINV - 1.0_dp
                  bx2 = 2.0_dp*bx
                  bbase = bi*(BOYS_MMAX + 1)*(BOYS_NCHEB + 1)
                  bj = bbase + 2*(BOYS_NCHEB + 1)
                  b1 = boys_d(bj + BOYS_NCHEB + 1)
                  b2 = 0.0_dp
                  b0 = bx2*b1 - b2 + boys_d(bj + 5); b2 = b1; b1 = b0
                  b0 = bx2*b1 - b2 + boys_d(bj + 4); b2 = b1; b1 = b0
                  b0 = bx2*b1 - b2 + boys_d(bj + 3); b2 = b1; b1 = b0
                  b0 = bx2*b1 - b2 + boys_d(bj + 2); b2 = b1; b1 = b0
                  f(2) = bx*b1 - b2 + boys_d(bj + 1)
                  bet = exp(-tval)
                  btt = 2.0_dp*tval
                  f(1) = (btt*f(2) + bet)*(0.3333333333333333_dp)
                  f(0) = (btt*f(1) + bet)*(1.0_dp)
               end if


                        oo2z = 0.5_dp/zeta; oo2e = 0.5_dp/eta; oo2ze = 0.5_dp/zpe
                        rz = rho/zeta; re = rho/eta
            ! --- level m = 2 ---
            v(1,0) = pref*f(2)
            ! --- level m = 1 ---
            v(1,1) = pref*f(1)
            v(2,1) = qcx*v(1,1) + wqx*v(1,0)
            v(3,1) = qcy*v(1,1) + wqy*v(1,0)
            v(4,1) = qcz*v(1,1) + wqz*v(1,0)
            ! --- level m = 0 ---
            v(1,0) = pref*f(0)
            v(2,0) = qcx*v(1,0) + wqx*v(1,1)
            v(3,0) = qcy*v(1,0) + wqy*v(1,1)
            v(4,0) = qcz*v(1,0) + wqz*v(1,1)
            v(5,0) = qcx*v(2,0) + wqx*v(2,1) &
               + 1.0_dp*oo2e*(v(1,0) - re*v(1,1))
            v(6,0) = qcx*v(3,0) + wqx*v(3,1)
            v(7,0) = qcx*v(4,0) + wqx*v(4,1)
            v(8,0) = qcy*v(3,0) + wqy*v(3,1) &
               + 1.0_dp*oo2e*(v(1,0) - re*v(1,1))
            v(9,0) = qcy*v(4,0) + wqy*v(4,1)
            v(10,0) = qcz*v(4,0) + wqz*v(4,1) &
               + 1.0_dp*oo2e*(v(1,0) - re*v(1,1))
               cur = 0
                     end if

                     ! KET CONTRACTION ACROSS THE LANES: tc(x, c) += sum over
                     ! the chunk's pairs of W(pair, c) v(x), staged through
                     ! shared memory PG_XC components at a time.
                     do x0 = 1, 10, PG_XC
                        xc = min(PG_XC, 10 - x0 + 1)
                        call syncthreads()
                        do x = 1, xc
                           if (have) then
                              Vs(x, tau) = v(x0 + x - 1, cur)
                           else
                              Vs(x, tau) = 0.0_dp
                           end if
                        end do
                        call syncthreads()
                        do j = 1, ntcl
                           e = tau + (j - 1)*PG_T
                           if (e > ntc) exit
                           x = mod(e - 1, 10) + 1
                           c = (e - 1)/10 + 1
                           if (x >= x0 .and. x < x0 + xc) then
                              acc = 0.0_dp
                              do l = 1, PG_T
                                 acc = acc + Vs(x - x0 + 1, l)*Ws(l, c)
                              end do
                              tcown(j) = tcown(j) + acc
                           end if
                        end do
                     end do
                  end do   ! kq0

                  ! BRA FOLD, by the owners: g(x, a, c) += c_a c_b tc(x, c).
                  do j = 1, ntcl
                     e = tau + (j - 1)*PG_T
                     if (e > ntc) exit
                     do a = 1, nabc
                        gown(j + (a - 1)*ntcl) = gown(j + (a - 1)*ntcl) + cab(a)*tcown(j)
                     end do
                  end do
               end do   ! kp

               !
               ! DIGESTION, one thread per column combination of the chunk,
               ! in batches of PG_GB: the owners scatter into shared memory,
               ! the thread takes its column and runs the HRR and the folded
               ! digestion exactly as the do concurrent kernels do.
               !
               ncomb = nabc*ncdc
               do cb0 = 1, ncomb, PG_GB
                  nbt = min(PG_GB, ncomb - cb0 + 1)
                  call syncthreads()
                  do j = 1, ntcl
                     e = tau + (j - 1)*PG_T
                     if (e > ntc) exit
                     x = mod(e - 1, 10) + 1
                     c = (e - 1)/10 + 1
                     do a = 1, nabc
                        combo = a + (c - 1)*nabc
                        if (combo >= cb0 .and. combo < cb0 + nbt) then
                           Gs(x, combo - cb0 + 1) = gown(j + (a - 1)*ntcl)
                        end if
                     end do
                  end do
                  call syncthreads()
                  if (tau <= nbt) then
                     combo = cb0 + tau - 1
                     a = mod(combo - 1, nabc) + 1
                     c = (combo - 1)/nabc + 1
                     iabc = ab0 + a - 1
                     icdc = cd0 + c - 1
                     ia2 = mod(iabc - 1, nca) + 1; ib2 = (iabc - 1)/nca + 1
                     ic2 = mod(icdc - 1, nccl) + 1; id2 = (icdc - 1)/nccl + 1
                     ! Only the canonical contracted quartets, as the
                     ! contracted path enumerated them.
                     ok = .not. (same_ab .and. ia2 < ib2)
                     if (same_cd .and. ic2 < id2) ok = .false.
                     if (same_pair .and. iabc < icdc) ok = .false.
                     if (ok) then
                        dij = .not. (same_ab .and. ia2 == ib2)
                        dkl = .not. (same_cd .and. ic2 == id2)
                        dpq = .not. (same_pair .and. iabc == icdc)
                        mui = col_ao(ps_soff(si) + ia2); nuj = col_ao(ps_soff(sj) + ib2)
                        lamk = col_ao(ps_soff(sk) + ic2); sigl = col_ao(ps_soff(sl) + id2)
                        do x = 1, 10
                           g1(x) = Gs(x, tau)
                        end do
         ! --- HRR ---
         vbuf(1) = cdx*g1(2) &
            + g1(5)
         vbuf(2) = cdx*g1(3) &
            + g1(6)
         vbuf(3) = cdx*g1(4) &
            + g1(7)
         vbuf(4) = cdy*g1(2) &
            + g1(6)
         vbuf(5) = cdy*g1(3) &
            + g1(8)
         vbuf(6) = cdy*g1(4) &
            + g1(9)
         vbuf(7) = cdz*g1(2) &
            + g1(7)
         vbuf(8) = cdz*g1(3) &
            + g1(9)
         vbuf(9) = cdz*g1(4) &
            + g1(10)

#ifdef TRC_NO_DIGEST
         !
         ! Evaluation only, for like-for-like comparison against published
         ! numbers that were measured with digestion removed (the libERI paper
         ! edits QUICK's source to strip it, so its Tables 2 and 3 are ERI
         ! evaluation alone).  Every integral is still formed -- the whole VRR
         ! and HRR run and every component of vbuf is read, so nothing is
         ! dead-code eliminated -- but the density loads and the atomic
         ! scatters into the Fock matrix are gone.  The guard is opaque to the
         ! compiler and never fires, so jmat is untouched and the ANSWER IS
         ! DELIBERATELY WRONG.  Timing only.
         !
         sc = 0.0_dp
         do idx = 1, 9
            sc = sc + vbuf(idx)
         end do
         if (sc == huge(1.0_dp)) jmat(1, 1, 1) = sc
#else
         !
         ! BLOCK-ACCUMULATED DIGESTION.
         !
         ! The previous form did six atomic updates and six scattered `dmat`
         ! loads PER CARTESIAN COMPONENT.  For (pp|pp) that is 81 components x
         ! 6 = 486 of each, per quartet, even though only six small BLOCKS of
         ! jmat and six of dmat are ever touched.
         !
         ! gpu4pyscf's rys_contract_jk.cu does it the other way round: pull the
         ! density blocks into registers once (`load_dm`), contract every
         ! component against them there (`dot_dm`), and write each output block
         ! out once.  Same arithmetic, an order of magnitude less traffic --
         ! 54 loads and 54 atomics for (pp|pp) instead of 486.
         !
         ! The degeneracy factors are per-quartet, so they collapse into one
         ! scalar applied as the components are consumed.
         !
         wq = 1.0_dp
         if (.not. dij) wq = wq*0.5_dp
         if (.not. dkl) wq = wq*0.5_dp
         if (.not. dpq) wq = wq*0.5_dp

         !
         ! BATCHED OVER DENSITIES.
         !
         ! The integral is formed once, in `vbuf`, and contracted against every
         ! density in the batch. In the coupled-perturbed equations that is the
         ! difference between one integral pass and a hundred: the dynamic
         ! polarizabilities need nine perturbations times twelve imaginary
         ! frequencies, each a Fock build on a different response density.
         !
         ! The density loop is OUTSIDE the block accumulators, not inside, and
         ! that is the whole trick. The six blocks are zeroed, filled and
         ! written per density, so REGISTER PRESSURE DOES NOT GROW WITH THE
         ! BATCH -- holding N sets of blocks at once would have cost 54 more
         ! doubles per density at (pp|pp) and 216 at (dd|dd), on a kernel
         ! already spilling. Cost is `eval + ndens*digest`, and the ceiling is
         ! one over the digestion fraction.
         !
         do idens = 1, ndens

         do ib = 0, 0
