         sy(1,3) = pby*sy(1,2) + 1.0_dp*oo2z*sy(0,2) + 2.0_dp*oo2z*sy(1,1)
         sy(0,4) = pby*sy(0,3) + 3.0_dp*oo2z*sy(0,2)
         sy(1,4) = pby*sy(1,3) + 1.0_dp*oo2z*sy(0,3) + 3.0_dp*oo2z*sy(1,2)
         sz(0,0) = e0z
         sz(1,0) = paz*sz(0,0)
         sz(0,1) = pbz*sz(0,0)
         sz(1,1) = pbz*sz(1,0) + 1.0_dp*oo2z*sz(0,0)
         sz(0,2) = pbz*sz(0,1) + 1.0_dp*oo2z*sz(0,0)
         sz(1,2) = pbz*sz(1,1) + 1.0_dp*oo2z*sz(0,1) + 1.0_dp*oo2z*sz(1,0)
         sz(0,3) = pbz*sz(0,2) + 2.0_dp*oo2z*sz(0,1)
         sz(1,3) = pbz*sz(1,2) + 1.0_dp*oo2z*sz(0,2) + 2.0_dp*oo2z*sz(1,1)
         sz(0,4) = pbz*sz(0,3) + 3.0_dp*oo2z*sz(0,2)
         sz(1,4) = pbz*sz(1,3) + 1.0_dp*oo2z*sz(0,3) + 3.0_dp*oo2z*sz(1,2)

         tx(0,0) = 1.0_dp*bet*sx(0,0) - tbb*sx(0,2)
         tx(1,0) = 1.0_dp*bet*sx(1,0) - tbb*sx(1,2)
         tx(0,1) = 3.0_dp*bet*sx(0,1) - tbb*sx(0,3)
         tx(1,1) = 3.0_dp*bet*sx(1,1) - tbb*sx(1,3)
         tx(0,2) = 5.0_dp*bet*sx(0,2) - tbb*sx(0,4) - 1.0_dp*sx(0,0)
         tx(1,2) = 5.0_dp*bet*sx(1,2) - tbb*sx(1,4) - 1.0_dp*sx(1,0)
         ty(0,0) = 1.0_dp*bet*sy(0,0) - tbb*sy(0,2)
         ty(1,0) = 1.0_dp*bet*sy(1,0) - tbb*sy(1,2)
         ty(0,1) = 3.0_dp*bet*sy(0,1) - tbb*sy(0,3)
         ty(1,1) = 3.0_dp*bet*sy(1,1) - tbb*sy(1,3)
         ty(0,2) = 5.0_dp*bet*sy(0,2) - tbb*sy(0,4) - 1.0_dp*sy(0,0)
         ty(1,2) = 5.0_dp*bet*sy(1,2) - tbb*sy(1,4) - 1.0_dp*sy(1,0)
         tz(0,0) = 1.0_dp*bet*sz(0,0) - tbb*sz(0,2)
         tz(1,0) = 1.0_dp*bet*sz(1,0) - tbb*sz(1,2)
         tz(0,1) = 3.0_dp*bet*sz(0,1) - tbb*sz(0,3)
         tz(1,1) = 3.0_dp*bet*sz(1,1) - tbb*sz(1,3)
         tz(0,2) = 5.0_dp*bet*sz(0,2) - tbb*sz(0,4) - 1.0_dp*sz(0,0)
         tz(1,2) = 5.0_dp*bet*sz(1,2) - tbb*sz(1,4) - 1.0_dp*sz(1,0)

         sout(1) = sout(1) + cc*sx(1,2)*sy(0,0)*sz(0,0)
         tout(1) = tout(1) + cc*(tx(1,2)*sy(0,0)*sz(0,0) &
            + sx(1,2)*ty(0,0)*sz(0,0) &
            + sx(1,2)*sy(0,0)*tz(0,0))
         sout(2) = sout(2) + cc*sx(0,2)*sy(1,0)*sz(0,0)
         tout(2) = tout(2) + cc*(tx(0,2)*sy(1,0)*sz(0,0) &
            + sx(0,2)*ty(1,0)*sz(0,0) &
            + sx(0,2)*sy(1,0)*tz(0,0))
         sout(3) = sout(3) + cc*sx(0,2)*sy(0,0)*sz(1,0)
         tout(3) = tout(3) + cc*(tx(0,2)*sy(0,0)*sz(1,0) &
            + sx(0,2)*ty(0,0)*sz(1,0) &
            + sx(0,2)*sy(0,0)*tz(1,0))
         sout(4) = sout(4) + cc*sx(1,1)*sy(0,1)*sz(0,0)
         tout(4) = tout(4) + cc*(tx(1,1)*sy(0,1)*sz(0,0) &
            + sx(1,1)*ty(0,1)*sz(0,0) &
            + sx(1,1)*sy(0,1)*tz(0,0))
         sout(5) = sout(5) + cc*sx(0,1)*sy(1,1)*sz(0,0)
         tout(5) = tout(5) + cc*(tx(0,1)*sy(1,1)*sz(0,0) &
            + sx(0,1)*ty(1,1)*sz(0,0) &
            + sx(0,1)*sy(1,1)*tz(0,0))
         sout(6) = sout(6) + cc*sx(0,1)*sy(0,1)*sz(1,0)
         tout(6) = tout(6) + cc*(tx(0,1)*sy(0,1)*sz(1,0) &
            + sx(0,1)*ty(0,1)*sz(1,0) &
            + sx(0,1)*sy(0,1)*tz(1,0))
         sout(7) = sout(7) + cc*sx(1,1)*sy(0,0)*sz(0,1)
         tout(7) = tout(7) + cc*(tx(1,1)*sy(0,0)*sz(0,1) &
            + sx(1,1)*ty(0,0)*sz(0,1) &
            + sx(1,1)*sy(0,0)*tz(0,1))
         sout(8) = sout(8) + cc*sx(0,1)*sy(1,0)*sz(0,1)
         tout(8) = tout(8) + cc*(tx(0,1)*sy(1,0)*sz(0,1) &
            + sx(0,1)*ty(1,0)*sz(0,1) &
            + sx(0,1)*sy(1,0)*tz(0,1))
         sout(9) = sout(9) + cc*sx(0,1)*sy(0,0)*sz(1,1)
         tout(9) = tout(9) + cc*(tx(0,1)*sy(0,0)*sz(1,1) &
            + sx(0,1)*ty(0,0)*sz(1,1) &
            + sx(0,1)*sy(0,0)*tz(1,1))
         sout(10) = sout(10) + cc*sx(1,0)*sy(0,2)*sz(0,0)
         tout(10) = tout(10) + cc*(tx(1,0)*sy(0,2)*sz(0,0) &
            + sx(1,0)*ty(0,2)*sz(0,0) &
            + sx(1,0)*sy(0,2)*tz(0,0))
         sout(11) = sout(11) + cc*sx(0,0)*sy(1,2)*sz(0,0)
         tout(11) = tout(11) + cc*(tx(0,0)*sy(1,2)*sz(0,0) &
            + sx(0,0)*ty(1,2)*sz(0,0) &
            + sx(0,0)*sy(1,2)*tz(0,0))
         sout(12) = sout(12) + cc*sx(0,0)*sy(0,2)*sz(1,0)
         tout(12) = tout(12) + cc*(tx(0,0)*sy(0,2)*sz(1,0) &
            + sx(0,0)*ty(0,2)*sz(1,0) &
            + sx(0,0)*sy(0,2)*tz(1,0))
         sout(13) = sout(13) + cc*sx(1,0)*sy(0,1)*sz(0,1)
         tout(13) = tout(13) + cc*(tx(1,0)*sy(0,1)*sz(0,1) &
            + sx(1,0)*ty(0,1)*sz(0,1) &
            + sx(1,0)*sy(0,1)*tz(0,1))
         sout(14) = sout(14) + cc*sx(0,0)*sy(1,1)*sz(0,1)
         tout(14) = tout(14) + cc*(tx(0,0)*sy(1,1)*sz(0,1) &
            + sx(0,0)*ty(1,1)*sz(0,1) &
            + sx(0,0)*sy(1,1)*tz(0,1))
         sout(15) = sout(15) + cc*sx(0,0)*sy(0,1)*sz(1,1)
         tout(15) = tout(15) + cc*(tx(0,0)*sy(0,1)*sz(1,1) &
            + sx(0,0)*ty(0,1)*sz(1,1) &
            + sx(0,0)*sy(0,1)*tz(1,1))
         sout(16) = sout(16) + cc*sx(1,0)*sy(0,0)*sz(0,2)
         tout(16) = tout(16) + cc*(tx(1,0)*sy(0,0)*sz(0,2) &
            + sx(1,0)*ty(0,0)*sz(0,2) &
            + sx(1,0)*sy(0,0)*tz(0,2))
         sout(17) = sout(17) + cc*sx(0,0)*sy(1,0)*sz(0,2)
         tout(17) = tout(17) + cc*(tx(0,0)*sy(1,0)*sz(0,2) &
            + sx(0,0)*ty(1,0)*sz(0,2) &
            + sx(0,0)*sy(1,0)*tz(0,2))
         sout(18) = sout(18) + cc*sx(0,0)*sy(0,0)*sz(1,2)
         tout(18) = tout(18) + cc*(tx(0,0)*sy(0,0)*sz(1,2) &
            + sx(0,0)*ty(0,0)*sz(1,2) &
            + sx(0,0)*sy(0,0)*tz(1,2))

         ! --- nuclear attraction: one VRR per nucleus, accumulated ---
         vpref = 2.0_dp*PI/zeta*exp(-xi*rab2)
         do ic = 1, natm
            pcx = px - ratm(1, ic)
            pcy = py - ratm(2, ic)
            pcz = pz - ratm(3, ic)
            tval = zeta*(pcx*pcx + pcy*pcy + pcz*pcz)
            call boys_eval(3, tval, f)

            ! --- m = 3 ---
            vn(1,3) = vpref*f(3)
            ! --- m = 2 ---
            vn(1,2) = vpref*f(2)
            vn(2,2) = pax*vn(1,2) - pcx*vn(1,3)
            vn(3,2) = pay*vn(1,2) - pcy*vn(1,3)
            vn(4,2) = paz*vn(1,2) - pcz*vn(1,3)
            ! --- m = 1 ---
            vn(1,1) = vpref*f(1)
            vn(2,1) = pax*vn(1,1) - pcx*vn(1,2)
            vn(3,1) = pay*vn(1,1) - pcy*vn(1,2)
            vn(4,1) = paz*vn(1,1) - pcz*vn(1,2)
            vn(5,1) = pax*vn(2,1) - pcx*vn(2,2) &
               + 1.0_dp*oo2z*(vn(1,1) - vn(1,2))
            vn(6,1) = pax*vn(3,1) - pcx*vn(3,2)
            vn(7,1) = pax*vn(4,1) - pcx*vn(4,2)
            vn(8,1) = pay*vn(3,1) - pcy*vn(3,2) &
               + 1.0_dp*oo2z*(vn(1,1) - vn(1,2))
            vn(9,1) = pay*vn(4,1) - pcy*vn(4,2)
            vn(10,1) = paz*vn(4,1) - pcz*vn(4,2) &
               + 1.0_dp*oo2z*(vn(1,1) - vn(1,2))
            ! --- m = 0 ---
            vn(1,0) = vpref*f(0)
            vn(2,0) = pax*vn(1,0) - pcx*vn(1,1)
            vn(3,0) = pay*vn(1,0) - pcy*vn(1,1)
            vn(4,0) = paz*vn(1,0) - pcz*vn(1,1)
            vn(5,0) = pax*vn(2,0) - pcx*vn(2,1) &
               + 1.0_dp*oo2z*(vn(1,0) - vn(1,1))
            vn(6,0) = pax*vn(3,0) - pcx*vn(3,1)
            vn(7,0) = pax*vn(4,0) - pcx*vn(4,1)
            vn(8,0) = pay*vn(3,0) - pcy*vn(3,1) &
               + 1.0_dp*oo2z*(vn(1,0) - vn(1,1))
            vn(9,0) = pay*vn(4,0) - pcy*vn(4,1)
            vn(10,0) = paz*vn(4,0) - pcz*vn(4,1) &
               + 1.0_dp*oo2z*(vn(1,0) - vn(1,1))
            vn(11,0) = pax*vn(5,0) - pcx*vn(5,1) &
               + 2.0_dp*oo2z*(vn(2,0) - vn(2,1))
            vn(12,0) = pax*vn(6,0) - pcx*vn(6,1) &
               + 1.0_dp*oo2z*(vn(3,0) - vn(3,1))
            vn(13,0) = pax*vn(7,0) - pcx*vn(7,1) &
               + 1.0_dp*oo2z*(vn(4,0) - vn(4,1))
            vn(14,0) = pax*vn(8,0) - pcx*vn(8,1)
            vn(15,0) = pax*vn(9,0) - pcx*vn(9,1)
            vn(16,0) = pax*vn(10,0) - pcx*vn(10,1)
            vn(17,0) = pay*vn(8,0) - pcy*vn(8,1) &
               + 2.0_dp*oo2z*(vn(3,0) - vn(3,1))
            vn(18,0) = pay*vn(9,0) - pcy*vn(9,1) &
               + 1.0_dp*oo2z*(vn(4,0) - vn(4,1))
            vn(19,0) = pay*vn(10,0) - pcy*vn(10,1)
            vn(20,0) = paz*vn(10,0) - pcz*vn(10,1) &
               + 2.0_dp*oo2z*(vn(4,0) - vn(4,1))

            do k = 1, 20
               vn0(k) = vn(k,0)
            end do

            vtmp(1) = abx*abx*vn0(2) &
               + 2.0_dp*abx*vn0(5) &
               + vn0(11)
            vtmp(2) = abx*abx*vn0(3) &
               + 2.0_dp*abx*vn0(6) &
               + vn0(12)
            vtmp(3) = abx*abx*vn0(4) &
               + 2.0_dp*abx*vn0(7) &
               + vn0(13)
            vtmp(4) = abx*aby*vn0(2) &
               + abx*vn0(6) &
               + aby*vn0(5) &
               + vn0(12)
            vtmp(5) = abx*aby*vn0(3) &
               + abx*vn0(8) &
               + aby*vn0(6) &
               + vn0(14)
            vtmp(6) = abx*aby*vn0(4) &
               + abx*vn0(9) &
               + aby*vn0(7) &
               + vn0(15)
            vtmp(7) = abx*abz*vn0(2) &
               + abx*vn0(7) &
               + abz*vn0(5) &
               + vn0(13)
            vtmp(8) = abx*abz*vn0(3) &
               + abx*vn0(9) &
               + abz*vn0(6) &
               + vn0(15)
            vtmp(9) = abx*abz*vn0(4) &
               + abx*vn0(10) &
               + abz*vn0(7) &
               + vn0(16)
            vtmp(10) = aby*aby*vn0(2) &
               + 2.0_dp*aby*vn0(6) &
               + vn0(14)
            vtmp(11) = aby*aby*vn0(3) &
               + 2.0_dp*aby*vn0(8) &
               + vn0(17)
            vtmp(12) = aby*aby*vn0(4) &
               + 2.0_dp*aby*vn0(9) &
               + vn0(18)
            vtmp(13) = aby*abz*vn0(2) &
               + aby*vn0(7) &
               + abz*vn0(6) &
               + vn0(15)
            vtmp(14) = aby*abz*vn0(3) &
               + aby*vn0(9) &
               + abz*vn0(8) &
               + vn0(18)
            vtmp(15) = aby*abz*vn0(4) &
               + aby*vn0(10) &
               + abz*vn0(9) &
               + vn0(19)
            vtmp(16) = abz*abz*vn0(2) &
               + 2.0_dp*abz*vn0(7) &
               + vn0(16)
            vtmp(17) = abz*abz*vn0(3) &
               + 2.0_dp*abz*vn0(9) &
               + vn0(19)
            vtmp(18) = abz*abz*vn0(4) &
               + 2.0_dp*abz*vn0(10) &
               + vn0(20)

            do k = 1, 18
               vout(k) = vout(k) - cc*zatm(ic)*vtmp(k)
            end do
         end do
      end do
      end do
   end subroutine one_e_12


   !> (2|0) one-electron block: overlap, kinetic, nuclear attraction.
   !>
   !> One routine for all three because they share the shell-pair quantities
   !> (zeta, P, the Gaussian product prefactor) and mqc needs all three to form
   !> the core Hamiltonian. Computing them together reads the primitive data
   !> once instead of three times.
   pure subroutine one_e_20(nprim_a, nprim_b, ea, ca, eb, cb, ra, rb, &
                               natm, zatm, ratm, sout, tout, vout)
      !$acc routine seq
      integer,  intent(in)  :: nprim_a, nprim_b, natm
      real(dp), intent(in)  :: ea(nprim_a), ca(nprim_a)
      real(dp), intent(in)  :: eb(nprim_b), cb(nprim_b)
      real(dp), intent(in)  :: ra(3), rb(3)
      real(dp), intent(in)  :: zatm(natm), ratm(3, natm)
      real(dp), intent(out) :: sout(6), tout(6), vout(6)

      integer  :: ip, jp, ic, k
      real(dp) :: al, bet, zeta, oo2z, xi, cc, tbb
      real(dp) :: px, py, pz, pax, pay, paz, pbx, pby, pbz
      real(dp) :: pcx, pcy, pcz, tval, vpref, rab2
      real(dp) :: abx, aby, abz, e0x, e0y, e0z
      real(dp) :: sx(0:2,0:2), sy(0:2,0:2), sz(0:2,0:2)
      real(dp) :: tx(0:2,0:0), ty(0:2,0:0), tz(0:2,0:0)
      real(dp) :: vn(10,0:2), vn0(10), vtmp(6)
      real(dp) :: f(0:BOYS_MMAX)

      abx = ra(1) - rb(1); aby = ra(2) - rb(2); abz = ra(3) - rb(3)
      rab2 = abx*abx + aby*aby + abz*abz

      do k = 1, 6
         sout(k) = 0.0_dp; tout(k) = 0.0_dp; vout(k) = 0.0_dp
      end do

      do ip = 1, nprim_a
         al = ea(ip)
      do jp = 1, nprim_b
         bet = eb(jp)
         zeta = al + bet
         oo2z = 0.5_dp/zeta
         xi = al*bet/zeta
         cc = ca(ip)*cb(jp)
         tbb = 2.0_dp*bet*bet

         px = (al*ra(1) + bet*rb(1))/zeta
         py = (al*ra(2) + bet*rb(2))/zeta
         pz = (al*ra(3) + bet*rb(3))/zeta
         pax = px - ra(1); pay = py - ra(2); paz = pz - ra(3)
         pbx = px - rb(1); pby = py - rb(2); pbz = pz - rb(3)

         ! 1-D Gaussian-product prefactors; their product is
         ! (pi/zeta)^(3/2) exp(-xi |AB|^2), the 3-D overlap of two s functions.
         e0x = sqrt(PI/zeta)*exp(-xi*abx*abx)
         e0y = sqrt(PI/zeta)*exp(-xi*aby*aby)
         e0z = sqrt(PI/zeta)*exp(-xi*abz*abz)

         sx(0,0) = e0x
         sx(1,0) = pax*sx(0,0)
         sx(2,0) = pax*sx(1,0) + 1.0_dp*oo2z*sx(0,0)
         sx(0,1) = pbx*sx(0,0)
         sx(1,1) = pbx*sx(1,0) + 1.0_dp*oo2z*sx(0,0)
         sx(2,1) = pbx*sx(2,0) + 2.0_dp*oo2z*sx(1,0)
         sx(0,2) = pbx*sx(0,1) + 1.0_dp*oo2z*sx(0,0)
         sx(1,2) = pbx*sx(1,1) + 1.0_dp*oo2z*sx(0,1) + 1.0_dp*oo2z*sx(1,0)
         sx(2,2) = pbx*sx(2,1) + 2.0_dp*oo2z*sx(1,1) + 1.0_dp*oo2z*sx(2,0)
         sy(0,0) = e0y
         sy(1,0) = pay*sy(0,0)
         sy(2,0) = pay*sy(1,0) + 1.0_dp*oo2z*sy(0,0)
         sy(0,1) = pby*sy(0,0)
         sy(1,1) = pby*sy(1,0) + 1.0_dp*oo2z*sy(0,0)
         sy(2,1) = pby*sy(2,0) + 2.0_dp*oo2z*sy(1,0)
         sy(0,2) = pby*sy(0,1) + 1.0_dp*oo2z*sy(0,0)
         sy(1,2) = pby*sy(1,1) + 1.0_dp*oo2z*sy(0,1) + 1.0_dp*oo2z*sy(1,0)
         sy(2,2) = pby*sy(2,1) + 2.0_dp*oo2z*sy(1,1) + 1.0_dp*oo2z*sy(2,0)
         sz(0,0) = e0z
         sz(1,0) = paz*sz(0,0)
         sz(2,0) = paz*sz(1,0) + 1.0_dp*oo2z*sz(0,0)
         sz(0,1) = pbz*sz(0,0)
         sz(1,1) = pbz*sz(1,0) + 1.0_dp*oo2z*sz(0,0)
         sz(2,1) = pbz*sz(2,0) + 2.0_dp*oo2z*sz(1,0)
         sz(0,2) = pbz*sz(0,1) + 1.0_dp*oo2z*sz(0,0)
         sz(1,2) = pbz*sz(1,1) + 1.0_dp*oo2z*sz(0,1) + 1.0_dp*oo2z*sz(1,0)
         sz(2,2) = pbz*sz(2,1) + 2.0_dp*oo2z*sz(1,1) + 1.0_dp*oo2z*sz(2,0)

         tx(0,0) = 1.0_dp*bet*sx(0,0) - tbb*sx(0,2)
         tx(1,0) = 1.0_dp*bet*sx(1,0) - tbb*sx(1,2)
         tx(2,0) = 1.0_dp*bet*sx(2,0) - tbb*sx(2,2)
         ty(0,0) = 1.0_dp*bet*sy(0,0) - tbb*sy(0,2)
         ty(1,0) = 1.0_dp*bet*sy(1,0) - tbb*sy(1,2)
         ty(2,0) = 1.0_dp*bet*sy(2,0) - tbb*sy(2,2)
         tz(0,0) = 1.0_dp*bet*sz(0,0) - tbb*sz(0,2)
         tz(1,0) = 1.0_dp*bet*sz(1,0) - tbb*sz(1,2)
         tz(2,0) = 1.0_dp*bet*sz(2,0) - tbb*sz(2,2)

         sout(1) = sout(1) + cc*sx(2,0)*sy(0,0)*sz(0,0)
         tout(1) = tout(1) + cc*(tx(2,0)*sy(0,0)*sz(0,0) &
            + sx(2,0)*ty(0,0)*sz(0,0) &
            + sx(2,0)*sy(0,0)*tz(0,0))
         sout(2) = sout(2) + cc*sx(1,0)*sy(1,0)*sz(0,0)
         tout(2) = tout(2) + cc*(tx(1,0)*sy(1,0)*sz(0,0) &
            + sx(1,0)*ty(1,0)*sz(0,0) &
            + sx(1,0)*sy(1,0)*tz(0,0))
         sout(3) = sout(3) + cc*sx(1,0)*sy(0,0)*sz(1,0)
         tout(3) = tout(3) + cc*(tx(1,0)*sy(0,0)*sz(1,0) &
            + sx(1,0)*ty(0,0)*sz(1,0) &
            + sx(1,0)*sy(0,0)*tz(1,0))
         sout(4) = sout(4) + cc*sx(0,0)*sy(2,0)*sz(0,0)
         tout(4) = tout(4) + cc*(tx(0,0)*sy(2,0)*sz(0,0) &
            + sx(0,0)*ty(2,0)*sz(0,0) &
            + sx(0,0)*sy(2,0)*tz(0,0))
         sout(5) = sout(5) + cc*sx(0,0)*sy(1,0)*sz(1,0)
         tout(5) = tout(5) + cc*(tx(0,0)*sy(1,0)*sz(1,0) &
            + sx(0,0)*ty(1,0)*sz(1,0) &
            + sx(0,0)*sy(1,0)*tz(1,0))
         sout(6) = sout(6) + cc*sx(0,0)*sy(0,0)*sz(2,0)
         tout(6) = tout(6) + cc*(tx(0,0)*sy(0,0)*sz(2,0) &
            + sx(0,0)*ty(0,0)*sz(2,0) &
            + sx(0,0)*sy(0,0)*tz(2,0))

         ! --- nuclear attraction: one VRR per nucleus, accumulated ---
         vpref = 2.0_dp*PI/zeta*exp(-xi*rab2)
         do ic = 1, natm
            pcx = px - ratm(1, ic)
            pcy = py - ratm(2, ic)
            pcz = pz - ratm(3, ic)
            tval = zeta*(pcx*pcx + pcy*pcy + pcz*pcz)
            call boys_eval(2, tval, f)

            ! --- m = 2 ---
            vn(1,2) = vpref*f(2)
            ! --- m = 1 ---
            vn(1,1) = vpref*f(1)
            vn(2,1) = pax*vn(1,1) - pcx*vn(1,2)
            vn(3,1) = pay*vn(1,1) - pcy*vn(1,2)
            vn(4,1) = paz*vn(1,1) - pcz*vn(1,2)
            ! --- m = 0 ---
            vn(1,0) = vpref*f(0)
            vn(2,0) = pax*vn(1,0) - pcx*vn(1,1)
            vn(3,0) = pay*vn(1,0) - pcy*vn(1,1)
            vn(4,0) = paz*vn(1,0) - pcz*vn(1,1)
            vn(5,0) = pax*vn(2,0) - pcx*vn(2,1) &
               + 1.0_dp*oo2z*(vn(1,0) - vn(1,1))
            vn(6,0) = pax*vn(3,0) - pcx*vn(3,1)
            vn(7,0) = pax*vn(4,0) - pcx*vn(4,1)
            vn(8,0) = pay*vn(3,0) - pcy*vn(3,1) &
               + 1.0_dp*oo2z*(vn(1,0) - vn(1,1))
            vn(9,0) = pay*vn(4,0) - pcy*vn(4,1)
            vn(10,0) = paz*vn(4,0) - pcz*vn(4,1) &
               + 1.0_dp*oo2z*(vn(1,0) - vn(1,1))

            do k = 1, 10
               vn0(k) = vn(k,0)
            end do

            vtmp(1) = vn0(5)
            vtmp(2) = vn0(6)
            vtmp(3) = vn0(7)
            vtmp(4) = vn0(8)
            vtmp(5) = vn0(9)
            vtmp(6) = vn0(10)

            do k = 1, 6
               vout(k) = vout(k) - cc*zatm(ic)*vtmp(k)
            end do
         end do
      end do
      end do
   end subroutine one_e_20


   !> (2|1) one-electron block: overlap, kinetic, nuclear attraction.
   !>
   !> One routine for all three because they share the shell-pair quantities
   !> (zeta, P, the Gaussian product prefactor) and mqc needs all three to form
   !> the core Hamiltonian. Computing them together reads the primitive data
   !> once instead of three times.
   pure subroutine one_e_21(nprim_a, nprim_b, ea, ca, eb, cb, ra, rb, &
                               natm, zatm, ratm, sout, tout, vout)
      !$acc routine seq
      integer,  intent(in)  :: nprim_a, nprim_b, natm
      real(dp), intent(in)  :: ea(nprim_a), ca(nprim_a)
      real(dp), intent(in)  :: eb(nprim_b), cb(nprim_b)
      real(dp), intent(in)  :: ra(3), rb(3)
      real(dp), intent(in)  :: zatm(natm), ratm(3, natm)
      real(dp), intent(out) :: sout(18), tout(18), vout(18)

      integer  :: ip, jp, ic, k
      real(dp) :: al, bet, zeta, oo2z, xi, cc, tbb
      real(dp) :: px, py, pz, pax, pay, paz, pbx, pby, pbz
      real(dp) :: pcx, pcy, pcz, tval, vpref, rab2
      real(dp) :: abx, aby, abz, e0x, e0y, e0z
      real(dp) :: sx(0:2,0:3), sy(0:2,0:3), sz(0:2,0:3)
      real(dp) :: tx(0:2,0:1), ty(0:2,0:1), tz(0:2,0:1)
      real(dp) :: vn(20,0:3), vn0(20), vtmp(18)
      real(dp) :: f(0:BOYS_MMAX)

      abx = ra(1) - rb(1); aby = ra(2) - rb(2); abz = ra(3) - rb(3)
      rab2 = abx*abx + aby*aby + abz*abz

      do k = 1, 18
         sout(k) = 0.0_dp; tout(k) = 0.0_dp; vout(k) = 0.0_dp
      end do

      do ip = 1, nprim_a
         al = ea(ip)
      do jp = 1, nprim_b
         bet = eb(jp)
         zeta = al + bet
         oo2z = 0.5_dp/zeta
         xi = al*bet/zeta
         cc = ca(ip)*cb(jp)
         tbb = 2.0_dp*bet*bet

         px = (al*ra(1) + bet*rb(1))/zeta
         py = (al*ra(2) + bet*rb(2))/zeta
         pz = (al*ra(3) + bet*rb(3))/zeta
         pax = px - ra(1); pay = py - ra(2); paz = pz - ra(3)
         pbx = px - rb(1); pby = py - rb(2); pbz = pz - rb(3)

         ! 1-D Gaussian-product prefactors; their product is
         ! (pi/zeta)^(3/2) exp(-xi |AB|^2), the 3-D overlap of two s functions.
         e0x = sqrt(PI/zeta)*exp(-xi*abx*abx)
         e0y = sqrt(PI/zeta)*exp(-xi*aby*aby)
         e0z = sqrt(PI/zeta)*exp(-xi*abz*abz)

         sx(0,0) = e0x
         sx(1,0) = pax*sx(0,0)
         sx(2,0) = pax*sx(1,0) + 1.0_dp*oo2z*sx(0,0)
         sx(0,1) = pbx*sx(0,0)
         sx(1,1) = pbx*sx(1,0) + 1.0_dp*oo2z*sx(0,0)
         sx(2,1) = pbx*sx(2,0) + 2.0_dp*oo2z*sx(1,0)
         sx(0,2) = pbx*sx(0,1) + 1.0_dp*oo2z*sx(0,0)
         sx(1,2) = pbx*sx(1,1) + 1.0_dp*oo2z*sx(0,1) + 1.0_dp*oo2z*sx(1,0)
         sx(2,2) = pbx*sx(2,1) + 2.0_dp*oo2z*sx(1,1) + 1.0_dp*oo2z*sx(2,0)
         sx(0,3) = pbx*sx(0,2) + 2.0_dp*oo2z*sx(0,1)
         sx(1,3) = pbx*sx(1,2) + 1.0_dp*oo2z*sx(0,2) + 2.0_dp*oo2z*sx(1,1)
         sx(2,3) = pbx*sx(2,2) + 2.0_dp*oo2z*sx(1,2) + 2.0_dp*oo2z*sx(2,1)
         sy(0,0) = e0y
         sy(1,0) = pay*sy(0,0)
         sy(2,0) = pay*sy(1,0) + 1.0_dp*oo2z*sy(0,0)
         sy(0,1) = pby*sy(0,0)
         sy(1,1) = pby*sy(1,0) + 1.0_dp*oo2z*sy(0,0)
         sy(2,1) = pby*sy(2,0) + 2.0_dp*oo2z*sy(1,0)
         sy(0,2) = pby*sy(0,1) + 1.0_dp*oo2z*sy(0,0)
         sy(1,2) = pby*sy(1,1) + 1.0_dp*oo2z*sy(0,1) + 1.0_dp*oo2z*sy(1,0)
         sy(2,2) = pby*sy(2,1) + 2.0_dp*oo2z*sy(1,1) + 1.0_dp*oo2z*sy(2,0)
         sy(0,3) = pby*sy(0,2) + 2.0_dp*oo2z*sy(0,1)
         sy(1,3) = pby*sy(1,2) + 1.0_dp*oo2z*sy(0,2) + 2.0_dp*oo2z*sy(1,1)
         sy(2,3) = pby*sy(2,2) + 2.0_dp*oo2z*sy(1,2) + 2.0_dp*oo2z*sy(2,1)
         sz(0,0) = e0z
         sz(1,0) = paz*sz(0,0)
         sz(2,0) = paz*sz(1,0) + 1.0_dp*oo2z*sz(0,0)
         sz(0,1) = pbz*sz(0,0)
         sz(1,1) = pbz*sz(1,0) + 1.0_dp*oo2z*sz(0,0)
         sz(2,1) = pbz*sz(2,0) + 2.0_dp*oo2z*sz(1,0)
         sz(0,2) = pbz*sz(0,1) + 1.0_dp*oo2z*sz(0,0)
         sz(1,2) = pbz*sz(1,1) + 1.0_dp*oo2z*sz(0,1) + 1.0_dp*oo2z*sz(1,0)
         sz(2,2) = pbz*sz(2,1) + 2.0_dp*oo2z*sz(1,1) + 1.0_dp*oo2z*sz(2,0)
         sz(0,3) = pbz*sz(0,2) + 2.0_dp*oo2z*sz(0,1)
         sz(1,3) = pbz*sz(1,2) + 1.0_dp*oo2z*sz(0,2) + 2.0_dp*oo2z*sz(1,1)
         sz(2,3) = pbz*sz(2,2) + 2.0_dp*oo2z*sz(1,2) + 2.0_dp*oo2z*sz(2,1)

         tx(0,0) = 1.0_dp*bet*sx(0,0) - tbb*sx(0,2)
         tx(1,0) = 1.0_dp*bet*sx(1,0) - tbb*sx(1,2)
         tx(2,0) = 1.0_dp*bet*sx(2,0) - tbb*sx(2,2)
         tx(0,1) = 3.0_dp*bet*sx(0,1) - tbb*sx(0,3)
         tx(1,1) = 3.0_dp*bet*sx(1,1) - tbb*sx(1,3)
         tx(2,1) = 3.0_dp*bet*sx(2,1) - tbb*sx(2,3)
         ty(0,0) = 1.0_dp*bet*sy(0,0) - tbb*sy(0,2)
         ty(1,0) = 1.0_dp*bet*sy(1,0) - tbb*sy(1,2)
         ty(2,0) = 1.0_dp*bet*sy(2,0) - tbb*sy(2,2)
         ty(0,1) = 3.0_dp*bet*sy(0,1) - tbb*sy(0,3)
         ty(1,1) = 3.0_dp*bet*sy(1,1) - tbb*sy(1,3)
         ty(2,1) = 3.0_dp*bet*sy(2,1) - tbb*sy(2,3)
         tz(0,0) = 1.0_dp*bet*sz(0,0) - tbb*sz(0,2)
         tz(1,0) = 1.0_dp*bet*sz(1,0) - tbb*sz(1,2)
         tz(2,0) = 1.0_dp*bet*sz(2,0) - tbb*sz(2,2)
         tz(0,1) = 3.0_dp*bet*sz(0,1) - tbb*sz(0,3)
         tz(1,1) = 3.0_dp*bet*sz(1,1) - tbb*sz(1,3)
         tz(2,1) = 3.0_dp*bet*sz(2,1) - tbb*sz(2,3)

         sout(1) = sout(1) + cc*sx(2,1)*sy(0,0)*sz(0,0)
         tout(1) = tout(1) + cc*(tx(2,1)*sy(0,0)*sz(0,0) &
            + sx(2,1)*ty(0,0)*sz(0,0) &
            + sx(2,1)*sy(0,0)*tz(0,0))
         sout(2) = sout(2) + cc*sx(1,1)*sy(1,0)*sz(0,0)
         tout(2) = tout(2) + cc*(tx(1,1)*sy(1,0)*sz(0,0) &
            + sx(1,1)*ty(1,0)*sz(0,0) &
            + sx(1,1)*sy(1,0)*tz(0,0))
         sout(3) = sout(3) + cc*sx(1,1)*sy(0,0)*sz(1,0)
         tout(3) = tout(3) + cc*(tx(1,1)*sy(0,0)*sz(1,0) &
            + sx(1,1)*ty(0,0)*sz(1,0) &
            + sx(1,1)*sy(0,0)*tz(1,0))
         sout(4) = sout(4) + cc*sx(0,1)*sy(2,0)*sz(0,0)
         tout(4) = tout(4) + cc*(tx(0,1)*sy(2,0)*sz(0,0) &
            + sx(0,1)*ty(2,0)*sz(0,0) &
            + sx(0,1)*sy(2,0)*tz(0,0))
         sout(5) = sout(5) + cc*sx(0,1)*sy(1,0)*sz(1,0)
         tout(5) = tout(5) + cc*(tx(0,1)*sy(1,0)*sz(1,0) &
            + sx(0,1)*ty(1,0)*sz(1,0) &
            + sx(0,1)*sy(1,0)*tz(1,0))
         sout(6) = sout(6) + cc*sx(0,1)*sy(0,0)*sz(2,0)
         tout(6) = tout(6) + cc*(tx(0,1)*sy(0,0)*sz(2,0) &
            + sx(0,1)*ty(0,0)*sz(2,0) &
            + sx(0,1)*sy(0,0)*tz(2,0))
         sout(7) = sout(7) + cc*sx(2,0)*sy(0,1)*sz(0,0)
         tout(7) = tout(7) + cc*(tx(2,0)*sy(0,1)*sz(0,0) &
            + sx(2,0)*ty(0,1)*sz(0,0) &
            + sx(2,0)*sy(0,1)*tz(0,0))
         sout(8) = sout(8) + cc*sx(1,0)*sy(1,1)*sz(0,0)
         tout(8) = tout(8) + cc*(tx(1,0)*sy(1,1)*sz(0,0) &
            + sx(1,0)*ty(1,1)*sz(0,0) &
            + sx(1,0)*sy(1,1)*tz(0,0))
         sout(9) = sout(9) + cc*sx(1,0)*sy(0,1)*sz(1,0)
         tout(9) = tout(9) + cc*(tx(1,0)*sy(0,1)*sz(1,0) &
            + sx(1,0)*ty(0,1)*sz(1,0) &
            + sx(1,0)*sy(0,1)*tz(1,0))
         sout(10) = sout(10) + cc*sx(0,0)*sy(2,1)*sz(0,0)
         tout(10) = tout(10) + cc*(tx(0,0)*sy(2,1)*sz(0,0) &
            + sx(0,0)*ty(2,1)*sz(0,0) &
            + sx(0,0)*sy(2,1)*tz(0,0))
         sout(11) = sout(11) + cc*sx(0,0)*sy(1,1)*sz(1,0)
         tout(11) = tout(11) + cc*(tx(0,0)*sy(1,1)*sz(1,0) &
            + sx(0,0)*ty(1,1)*sz(1,0) &
            + sx(0,0)*sy(1,1)*tz(1,0))
         sout(12) = sout(12) + cc*sx(0,0)*sy(0,1)*sz(2,0)
         tout(12) = tout(12) + cc*(tx(0,0)*sy(0,1)*sz(2,0) &
            + sx(0,0)*ty(0,1)*sz(2,0) &
            + sx(0,0)*sy(0,1)*tz(2,0))
         sout(13) = sout(13) + cc*sx(2,0)*sy(0,0)*sz(0,1)
         tout(13) = tout(13) + cc*(tx(2,0)*sy(0,0)*sz(0,1) &
            + sx(2,0)*ty(0,0)*sz(0,1) &
            + sx(2,0)*sy(0,0)*tz(0,1))
         sout(14) = sout(14) + cc*sx(1,0)*sy(1,0)*sz(0,1)
         tout(14) = tout(14) + cc*(tx(1,0)*sy(1,0)*sz(0,1) &
            + sx(1,0)*ty(1,0)*sz(0,1) &
            + sx(1,0)*sy(1,0)*tz(0,1))
         sout(15) = sout(15) + cc*sx(1,0)*sy(0,0)*sz(1,1)
         tout(15) = tout(15) + cc*(tx(1,0)*sy(0,0)*sz(1,1) &
            + sx(1,0)*ty(0,0)*sz(1,1) &
            + sx(1,0)*sy(0,0)*tz(1,1))
         sout(16) = sout(16) + cc*sx(0,0)*sy(2,0)*sz(0,1)
         tout(16) = tout(16) + cc*(tx(0,0)*sy(2,0)*sz(0,1) &
            + sx(0,0)*ty(2,0)*sz(0,1) &
            + sx(0,0)*sy(2,0)*tz(0,1))
         sout(17) = sout(17) + cc*sx(0,0)*sy(1,0)*sz(1,1)
         tout(17) = tout(17) + cc*(tx(0,0)*sy(1,0)*sz(1,1) &
            + sx(0,0)*ty(1,0)*sz(1,1) &
            + sx(0,0)*sy(1,0)*tz(1,1))
         sout(18) = sout(18) + cc*sx(0,0)*sy(0,0)*sz(2,1)
         tout(18) = tout(18) + cc*(tx(0,0)*sy(0,0)*sz(2,1) &
            + sx(0,0)*ty(0,0)*sz(2,1) &
            + sx(0,0)*sy(0,0)*tz(2,1))

         ! --- nuclear attraction: one VRR per nucleus, accumulated ---
         vpref = 2.0_dp*PI/zeta*exp(-xi*rab2)
         do ic = 1, natm
            pcx = px - ratm(1, ic)
            pcy = py - ratm(2, ic)
            pcz = pz - ratm(3, ic)
            tval = zeta*(pcx*pcx + pcy*pcy + pcz*pcz)
            call boys_eval(3, tval, f)

            ! --- m = 3 ---
            vn(1,3) = vpref*f(3)
            ! --- m = 2 ---
            vn(1,2) = vpref*f(2)
            vn(2,2) = pax*vn(1,2) - pcx*vn(1,3)
            vn(3,2) = pay*vn(1,2) - pcy*vn(1,3)
            vn(4,2) = paz*vn(1,2) - pcz*vn(1,3)
            ! --- m = 1 ---
            vn(1,1) = vpref*f(1)
            vn(2,1) = pax*vn(1,1) - pcx*vn(1,2)
            vn(3,1) = pay*vn(1,1) - pcy*vn(1,2)
            vn(4,1) = paz*vn(1,1) - pcz*vn(1,2)
            vn(5,1) = pax*vn(2,1) - pcx*vn(2,2) &
               + 1.0_dp*oo2z*(vn(1,1) - vn(1,2))
            vn(6,1) = pax*vn(3,1) - pcx*vn(3,2)
            vn(7,1) = pax*vn(4,1) - pcx*vn(4,2)
            vn(8,1) = pay*vn(3,1) - pcy*vn(3,2) &
               + 1.0_dp*oo2z*(vn(1,1) - vn(1,2))
            vn(9,1) = pay*vn(4,1) - pcy*vn(4,2)
            vn(10,1) = paz*vn(4,1) - pcz*vn(4,2) &
               + 1.0_dp*oo2z*(vn(1,1) - vn(1,2))
            ! --- m = 0 ---
            vn(1,0) = vpref*f(0)
            vn(2,0) = pax*vn(1,0) - pcx*vn(1,1)
            vn(3,0) = pay*vn(1,0) - pcy*vn(1,1)
            vn(4,0) = paz*vn(1,0) - pcz*vn(1,1)
            vn(5,0) = pax*vn(2,0) - pcx*vn(2,1) &
               + 1.0_dp*oo2z*(vn(1,0) - vn(1,1))
            vn(6,0) = pax*vn(3,0) - pcx*vn(3,1)
            vn(7,0) = pax*vn(4,0) - pcx*vn(4,1)
            vn(8,0) = pay*vn(3,0) - pcy*vn(3,1) &
               + 1.0_dp*oo2z*(vn(1,0) - vn(1,1))
            vn(9,0) = pay*vn(4,0) - pcy*vn(4,1)
            vn(10,0) = paz*vn(4,0) - pcz*vn(4,1) &
               + 1.0_dp*oo2z*(vn(1,0) - vn(1,1))
            vn(11,0) = pax*vn(5,0) - pcx*vn(5,1) &
               + 2.0_dp*oo2z*(vn(2,0) - vn(2,1))
            vn(12,0) = pax*vn(6,0) - pcx*vn(6,1) &
               + 1.0_dp*oo2z*(vn(3,0) - vn(3,1))
            vn(13,0) = pax*vn(7,0) - pcx*vn(7,1) &
               + 1.0_dp*oo2z*(vn(4,0) - vn(4,1))
            vn(14,0) = pax*vn(8,0) - pcx*vn(8,1)
            vn(15,0) = pax*vn(9,0) - pcx*vn(9,1)
            vn(16,0) = pax*vn(10,0) - pcx*vn(10,1)
            vn(17,0) = pay*vn(8,0) - pcy*vn(8,1) &
               + 2.0_dp*oo2z*(vn(3,0) - vn(3,1))
            vn(18,0) = pay*vn(9,0) - pcy*vn(9,1) &
               + 1.0_dp*oo2z*(vn(4,0) - vn(4,1))
            vn(19,0) = pay*vn(10,0) - pcy*vn(10,1)
            vn(20,0) = paz*vn(10,0) - pcz*vn(10,1) &
               + 2.0_dp*oo2z*(vn(4,0) - vn(4,1))

            do k = 1, 20
               vn0(k) = vn(k,0)
            end do

            vtmp(1) = abx*vn0(5) &
               + vn0(11)
            vtmp(2) = abx*vn0(6) &
               + vn0(12)
            vtmp(3) = abx*vn0(7) &
