         sx(1,4) = pbx*sx(1,3) + 1.0_dp*oo2z*sx(0,3) + 3.0_dp*oo2z*sx(1,2)
         sx(2,4) = pbx*sx(2,3) + 2.0_dp*oo2z*sx(1,3) + 3.0_dp*oo2z*sx(2,2)
