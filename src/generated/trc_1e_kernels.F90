      real(dp) :: sx(0:0,0:2), sy(0:0,0:2), sz(0:0,0:2)
      real(dp) :: tx(0:0,0:0), ty(0:0,0:0), tz(0:0,0:0)
      real(dp) :: vn(1,0:0), vn0(1), vtmp(1)
