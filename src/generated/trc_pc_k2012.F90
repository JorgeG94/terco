                                           + kbc(1 + ib + 1*ic)
            end do
         end do
         do id = 0, 5
            do ib = 0, 0
               !$acc atomic update
               jmat(idens, nuj + ib, sigl + id) = jmat(idens, nuj + ib, sigl + id) &
                                           + kbd(1 + ib + 1*id)
            end do
         end do

         end do   ! idens
