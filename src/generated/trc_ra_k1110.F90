         vbuf(2) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(11) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(20) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3
         t1 = vbuf(5); t2 = vbuf(14); t3 = vbuf(23)
         vbuf(5) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(14) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(23) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3
         t1 = vbuf(8); t2 = vbuf(17); t3 = vbuf(26)
         vbuf(8) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(17) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(26) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3
         t1 = vbuf(3); t2 = vbuf(12); t3 = vbuf(21)
         vbuf(3) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(12) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(21) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3
         t1 = vbuf(6); t2 = vbuf(15); t3 = vbuf(24)
         vbuf(6) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(15) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(24) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3
         t1 = vbuf(9); t2 = vbuf(18); t3 = vbuf(27)
         vbuf(9) = rot(1,1)*t1 + rot(1,2)*t2 + rot(1,3)*t3
         vbuf(18) = rot(2,1)*t1 + rot(2,2)*t2 + rot(2,3)*t3
         vbuf(27) = rot(3,1)*t1 + rot(3,2)*t2 + rot(3,3)*t3

         ! Single column on every side: the canonical enumeration and the
         ! degeneracy weights are the pair-level ones.
         dij = .not. same_ab
         dkl = .not. same_cd
         dpq = .not. same_pair
         mui = ao_off(si); nuj = ao_off(sj); lamk = ao_off(sk); sigl = ao_off(sl)


         !
         ! BLOCK-ACCUMULATED DIGESTION.
         !
         ! The previous form did six atomic updates and six scattered `dmat`
         ! loads PER CARTESIAN COMPONENT.  For (pp|pp) that is 81 components x
         ! 6 = 486 of each, per quartet, even though only six small BLOCKS of
         ! jmat and six of dmat are ever touched.
         !
         ! gpu4pyscf's rys_contract_jk.cu does it the other way round: pull the
         ! density blocks into registers once (`load_dm`), contract every
         ! component against them there (`dot_dm`), and write each output block
         ! out once.  Same arithmetic, an order of magnitude less traffic --
         ! 54 loads and 54 atomics for (pp|pp) instead of 486.
         !
         ! The degeneracy factors are per-quartet, so they collapse into one
         ! scalar applied as the components are consumed.
         !
         wq = 1.0_dp
         if (.not. dij) wq = wq*0.5_dp
         if (.not. dkl) wq = wq*0.5_dp
         if (.not. dpq) wq = wq*0.5_dp

         !
         ! J-ONLY DIGESTION, for kfac = 0 (a pure LDA/GGA functional, or the
         ! Coulomb-only pass of the response equations). The exchange half of
         ! the general digestion below is then four density-block gathers and
         ! four multiply-adds per component that all come out exactly
         ! 0.0_dp, plus four accumulator blocks held live for nothing. This
         ! copy drops them; its J statements are the general branch's,
         ! character for character, so every jmat element is bit-identical
         ! to what that branch would have produced. A separate branch and not
         ! a test inside the component loop: guarding the K updates per
         ! component was measured 22% slower on a hybrid (w20/6-31G* B3LYP,
         ! V100), because the test sits on the branch that is always taken.
         ! kfac is uniform over the launch, so no warp diverges here.
         !
         if (kfac == 0.0_dp) then
         do idens = 1, ndens

         do ib = 0, 2
            do ia = 0, 2
               dab(1 + ia + 3*ib) = dmat(idens, mui + ia, nuj + ib)
               jab(1 + ia + 3*ib) = 0.0_dp
            end do
         end do
         id = 0
            do ic = 0, 2
               dcd(1 + ic + 3*id) = dmat(idens, lamk + ic, sigl + id)
               jcd(1 + ic + 3*id) = 0.0_dp
            end do

         ! Spelled differently from the general branch, on purpose, and with
         ! the same arithmetic: the component index in closed form and the
         ! scaled integral inline rather than in `idx` and `sc`. A second
         ! counted loop fails to translate the Rys launch under nvfortran
         ! 26.5 ("Missing increment value", trc_pc_rys1102).
         id = 0
         do ic = 0, 2
         do ib = 0, 2
         do ia = 0, 2
            jab(1 + ia + 3*ib) = jab(1 + ia + 3*ib) &
                                    + 4.0_dp*jfac*(wq*vbuf(1 + ia + 3*ib + 9*ic + 27*id)) &
                                    *dcd(1 + ic + 3*id)
            jcd(1 + ic + 3*id) = jcd(1 + ic + 3*id) &
                                    + 4.0_dp*jfac*(wq*vbuf(1 + ia + 3*ib + 9*ic + 27*id)) &
                                    *dab(1 + ia + 3*ib)
         end do
         end do
         end do

         do ib = 0, 2
            do ia = 0, 2
               !$acc atomic update
               jmat(idens, mui + ia, nuj + ib) = jmat(idens, mui + ia, nuj + ib) &
                                          + jab(1 + ia + 3*ib)
            end do
         end do
         id = 0
            do ic = 0, 2
               !$acc atomic update
               jmat(idens, lamk + ic, sigl + id) = jmat(idens, lamk + ic, sigl + id) &
                                            + jcd(1 + ic + 3*id)
            end do

         end do   ! idens
         else

         !
         ! BATCHED OVER DENSITIES.
         !
         ! The integral is formed once, in `vbuf`, and contracted against every
         ! density in the batch. In the coupled-perturbed equations that is the
         ! difference between one integral pass and a hundred: the dynamic
         ! polarizabilities need nine perturbations times twelve imaginary
         ! frequencies, each a Fock build on a different response density.
         !
         ! The density loop is OUTSIDE the block accumulators, not inside, and
         ! that is the whole trick. The six blocks are zeroed, filled and
         ! written per density, so REGISTER PRESSURE DOES NOT GROW WITH THE
         ! BATCH -- holding N sets of blocks at once would have cost 54 more
         ! doubles per density at (pp|pp) and 216 at (dd|dd), on a kernel
         ! already spilling. Cost is `eval + ndens*digest`, and the ceiling is
         ! one over the digestion fraction.
         !
         do idens = 1, ndens

         do ib = 0, 2
            do ia = 0, 2
               dab(1 + ia + 3*ib) = dmat(idens, mui + ia, nuj + ib)
               jab(1 + ia + 3*ib) = 0.0_dp
            end do
         end do
         do id = 0, 0
            do ic = 0, 2
               dcd(1 + ic + 3*id) = dmat(idens, lamk + ic, sigl + id)
               jcd(1 + ic + 3*id) = 0.0_dp
            end do
         end do
         do ic = 0, 2
            do ia = 0, 2
               dac(1 + ia + 3*ic) = dmat(idens, mui + ia, lamk + ic)
               kac(1 + ia + 3*ic) = 0.0_dp
            end do
         end do
         do id = 0, 0
            do ia = 0, 2
               dad(1 + ia + 3*id) = dmat(idens, mui + ia, sigl + id)
               kad(1 + ia + 3*id) = 0.0_dp
            end do
         end do
         do ic = 0, 2
            do ib = 0, 2
               dbc(1 + ib + 3*ic) = dmat(idens, nuj + ib, lamk + ic)
               kbc(1 + ib + 3*ic) = 0.0_dp
            end do
         end do
         do id = 0, 0
            do ib = 0, 2
               dbd(1 + ib + 3*id) = dmat(idens, nuj + ib, sigl + id)
               kbd(1 + ib + 3*id) = 0.0_dp
            end do
         end do

         idx = 0
         do id = 0, 0
         do ic = 0, 2
         do ib = 0, 2
         do ia = 0, 2
            idx = idx + 1
            sc = wq*vbuf(idx)
            jab(1 + ia + 3*ib) = jab(1 + ia + 3*ib) &
                                    + 4.0_dp*jfac*sc*dcd(1 + ic + 3*id)
            jcd(1 + ic + 3*id) = jcd(1 + ic + 3*id) &
                                    + 4.0_dp*jfac*sc*dab(1 + ia + 3*ib)
            kac(1 + ia + 3*ic) = kac(1 + ia + 3*ic) &
                                    - kfac*sc*dbd(1 + ib + 3*id)
            kad(1 + ia + 3*id) = kad(1 + ia + 3*id) &
                                    - kfac*sc*dbc(1 + ib + 3*ic)
            kbc(1 + ib + 3*ic) = kbc(1 + ib + 3*ic) &
                                    - kfac*sc*dad(1 + ia + 3*id)
            kbd(1 + ib + 3*id) = kbd(1 + ib + 3*id) &
                                    - kfac*sc*dac(1 + ia + 3*ic)
         end do
         end do
         end do
         end do

         do ib = 0, 2
            do ia = 0, 2
               !$acc atomic update
               jmat(idens, mui + ia, nuj + ib) = jmat(idens, mui + ia, nuj + ib) &
                                          + jab(1 + ia + 3*ib)
            end do
         end do
         do id = 0, 0
            do ic = 0, 2
               !$acc atomic update
               jmat(idens, lamk + ic, sigl + id) = jmat(idens, lamk + ic, sigl + id) &
                                            + jcd(1 + ic + 3*id)
            end do
         end do
         do ic = 0, 2
            do ia = 0, 2
               !$acc atomic update
               jmat(idens, mui + ia, lamk + ic) = jmat(idens, mui + ia, lamk + ic) &
                                           + kac(1 + ia + 3*ic)
            end do
         end do
         do id = 0, 0
            do ia = 0, 2
               !$acc atomic update
               jmat(idens, mui + ia, sigl + id) = jmat(idens, mui + ia, sigl + id) &
                                           + kad(1 + ia + 3*id)
            end do
         end do
         do ic = 0, 2
            do ib = 0, 2
               !$acc atomic update
               jmat(idens, nuj + ib, lamk + ic) = jmat(idens, nuj + ib, lamk + ic) &
                                           + kbc(1 + ib + 3*ic)
            end do
         end do
         do id = 0, 0
            do ib = 0, 2
               !$acc atomic update
               jmat(idens, nuj + ib, sigl + id) = jmat(idens, nuj + ib, sigl + id) &
                                           + kbd(1 + ib + 3*id)
            end do
         end do

         end do   ! idens
         end if

   end subroutine rasi1110
