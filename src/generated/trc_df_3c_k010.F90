      ip = ord_p(int(mod(t, int(npc, int64))) + 1)
      kk = ord_a(int(t/npc) + 1)
      ii = p_i(ip); jj = p_j(ip)
      abx = sh_r(1, ii) - sh_r(1, jj)
      aby = sh_r(2, ii) - sh_r(2, jj)
      abz = sh_r(3, ii) - sh_r(3, jj)
      o = pp_off(ip)

      call df_3c010(pp_n(ip), pp_z(o + 1:o + pp_n(ip)), pp_k(o + 1:o + pp_n(ip)), &
