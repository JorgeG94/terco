!
! The spherical (pure) AO space, on top of a basis that is -- and stays --
! Cartesian underneath.
!
! WHAT THIS IS FOR
! -----------------
! Every kernel, generator and screen in terco computes Cartesian integrals,
! unchanged, as docs/GENERATORS.md says they should stay. def2 and most
! other modern bases are defined SPHERICAL, though, and a Cartesian run of
! them is not the same basis pyscf's default (cart=False) or GAMESS mean
! when they say "def2-SVP" -- it is pyscf's cart=True basis instead. This
! module is the boundary: it turns a Cartesian (nao, nao) matrix into a
! spherical (nao_sph, nao_sph) one and back, so the SCF (trc_scf.F90) can
! run its own matrices -- S, H, D, F, C, eps -- at nao_sph while every
! integral underneath them is still built at nao.
!
! THE TRANSFORM IS A SET OF TINY, PER-SHELL BLOCKS
! --------------------------------------------------
! T (nao, nao_sph) is block-diagonal: shell i's block is (ncart(l_i),
! 2*l_i+1), at most (15, 9) through g, and every entry outside the
! block-diagonal is an EXACT zero -- a d orbital's spherical combination
! never reaches into a neighbouring shell's Cartesian components. Forming T
! densely and running M_sph = T^T M_cart T as two (nao_sph, nao) and (nao,
! nao_sph) GEMMs would multiply by that zero nshell-1 times out of nshell
! for every shell pair; `cart_to_sph`/`sph_to_cart` below instead walk shell
! PAIRS directly and do one (nsph_i, ncart_i) x (ncart_i, ncart_j) x
! (ncart_j, nsph_j) contraction per pair, reading SPH_T (trc_sph_tables.F90,
! generated by scripts/gen_sph.py) for each shell's own tiny block. Cost is
! O(nshell^2 * ncart^3) at worst (two d shells, 6^3), which is negligible
! next to the O(nao^4) Fock build it sits beside -- see check_spherical's
! own timing comparison for the measured ratio on a 1000+ AO case.
!
! WHERE THE TRANSFORMS RUN
! --------------------------
! On the device, where S, H, D and F already live for the whole SCF
! iteration (trc_scf.F90's module header: "every matrix resident on the
! device"). `cart_to_sph`/`sph_to_cart` are `do concurrent` over a FLATTENED
! shell-pair index, for the same reason trc_decontract.F90's
! `expand_kernel`/`fold_kernel` are: a two-dimensional `do concurrent`
! header did not give every iteration its own accumulator under nvfortran
! despite a `local(...)` clause naming it, and the transform came back
! wrong by order one while the identical host loop was exact -- see that
! module's own comment on `expand_kernel`. Flattening to one dimension is
! the fix that was measured to work, so it is used here from the start
! rather than rediscovered. SPH_T itself is a module PARAMETER (a
! compile-time constant, like trc_collocation_table.inc's CC_NX/CC_NY/CC_NZ)
! and needs no `!$acc declare`/`update device` of its own.
!
! NORMALISATION AND NO FURTHER RESCALE
! ---------------------------------------
! scripts/gen_sph.py's own header derives this exactly: terco's Cartesian
! convention (libcint's "sp"-normalised one, per commit 0a3985f) is already
! what the real-solid-harmonic closed form assumes, so SPH_T needs no
! GAMESS-style per-component diagonal folded in anywhere. That diagonal
! (trc_ao_norm.F90's TRC_AO_NORM_UNIT) is an orthogonal, unrelated axis and
! the two do not compose -- see trc_capi.F90's AO classification header for
! why a UNIT-normalised spherical basis is refused rather than silently
! wrong.
!
! THE XC PATH
! -----------
! trc_xc_rks/uks (src/xc/trc_xc.F90) evaluate Cartesian AO values on the
! quadrature grid and contract them against a Cartesian density -- untouched
! by this feature. The SCF driver keeps a D_cart buffer, built from D_sph by
! `sph_to_cart` once per iteration, and hands THAT to the XC integrator and
! to the Fock build alike, rather than transforming grid AO values to
! spherical. Two reasons this is the cleaner of the two options the
! milestone plan raised: (1) it is one transform shared by the Coulomb/
! exchange build and the XC grid, instead of a second, separate one for the
! grid; (2) `shell_collocate` (src/xc/trc_collocation.F90) evaluates a
! shell's CARTESIAN components directly from its own flat table
! (trc_collocation_table.inc) with no AO-space indirection at all today, and
! teaching it to also know about nao_sph would duplicate exactly the
! block structure this module already owns.
!
module trc_sph
   use trc_boys, only: dp
   use trc_api, only: trc_basis_t
   use trc_sph_tables, only: SPH_T
   implicit none
   private

   public :: sph_cart_to_sph, sph_sph_to_cart

contains

   !
   ! M_sph := T^T M_cart T. Wrapper over the explicit-shape driver, for a
   ! caller holding a `trc_basis_t` rather than its raw shell arrays --
   ! trc_api.F90's own `trc_1e`/`trc_multipoles` are the same shape of
   ! wrapper for the same reason (explicit extents, declared first, so
   ! nvfortran is not walking an assumed-shape descriptor per launch).
   !
   subroutine sph_cart_to_sph(b, mcart, msph)
      type(trc_basis_t), intent(in) :: b
      real(dp), intent(in)  :: mcart(b%nao, b%nao)
      real(dp), intent(out) :: msph(b%nao_sph, b%nao_sph)
      call cart_to_sph_driver(b%nshell, b%sh_l, b%sh_ao, b%sh_ao_sph, &
                              b%nao, b%nao_sph, mcart, msph)
   end subroutine sph_cart_to_sph

   subroutine sph_sph_to_cart(b, msph, mcart)
      !! M_cart := T M_sph T^T.
      type(trc_basis_t), intent(in) :: b
      real(dp), intent(in)  :: msph(b%nao_sph, b%nao_sph)
      real(dp), intent(out) :: mcart(b%nao, b%nao)
      call sph_to_cart_driver(b%nshell, b%sh_l, b%sh_ao, b%sh_ao_sph, &
                              b%nao, b%nao_sph, msph, mcart)
   end subroutine sph_sph_to_cart

   !
   ! M_sph(bi:bi+nsi-1, bj:bj+nsj-1) := Ti^T * M_cart(ai:ai+nci-1, aj:aj+ncj-1) * Tj
   ! for every shell pair (i, j), Ti/Tj the (ncart, nsph) blocks SPH_T(:,:,l)
   ! carries for that shell's own angular momentum. General rather than
   ! symmetric-only: it is run on S, H, D and F alike, and only D and F
   ! happen to be symmetric -- a caller handing it a nonsymmetric matrix
   ! (there is none today) would still get the right answer.
   !
   subroutine cart_to_sph_driver(nshell, sh_l, sh_ao, sh_ao_sph, nao_c, nao_s, mcart, msph)
      integer,  intent(in)  :: nshell, nao_c, nao_s
      integer,  intent(in)  :: sh_l(nshell), sh_ao(nshell), sh_ao_sph(nshell)
      real(dp), intent(in)  :: mcart(nao_c, nao_c)
      real(dp), intent(out) :: msph(nao_s, nao_s)
      integer :: ij, ish, jsh, li, lj, nci, ncj, nsi, nsj, ai, aj, bi, bj
      integer :: p, q, r, s
      real(dp) :: acc, inner

      ! Flattened shell-pair index -- see this module's own header on why
      ! `do concurrent(jsh=..., ish=...)` is not used here.
      do concurrent(ij=0:nshell*nshell - 1) local(ish, jsh, li, lj, nci, ncj, nsi, nsj, ai, aj, bi, bj, p, q, r, s, acc, inner)
         jsh = ij/nshell + 1
         ish = ij - (jsh - 1)*nshell + 1
         li = sh_l(ish); lj = sh_l(jsh)
         nci = (li + 1)*(li + 2)/2; ncj = (lj + 1)*(lj + 2)/2
         nsi = 2*li + 1; nsj = 2*lj + 1
         ai = sh_ao(ish); aj = sh_ao(jsh)
         bi = sh_ao_sph(ish); bj = sh_ao_sph(jsh)
         do s = 1, nsj
            do r = 1, nsi
               acc = 0.0_dp
               do q = 1, ncj
                  inner = 0.0_dp
                  do p = 1, nci
                     inner = inner + SPH_T(p, r, li)*mcart(ai + p - 1, aj + q - 1)
                  end do
                  acc = acc + inner*SPH_T(q, s, lj)
               end do
               msph(bi + r - 1, bj + s - 1) = acc
            end do
         end do
      end do
   end subroutine cart_to_sph_driver

   !
   ! M_cart(ai:ai+nci-1, aj:aj+ncj-1) := Ti * M_sph(bi:bi+nsi-1, bj:bj+nsj-1) * Tj^T,
   ! the reverse contraction, same shell-pair loop.
   !
   subroutine sph_to_cart_driver(nshell, sh_l, sh_ao, sh_ao_sph, nao_c, nao_s, msph, mcart)
      integer,  intent(in)  :: nshell, nao_c, nao_s
      integer,  intent(in)  :: sh_l(nshell), sh_ao(nshell), sh_ao_sph(nshell)
      real(dp), intent(in)  :: msph(nao_s, nao_s)
      real(dp), intent(out) :: mcart(nao_c, nao_c)
      integer :: ij, ish, jsh, li, lj, nci, ncj, nsi, nsj, ai, aj, bi, bj
      integer :: p, q, r, s
      real(dp) :: acc, inner

      do concurrent(ij=0:nshell*nshell - 1) local(ish, jsh, li, lj, nci, ncj, nsi, nsj, ai, aj, bi, bj, p, q, r, s, acc, inner)
         jsh = ij/nshell + 1
         ish = ij - (jsh - 1)*nshell + 1
         li = sh_l(ish); lj = sh_l(jsh)
         nci = (li + 1)*(li + 2)/2; ncj = (lj + 1)*(lj + 2)/2
         nsi = 2*li + 1; nsj = 2*lj + 1
         ai = sh_ao(ish); aj = sh_ao(jsh)
         bi = sh_ao_sph(ish); bj = sh_ao_sph(jsh)
         do q = 1, ncj
            do p = 1, nci
               acc = 0.0_dp
               do s = 1, nsj
                  inner = 0.0_dp
                  do r = 1, nsi
                     inner = inner + SPH_T(p, r, li)*msph(bi + r - 1, bj + s - 1)
                  end do
                  acc = acc + inner*SPH_T(q, s, lj)
               end do
               mcart(ai + p - 1, aj + q - 1) = acc
            end do
         end do
      end do
   end subroutine sph_to_cart_driver

end module trc_sph
