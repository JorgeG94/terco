#!/usr/bin/env python3
"""Static architecture checker for terco (see docs/CODE_STRUCTURE.md).

    python3 tools/archcheck.py                     # fail on NEW violations
    python3 tools/archcheck.py --all               # list every violation
    python3 tools/archcheck.py --rule short-name   # one rule only
    python3 tools/archcheck.py --summary           # counts per rule
    python3 tools/archcheck.py --score             # the code score, by rule and file
    python3 tools/archcheck.py --update-baseline   # accept the current state

Rules (thresholds and word lists are the constants below):

    layer-up        a module uses a module in a higher layer
    module-prefix   a module name lacks the trc_ prefix
    proc-prefix     a public procedure does not start with its module's name
    short-name      a procedure or variable name contains an abbreviation
                    from SHORT_NAMES (ctx, cfg, dens, ...); a bind(c)
                    procedure's dummy arguments are C ABI names, exempt
    proc-length     a procedure is longer than MAX_PROC_LINES
    arg-count       a procedure has more than MAX_ARGS dummy arguments
                    (`routine seq` item routines and thin `do concurrent`
                    kernel drivers excepted; see KERNEL_HOST_STMTS)
    no-pointer      a declaration with the POINTER attribute (or a POINTER
                    statement), outside the places the language forces one:
                    the C ABI (POINTER_ALLOWED) and json-fortran's
                    `type(json_value), pointer`. Owners hold their parts by
                    value or as allocatable components and pass them down
                    as arguments instead

Results are deterministic: same tree, same output, sorted. The check compares
against tools/arch_baseline.json and fails only on violations that are new,
or on a measured one (length, argument count) that grew. Existing debt does
not block unrelated work; `--update-baseline` records paid-off debt so it
cannot come back.

Regex based, like tools/modmap.py (which it reuses for parsing modules). It
relies on terco's style: one declaration per statement with `::`.
"""
import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import modmap  # noqa: E402

ROOT = modmap.ROOT
BASELINE = Path(__file__).resolve().parent / "arch_baseline.json"

LAYERS = ["core", "basis", "grid", "eri", "xc", "solvation", "post_hf",
          "scf", "api", "opt", "app"]
MAX_PROC_LINES = 300
MAX_ARGS = 8
KERNEL_HOST_STMTS = 10
#: A procedure with a `do concurrent` and at most this many executable
#: statements outside its `do concurrent` bodies is a kernel driver: a thin
#: launch around same-module item routines, which must take explicit-shape
#: arrays (AGENTS.md: no derived-type components read inside `do
#: concurrent`), so it is exempt from arg-count like the item routines.
#: trc_-prefixed procedures (the library's entry points) never are.

# Whole `_`-separated words that are not allowed inside a name. The value is
# what to write instead. Domain vocabulary (scf, eri, dft, diis, xc) is not
# listed, so it stays legal. Edit this table to change the policy.
SHORT_NAMES = {
    "ctx": "context", "cfg": "config", "blk": "block", "tmp": "temporary",
    "dens": "density", "mat": "matrix", "thr": "threshold",
    "iter": "iteration", "calc": "calculate", "asm": "assemble",
    "idx": "index", "val": "value", "arr": "array", "buf": "buffer",
}

# Exempt from everything except layer-up and no-pointer: machine-translated
# functionals, and any file whose first 40 lines have a comment saying
# "Generated by ..." or "do not edit". src/generated/ is never scanned.
EXEMPT = ("src/xc/functionals/",)

# Where a POINTER is the language's, not a design choice: the C ABI turns
# handles into Fortran objects with c_f_pointer. json-fortran's own API
# (`type(json_value), pointer`) is allowed everywhere, by type.
POINTER_ALLOWED = ("src/api/", "src/opt/trc_opt_capi.F90")
RE_POINTER_ATTR = re.compile(r"\bpointer\b", re.I)
RE_POINTER_STMT = re.compile(r"^\s*pointer\b", re.I)
RE_JSON_VALUE = re.compile(r"^\s*type\s*\(\s*json_value\s*\)", re.I)

RE_DECL = re.compile(
    r"^\s*(?:integer|real|logical|complex|character|double\s+precision|"
    r"type\s*\(|class\s*\(|procedure\s*\()", re.I)


# Debt points per violation. Lower is better; zero means clean. Weights say
# what hurts most: a layering leak costs ten renames. Length and argument
# count grow with how far past the limit they are (arguments capped at 30
# points per procedure).
WEIGHTS = {"layer-up": 10, "module-prefix": 5, "no-pointer": 5, "proc-prefix": 1,
           "short-name": 1}


def points(v):
    if v.rule == "arg-count":
        return min(2 * (v.measure - MAX_ARGS), 30)  # capped: one giant callback is not 150 points
    if v.rule == "proc-length":
        return 5 + (v.measure - MAX_PROC_LINES) // 10
    return WEIGHTS[v.rule]


class Violation:
    def __init__(self, rule, path, scope, detail, line, measure, message):
        self.rule, self.path, self.scope = rule, str(path), scope
        self.detail, self.line, self.measure = detail, line, measure
        self.message = message

    @property
    def key(self):
        return f"{self.rule}|{self.path}|{self.scope}|{self.detail}"


RE_GENERATED = re.compile(r"generated by|do not edit", re.I)


def exempt(path):
    """Translated functionals, and any file whose header says it is generated."""
    if str(path).startswith(EXEMPT):
        return True
    with open(ROOT / path, errors="replace") as handle:
        head = [next(handle, "") for _ in range(40)]
    return any(l.lstrip().startswith("!") and RE_GENERATED.search(l)
               for l in head)


def split_top(text):
    """Split on commas that are not inside parentheses."""
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [p.strip() for p in out if p.strip()]


def declared_names(statement):
    """Entity names of a `type :: a, b(n) = 1` declaration (empty otherwise)."""
    if "::" not in statement or not RE_DECL.match(statement):
        return []
    names = []
    for part in split_top(statement.split("::", 1)[1]):
        m = re.match(r"(\w+)", part)
        if m:
            names.append(m.group(1).lower())
    return names


def header_args(statement, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*\(([^)]*)\)", statement, re.I)
    if not m:
        return []
    return [a.strip().lower() for a in m.group(1).split(",")
            if a.strip() and a.strip() != "*"]


RE_DO_CONCURRENT = re.compile(r"^\s*(\w+\s*:\s*)?do\s+concurrent\b", re.I)
RE_DO = re.compile(r"^\s*(\w+\s*:\s*)?do\b", re.I)
RE_END_DO = re.compile(r"^\s*end\s*do\b", re.I)
RE_SPEC = re.compile(r"^\s*(use|implicit|import|integer|real|logical|character|complex|"
                     r"double|type\s*\(|class\s*\(|dimension|parameter|save|external|"
                     r"intrinsic|procedure|contains)\b", re.I)


def track_kernel_shape(proc, st, is_decl):
    """Count, per procedure, the executable statements outside every `do
    concurrent` body, and whether it has one at all (is_kernel_driver)."""
    if is_decl or RE_SPEC.match(st):
        return
    if RE_DO_CONCURRENT.match(st):
        proc["has_dc"] = True
        proc["dos"].append("dc")
        return
    if RE_END_DO.match(st):
        if proc["dos"]:
            proc["dos"].pop()
        return
    inside_dc = "dc" in proc["dos"]
    if RE_DO.match(st):
        proc["dos"].append("do")
    if not inside_dc:
        proc["host_exec"] += 1


def is_kernel_driver(proc):
    # A trc_-prefixed procedure is a library entry point, not a thin launch,
    # however short it is; the caller excludes those by name.
    return proc.get("has_dc", False) and proc.get("host_exec", 0) <= KERNEL_HOST_STMTS


def scan_procedures(path):
    """Yield dicts: name, kind, start, end, args, names (declared), device."""
    text = path.read_text(errors="replace")
    stack, done, iface, pending_acc = [], [], 0, False
    unit, outer = None, []
    for ln, st in modmap.logical_lines(text):
        if st.lstrip().startswith("!"):
            if modmap.RE_ACC_SEQ.match(st):
                if stack:
                    stack[-1]["device"] = True
                else:
                    pending_acc = True
            continue
        if not st.strip():
            continue
        if not stack:
            mu = modmap.RE_MOD.match(st)
            if mu and unit is None:
                unit = mu.group(2).lower()
                continue
            if unit and modmap.RE_END_MOD.match(st):
                if outer:
                    done.append(dict(name=unit, kind="module", start=1, end=1,
                                     args=[], names=outer, device=False,
                                     container=True))
                unit, outer = None, []
                continue
        if modmap.RE_IFACE.match(st):
            iface += 1
            continue
        if re.match(r"^\s*end\s+interface\b", st, re.I):
            iface = max(0, iface - 1)
            continue
        if iface:
            continue
        m = modmap.RE_PROC.match(st)
        if (m and not re.match(r"^\s*(end|module\s+procedure)\b", st, re.I)):
            name = m.group(3).lower()
            stack.append(dict(name=name, kind=m.group(2).lower(), start=ln,
                              end=ln, args=header_args(st, m.group(3)),
                              names=[], device=pending_acc, has_dc=False,
                              host_exec=0, dos=[],
                              bind_c=bool(re.search(r"\bbind\s*\(\s*c\b", st, re.I))))
            pending_acc = False
            continue
        if stack:
            if modmap.RE_END_PROC.match(st):
                proc = stack.pop()
                proc["end"] = ln
                done.append(proc)
                continue
            if modmap.RE_ACC_SEQ.match(st):
                stack[-1]["device"] = True
            decl = declared_names(st)
            stack[-1]["names"].extend((n, ln) for n in decl)
            track_kernel_shape(stack[-1], st, bool(decl))
        elif unit:
            outer.extend((n, ln) for n in declared_names(st))
    return done


def pointer_names(statement):
    """Names a statement gives the POINTER attribute (empty if none)."""
    if RE_POINTER_STMT.match(statement):
        rest = statement.split("::", 1)[1] if "::" in statement else RE_POINTER_STMT.sub("", statement)
        return [p.split("(")[0].strip().lower() for p in split_top(rest)] or ["?"]
    if "::" not in statement or not RE_DECL.match(statement):
        return []
    if not RE_POINTER_ATTR.search(statement.split("::", 1)[0]):
        return []
    if RE_JSON_VALUE.match(statement):
        return []
    return declared_names(statement) or ["?"]


def check_pointers(found):
    """The no-pointer rule over every scanned file, generated headers included."""
    for path in source_files():
        rel = path.relative_to(ROOT)
        if str(rel).startswith(POINTER_ALLOWED):
            continue
        for ln, st in modmap.logical_lines(path.read_text(errors="replace")):
            if st.lstrip().startswith("!"):
                continue
            names = pointer_names(st)
            if names:
                what = ", ".join(names)
                found.append(Violation(
                    "no-pointer", rel, what, str(ln), ln, 1,
                    f"{what}: POINTER outside the C ABI and json-fortran; hold it by value "
                    f"or as an allocatable component and pass it as an argument"))


def source_files():
    out = []
    for base in ("app", "src"):
        for p in sorted((ROOT / base).rglob("*")):
            parts = p.relative_to(ROOT).parts
            if (p.suffix in modmap.EXTS and p.is_file()
                    and "vendor" not in parts and "generated" not in parts):
                out.append(p)
    return out


def bad_words(name):
    return sorted(t for t in name.lower().split("_") if t in SHORT_NAMES)


def check():
    units = modmap.collect()
    found = []
    rank = {l: i for i, l in enumerate(LAYERS)}

    for unit in sorted(units.values(), key=lambda u: (str(u.path), u.name)):
        path = unit.path
        # layer-up
        for dep in sorted(unit.uses):
            other = units.get(dep)
            if (other and unit.layer in rank and other.layer in rank
                    and rank[other.layer] > rank[unit.layer]):
                found.append(Violation(
                    "layer-up", path, unit.name, dep, unit.line, 1,
                    f"{unit.name} ({unit.layer}) uses {dep} ({other.layer})"))
        if exempt(path):
            continue
        if not unit.name.startswith("trc_"):
            found.append(Violation(
                "module-prefix", path, unit.name, "", unit.line, 1,
                f"module {unit.name} lacks the trc_ prefix"))
        stem = unit.name[4:] if unit.name.startswith("trc_") else unit.name
        for proc in sorted(unit.procs.values(), key=lambda p: p.line):
            if (unit.kind == "module" and proc.public
                    and not (proc.name.startswith("trc_")
                             or proc.name == stem
                             or proc.name.startswith(stem + "_"))):
                found.append(Violation(
                    "proc-prefix", path, f"{unit.name}::{proc.name}", "",
                    proc.line, 1,
                    f"public {proc.name} should start with {stem}_"))

    for path in source_files():
        rel = path.relative_to(ROOT)
        if exempt(rel):
            continue
        for proc in scan_procedures(path):
            scope = f"{proc['name']}"
            length = proc["end"] - proc["start"] + 1
            container = proc.get("container", False)
            if length > MAX_PROC_LINES and not container:
                found.append(Violation(
                    "proc-length", rel, scope, "", proc["start"], length,
                    f"{scope} is {length} lines (limit {MAX_PROC_LINES})"))
            kernel_driver = is_kernel_driver(proc) and not proc["name"].startswith("trc_")
            if len(proc["args"]) > MAX_ARGS and not proc["device"] and not kernel_driver:
                found.append(Violation(
                    "arg-count", rel, scope, "", proc["start"],
                    len(proc["args"]),
                    f"{scope} has {len(proc['args'])} arguments "
                    f"(limit {MAX_ARGS})"))
            seen = set()
            named = proc["names"] + ([] if container else [(proc["name"], proc["start"])])
            # A bind(c) procedure's dummy names are part of the C ABI (they
            # are the parameter names in include/terco.h), so they keep the
            # names C callers know.
            abi_names = set(proc["args"]) if proc.get("bind_c") else set()
            for name, line in named:
                if name in seen or name in abi_names:
                    continue
                seen.add(name)
                for word in bad_words(name):
                    found.append(Violation(
                        "short-name", rel, scope, name, line, 1,
                        f"{name} (in {scope}): spell out '{word}' as "
                        f"'{SHORT_NAMES[word]}'"))
    check_pointers(found)
    found.sort(key=lambda v: (v.rule, v.path, v.line, v.key))
    return found


def load_baseline():
    if not BASELINE.exists():
        return {}
    return json.loads(BASELINE.read_text())["violations"]


def save_baseline(found):
    data = {"version": 1,
            "violations": {v.key: v.measure
                           for v in sorted(found, key=lambda v: v.key)}}
    BASELINE.write_text(json.dumps(data, indent=0, sort_keys=True) + "\n")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--all", action="store_true", help="list every violation")
    ap.add_argument("--rule", action="append", help="only this rule (repeatable)")
    ap.add_argument("--summary", action="store_true", help="counts per rule")
    ap.add_argument("--score", action="store_true",
                    help="debt points by rule and by file")
    ap.add_argument("--top", type=int, default=12, help="files shown by --score")
    ap.add_argument("--update-baseline", action="store_true")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()

    found = check()
    if a.rule:
        found = [v for v in found if v.rule in a.rule]
    if a.update_baseline:
        if a.rule:
            sys.exit("--update-baseline records every rule; drop --rule")
        save_baseline(found)
        print(f"baseline written: {len(found)} violations")
        return 0

    base = load_baseline()
    new = [v for v in found if v.key not in base or v.measure > base[v.key]]
    gone = [k for k in base if k not in {v.key for v in found}
            and (not a.rule or k.split("|")[0] in a.rule)]

    if a.score:
        by_rule, by_file = Counter(), Counter()
        for v in found:
            by_rule[v.rule] += points(v)
            by_file[v.path] += points(v)
        total = sum(by_rule.values())
        print(f"code score: {total} debt points (0 is clean)\n")
        print(f"{'rule':<14}{'violations':>11}{'points':>8}{'share':>7}")
        counts = Counter(v.rule for v in found)
        for rule, pts in by_rule.most_common():
            print(f"{rule:<14}{counts[rule]:>11}{pts:>8}{100 * pts // max(total, 1):>6}%")
        print(f"\n{'worst files':<46}{'points':>7}")
        for path, pts in by_file.most_common(a.top):
            print(f"{path:<46}{pts:>7}")
        return 0
    if a.json:
        print(json.dumps([vars(v) for v in (found if a.all else new)], indent=1))
    elif a.summary:
        total, fresh = Counter(v.rule for v in found), Counter(v.rule for v in new)
        print(f"{'rule':<14}{'total':>7}{'new':>6}")
        for rule in sorted(total):
            print(f"{rule:<14}{total[rule]:>7}{fresh[rule]:>6}")
    else:
        for v in (found if a.all else new):
            print(f"{v.path}:{v.line}: [{v.rule}] {v.message}")
        print(f"\n{len(found)} violations, {len(found) - len(new)} in the "
              f"baseline, {len(new)} new, {len(gone)} fixed since the baseline.")
        if gone and not new:
            print("run --update-baseline to lock in the fixes.")
    return 1 if new else 0


if __name__ == "__main__":
    sys.exit(main())
