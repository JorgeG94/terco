"""Unit tests for tools/check_session_links.py (run with pytest)."""
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_session_links as csl  # noqa: E402


def git(repo, *args):
    subprocess.run(['git', *args], cwd=repo, check=True, capture_output=True)


def commit(repo, name, message):
    (repo / name).write_text(name)
    git(repo, 'add', name)
    git(repo, '-c', 'user.name=t', '-c', 'user.email=t@example.com', 'commit', '-m', message)


def make_repo(tmp_path):
    git(tmp_path, 'init', '-q', '-b', 'main')
    commit(tmp_path, 'a', 'base commit\n\nClaude-Session: https://claude.ai/code/session_old')
    git(tmp_path, 'tag', 'base')
    return tmp_path


def run(repo, monkeypatch):
    monkeypatch.chdir(repo)
    return csl.commit_hits('base', 'HEAD')


def test_clean_commits_pass(tmp_path, monkeypatch):
    repo = make_repo(tmp_path)
    commit(repo, 'b', 'a change\n\nCo-Authored-By: Someone <s@example.com>')
    assert run(repo, monkeypatch) == []


def test_trailer_is_caught(tmp_path, monkeypatch):
    repo = make_repo(tmp_path)
    commit(repo, 'b', 'a change\n\nClaude-Session: https://claude.ai/code/session_abc')
    hits = run(repo, monkeypatch)
    assert len(hits) == 1 and 'Claude-Session' in hits[0]


def test_url_in_the_body_is_caught(tmp_path, monkeypatch):
    repo = make_repo(tmp_path)
    commit(repo, 'b', 'a change\n\nsee https://claude.ai/code/session_abc')
    assert len(run(repo, monkeypatch)) == 1


def test_history_before_base_is_not_judged(tmp_path, monkeypatch):
    # make_repo's base commit carries a link; it must not be reported.
    repo = make_repo(tmp_path)
    commit(repo, 'b', 'clean')
    assert run(repo, monkeypatch) == []


def test_pr_body():
    footer = 'text\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_abc)_'
    assert len(csl.body_hits(footer)) == 1
    assert csl.body_hits('A body.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)') == []
