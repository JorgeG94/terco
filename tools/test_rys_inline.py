"""Unit tests for scripts/rys_inline.py's horizontal-transfer power helpers (run with pytest).

The transfer reads `ab{p}` up to the bra shell's l and `cd{p}` up to the ket
shell's: every power a generated body uses has to be declared and assigned,
at every l a generator can be asked for (an h shell, l = 5, left `ab5`
undeclared once)."""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'scripts'))
import rys_inline as ri  # noqa: E402

USED = re.compile(r'\b(ab|cd)(\d+)\*')
LMAX_TESTED = 6


def declared(lb, ld):
    return {n.strip() for n in ri._power_decl_names(lb, ld).split(',')}


def bodies(la, lb, lc, ld):
    ni, nk = la + lb, lc + ld
    yield ri.hrr_inline_body(ni, nk, la, lb, lc, ld, 'g', 'abx', 'cdx', 'h', 6)
    yield ri.hrr_scalar_assignments(ni, nk, la, lb, lc, ld, 'gx', 'abx', 'cdx', 'hx', 6)


def test_every_power_used_is_declared_and_assigned():
    for lb in range(LMAX_TESTED + 1):
        for ld in range(LMAX_TESTED + 1):
            for la in (0, 1, 2):
                for lc in (0, 1, 2):
                    for text in bodies(la, lb, lc, ld):
                        used = {f'{p}{n}' for p, n in USED.findall(text)}
                        assigned = set(re.findall(r'^\s*((?:ab|cd)\d+) = ', text, re.M))
                        assert used <= declared(lb, ld), (la, lb, lc, ld, used - declared(lb, ld))
                        assert used <= assigned, (la, lb, lc, ld, used - assigned)


def test_declarations_match_assignments():
    for lb in range(LMAX_TESTED + 1):
        for ld in range(LMAX_TESTED + 1):
            lines = ri._power_decl_names(lb, ld).split(', ')
            assigned = [ln.split(' = ')[0].strip() for ln in ri._ab_power_lines('abx', 'cdx', lb, ld, 0)]
            assert lines == assigned


def test_up_to_g_is_unchanged():
    # The committed generated files are regenerated byte for byte: up to l = 4
    # the helpers emit exactly the lines they always did.
    assert ri._power_decl_names(2, 2) == 'ab2, cd2'
    assert ri._power_decl_names(4, 3) == 'ab2, ab3, ab4, cd2, cd3'
    assert ri._ab_power_lines('abx', 'cdx', 4, 4, 3) == [
        '   ab2 = abx*abx', '   ab3 = ab2*abx', '   ab4 = ab3*abx',
        '   cd2 = cdx*cdx', '   cd3 = cd2*cdx', '   cd4 = cd3*cdx']
