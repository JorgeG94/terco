#!/usr/bin/env python3
"""Write docs/pic_api.md: what pic provides, at the tag terco pins.

The pr-review skill checks new code against this file ("use pic, don't
re-roll it"), so it has to describe the pic terco actually builds against.
The tag is read from fpm.toml and must agree with cmake/modules/Findpic.cmake.

    python3 tools/pic_api.py                     # clone pic at the pinned tag
    python3 tools/pic_api.py --pic-src ../pic    # use a checkout (at that tag)
    python3 tools/pic_api.py --check             # CI: fail if the doc is stale

Only `public` names are listed, module by module, with the module's first
FORD (`!!`) line when it has one.
"""
import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "pic_api.md"
URL = "https://github.com/JorgeG94/pic"


def pinned_tag() -> str:
    fpm = (ROOT / "fpm.toml").read_text()
    m = re.search(r'^pic\s*=\s*\{[^}]*tag\s*=\s*"([^"]+)"', fpm, re.M)
    if not m:
        sys.exit("pic_api: no pic tag in fpm.toml")
    tag = m.group(1)
    cmake = (ROOT / "cmake" / "modules" / "Findpic.cmake").read_text()
    c = re.search(r'set\(_rev\s+"([^"]+)"\)', cmake)
    if not c or c.group(1) != tag:
        sys.exit(f"pic_api: fpm.toml pins pic {tag} but Findpic.cmake pins "
                 f"{c.group(1) if c else 'nothing'}; make them agree")
    return tag


def strip_comment(line: str) -> str:
    out, q = [], None
    for ch in line:
        if q:
            out.append(ch)
            if ch == q:
                q = None
        elif ch in "'\"":
            q = ch
            out.append(ch)
        elif ch == "!":
            break
        else:
            out.append(ch)
    return "".join(out)


def logical_lines(text: str):
    """Join `&` continuations; yield (code, raw first line)."""
    buf, first = "", None
    for raw in text.splitlines():
        code = strip_comment(raw).rstrip()
        if first is None:
            first = raw
        if code.endswith("&"):
            buf += code[:-1] + " "
            continue
        buf += code.lstrip("&")
        yield buf, first
        buf, first = "", None


def scan(path: Path):
    """(module, summary, sorted public names) for one source file, or None."""
    text = path.read_text(errors="replace")
    mod = re.search(r"^\s*module\s+(?!procedure\b)(\w+)", text, re.I | re.M)
    if not mod:
        return None
    lines = text.splitlines()
    i = next(k for k, l in enumerate(lines) if re.match(r"\s*module\s+" + mod.group(1), l, re.I))
    summary = ""
    for l in lines[i + 1:i + 6]:
        m = re.match(r"\s*!!\s?(.*\S)", l)
        if m:
            summary = m.group(1)
            break
    names = set()
    for code, _ in logical_lines(text):
        m = re.match(r"\s*public\s*::\s*(.+)$", code, re.I)
        if m:
            names.update(n.strip() for n in m.group(1).split(",") if n.strip())
            continue
        m = re.match(r"\s*[^!]*,\s*public\b[^:]*::\s*(.+)$", code, re.I)
        if m:
            for ent in re.split(r",(?![^()]*\))", m.group(1)):
                n = re.match(r"\s*(\w+)", ent)
                if n:
                    names.add(n.group(1))
    names = sorted(names, key=str.lower)
    if not names:
        return None
    return mod.group(1), summary, names


def render(src: Path, tag: str) -> str:
    rows = []
    for f in sorted((src / "src").rglob("*.[fF]90")):
        r = scan(f)
        if r:
            rows.append((f.relative_to(src).as_posix(), *r))
    out = [
        "# pic API, as terco pins it",
        "",
        f"GENERATED by `tools/pic_api.py` from [pic]({URL}) **{tag}** -- do not edit.",
        "CI regenerates it and fails when it no longer matches the pinned tag.",
        "",
        "New terco code uses these rather than a local copy (pr-review section 10):",
        "timers and clocks, sorting, number/string formatting and string helpers,",
        "statistics, hash maps, heaps and growable vectors, logging, profiling.",
        "Code that runs on the device is exempt: pic is host code.",
        "",
        "| Module | Public names | File |",
        "|---|---|---|",
    ]
    for path, mod, summary, names in rows:
        lead = f"**{mod}**" + (f"<br>{summary}" if summary else "")
        out.append(f"| {lead} | {', '.join(f'`{n}`' for n in names)} | `{path}` |")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pic-src", type=Path, help="a pic checkout at the pinned tag")
    ap.add_argument("--check", action="store_true", help="fail if docs/pic_api.md is stale")
    a = ap.parse_args()
    tag = pinned_tag()
    with tempfile.TemporaryDirectory() as tmp:
        src = a.pic_src
        if src is None:
            src = Path(tmp) / "pic"
            subprocess.run(["git", "clone", "-q", "--depth", "1", "--branch", tag, URL, str(src)],
                           check=True)
        text = render(src, tag)
    if a.check:
        if not DOC.exists() or DOC.read_text() != text:
            print(f"::error file=docs/pic_api.md::docs/pic_api.md does not match pic {tag}; "
                  "run python3 tools/pic_api.py and commit it")
            return 1
        print(f"pic_api: docs/pic_api.md matches pic {tag}")
        return 0
    DOC.write_text(text)
    print(f"pic_api: wrote {DOC.relative_to(ROOT)} from pic {tag}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
