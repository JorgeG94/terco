!
! The symmetry keywords through the real `terco` binary: `symmetry`,
! `symmetry_tol` and `irrep_nelec` as flags and in a TOML file (whose parsed
! command line is what --json echoes), the group, the irrep labels and the
! energy of a HOCl run with `symmetry = auto`, and every refusal.
!
! HOCl (planar, Cs) cc-pVDZ. The anchors are pyscf's (pyscf_refs/sym_scf_cs.ref,
! generated by test/pyscf_refs/generate.py): the RHF energy and the electrons
! per irrep. The central oracle of the symmetry project is applied through the
! CLI: the symmetric run and a symmetry-off run on the symmetrised, oriented
! geometry the first one reports (its "geometry" in --json) agree in the total
! energy to 1e-10 Eh and in the gradient.
!
! Refused, each by name and before any SCF: --symmetry with --opt, --hessian,
! --rimp2 (and a double hybrid), --df, --pcm, --soscf, --fukui and --restart;
! a group that is not the detected one or a subgroup; a subgroup below the
! reported group (Cs on C2v water: only the reported group is run); a gradient with fixed irrep occupations that
! are not the aufbau ones; an irrep_nelec that is malformed or does not add up.
! MPI: the library refuses symmetry on more than one rank (the irrep labels
! live on the rank that ran the SCF); that path needs a multi-rank build and
! is covered by the code review, not by this check.
!
! Symmetry off is unchanged: `--symmetry off` prints nothing about symmetry.
!
! S17 (symmetry on by default): a run without the flag is `--symmetry default`.
! It reports in the input frame (the geometry input symmetrised, the gradient
! rotated back), gives the `--symmetry off` energy and gradient (water and an
! open-shell NO2, axis-aligned and rotated; benzene rotated; HF and B3LYP),
! says which frame its results are in with one line, prints one line only for
! a molecule without symmetry, and runs the paths the symmetric SCF does not
! support in C1 with exactly the old output and one line saying why. An
! explicit `--symmetry auto` keeps the standard frame and the refusals (the
! cases above, unchanged). The tests that assumed `off` was the default were
! changed: test_off_unchanged (now about the explicit `off`),
! test_skeleton_flag and test_irrep_nelec_bad (a bare --no-sym-skeleton is now
! valid, a bare --irrep-nelec means an explicit auto).
!
! A test-drive suite; its cases run in order (`parallel=.false.`), as the
! other CLI checks do.
!
module check_sym_cli_suite
   use pic_types, only: dp
   use pic_strings, only: to_string
   use json_module, only: json_file
   use testdrive, only: new_unittest, unittest_type, error_type, test_failed, check
   use pyscf_ref_io, only: ref_require, ref_close, ref_read_int, ref_read_real, ref_read_vector
   implicit none
   private
   public :: collect_sym_cli, cli_exe, work_dir

   character(len=:), allocatable :: cli_exe
      !! The terco CLI binary, from the command line.
   character(len=:), allocatable :: work_dir
      !! A scratch directory this check owns.
   character(len=*), parameter :: BASIS = ' -b basis_sets/cc-pvdz.json'
   real(dp), parameter :: TOL_E_HF = 1.0e-10_dp   !! the project's HF gate, symmetry vs C1
   real(dp), parameter :: TOL_G = 1.0e-9_dp       !! gradient, symmetry vs C1
   real(dp), parameter :: TOL_ANCHOR = 1.0e-8_dp  !! terco vs pyscf, RHF energy (measured 4e-12)
   character(len=*), parameter :: TIGHT = ' --econv 1e-12 --gconv 1e-10 --silent'
   character(len=*), parameter :: BS = char(92)
      !! One backslash, for the shell and TOML escapes below. NOT written as a
      !! literal '\' : backslash in a character literal is an ordinary character
      !! to gfortran but an escape introducer to nvfortran, which silently eats
      !! it and leaves the shell with an unbalanced quote.

contains

   subroutine collect_sym_cli(testsuite)
      type(unittest_type), allocatable, intent(out) :: testsuite(:)
      testsuite = [ &
         new_unittest("HOCl symmetry=auto: group, labels, energy vs pyscf and vs C1", test_hocl_auto), &
         new_unittest("symmetry=auto gradient equals the C1 gradient on the same geometry", test_gradient), &
         new_unittest("the report says the coordinates are in the standard frame", test_report), &
         new_unittest("symmetry=off prints nothing about symmetry and writes no symmetry block", test_off_unchanged), &
         new_unittest("default: energy, gradient and geometry equal --symmetry off, in the input frame", &
                      test_default_matches_off), &
         new_unittest("default: DFT energy and gradient equal --symmetry off", test_default_dft), &
         new_unittest("default: one line says the results are in the input frame; explicit auto says standard", &
                      test_default_report), &
         new_unittest("default on a molecule without symmetry: the output of off, apart from one line", &
                      test_default_c1_unchanged), &
         new_unittest("default: the unsupported paths run in C1 with one line and the old numbers", &
                      test_default_fallbacks), &
         new_unittest("default: --irrep-nelec is an explicit auto; the input echo says default", test_default_inputs), &
         new_unittest("TOML: symmetry keys give the flags' numbers and are echoed", test_toml), &
         new_unittest("TOML: a wrongly typed symmetry key is refused", test_toml_type), &
         new_unittest("--no-sym-skeleton: the same energy; needs --symmetry; the TOML key matches", test_skeleton_flag), &
         new_unittest("an explicit subgroup runs; C1 runs without symmetry", test_explicit), &
         new_unittest("an explicit group that is not a subgroup is refused", test_not_subgroup), &
         new_unittest("a subgroup below the detected group runs (Cs on water); a non-subgroup is refused", test_not_yet), &
         new_unittest("an unknown group is refused", test_unknown_group), &
         new_unittest("irrep_nelec: aufbau counts reproduce the energy; others are a different state", test_irrep_nelec), &
         new_unittest("irrep_nelec: malformed and not adding up are refused", test_irrep_nelec_bad), &
         new_unittest("a gradient with non-aufbau irrep occupations is refused", test_grad_fixed_refused), &
         new_unittest("--symmetry is refused with the unsupported paths", test_path_refusals) &
         ]
   end subroutine collect_sym_cli

   subroutine test_hocl_auto(error)
      type(error_type), allocatable, intent(out) :: error
      type(json_file) :: json
      character(len=:), allocatable :: group, detected, req, svec(:)
      integer, allocatable :: ilen(:)
      integer :: rc, u, nocc_a1, nocc_a2, nspin_ref
      logical :: found
      real(dp) :: e, e_ref, nelec(4), resid
      real(dp), allocatable :: dims(:)

      call setup()
      call run_cli('hocl.xyz'//BASIS//' --symmetry auto'//TIGHT//' --json '//work_dir//'/auto.json > '// &
                   work_dir//'/auto.out 2>&1', rc)
      call check(error, rc == 0, "the symmetric run failed:"//new_line('a')//slurp(work_dir//'/auto.out'))
      if (allocated(error)) return
      call json%initialize()
      call json%load(filename=work_dir//'/auto.json')
      call json%get('symmetry.group', group, found)
      call check(error, found .and. group == 'Cs', "symmetry.group should be Cs")
      if (allocated(error)) return
      call json%get('symmetry.detected group', detected, found)
      call check(error, found .and. detected == 'Cs', "symmetry.detected group should be Cs")
      if (allocated(error)) return
      call json%get('symmetry.requested', req, found)
      call check(error, found .and. req == 'auto', "symmetry.requested should be auto")
      if (allocated(error)) return
      call json%get('symmetry.residual', resid, found)
      call check(error, found .and. resid < 1.0e-9_dp, "a planar molecule needs no symmetrisation (residual "// &
                 to_string(resid, 'es10.2')//")")
      if (allocated(error)) return
      call json%get('symmetry.irreps', svec, ilen, found)
      call check(error, found .and. size(svec) == 2, "two irreps")
      if (allocated(error)) return
      call check(error, trim(svec(1)) == "A'" .and. trim(svec(2)) == 'A"', "irrep names are pyscf's: A', A""")
      if (allocated(error)) return
      call json%get('symmetry.irrep dimensions', dims, found)
      call check(error, found .and. size(dims) == 2, "irrep dimensions")
      if (allocated(error)) return
      call check(error, nint(dims(1)) == 27 .and. nint(dims(2)) == 10, "SO dimensions 27 and 10 (pyscf's mol.symm_orb)")
      if (allocated(error)) return
      ! The labels of the 13 occupied orbitals against pyscf's electrons per irrep.
      call json%get('symmetry.orbital irreps', svec, ilen, found)
      call check(error, found .and. size(svec) == 37, "one label per orbital (37)")
      if (allocated(error)) return
      nocc_a1 = count(trim_all(svec(1:13)) == "A'")
      nocc_a2 = count(trim_all(svec(1:13)) == 'A"')
      call ref_require('sym_scf_cs.ref', u)
      ! the file is sequential: NSPIN, E, then the electrons per irrep
      call ref_read_int(u, 'NSPIN_hocl_rhf', nspin_ref)
      call ref_read_real(u, 'E_hocl_rhf', e_ref)
      call ref_read_vector(u, 'NELEC_hocl_rhf', 4, nelec)
      call ref_close(u)
      call check(error, nocc_a1 == nint(nelec(1)) .and. nocc_a2 == nint(nelec(2)), &
                 "occupied A' / A"" orbitals "//to_string(nocc_a1)//" / "//to_string(nocc_a2)// &
                 " differ from pyscf's "//to_string(nint(nelec(1)))//" / "//to_string(nint(nelec(2))))
      if (allocated(error)) return
      call json%get('total energy', e, found)
      call check(error, found .and. abs(e - e_ref) < TOL_ANCHOR, "energy differs from pyscf by "// &
                 to_string(abs(e - e_ref), 'es10.2'))
      if (allocated(error)) return
      call json%destroy()
      ! Against symmetry off on the symmetrised geometry the run reports.
      call write_std_xyz(work_dir//'/auto.json', work_dir//'/std.xyz', error)
      if (allocated(error)) return
      call run_cli(work_dir//'/std.xyz'//BASIS//TIGHT//' --json '//work_dir//'/c1.json > '//work_dir//'/c1.out 2>&1', rc)
      call check(error, rc == 0, "the C1 run failed")
      if (allocated(error)) return
      call json%initialize()
      call json%load(filename=work_dir//'/c1.json')
      call json%get('total energy', e_ref, found)
      call json%destroy()
      call check(error, abs(e - e_ref) <= TOL_E_HF, "|E(sym) - E(C1)| = "//to_string(abs(e - e_ref), 'es10.2')// &
                 " exceeds 1e-10")
   end subroutine test_hocl_auto

   subroutine test_gradient(error)
      type(error_type), allocatable, intent(out) :: error
      real(dp), allocatable :: gs(:), gc(:)
      real(dp) :: e1, e2
      integer :: rc

      call setup()
      call run_cli('hocl.xyz'//BASIS//' --symmetry auto --grad'//TIGHT//' --json '//work_dir//'/g_sym.json > '// &
                   work_dir//'/g_sym.out 2>&1', rc)
      call check(error, rc == 0, "the symmetric gradient run failed:"//new_line('a')//slurp(work_dir//'/g_sym.out'))
      if (allocated(error)) return
      call write_std_xyz(work_dir//'/g_sym.json', work_dir//'/std.xyz', error)
      if (allocated(error)) return
      call run_cli(work_dir//'/std.xyz'//BASIS//' --grad'//TIGHT//' --json '//work_dir//'/g_c1.json > '// &
                   work_dir//'/g_c1.out 2>&1', rc)
      call check(error, rc == 0, "the C1 gradient run failed")
      if (allocated(error)) return
      call read_gradient(work_dir//'/g_sym.json', e1, gs, error)
      if (allocated(error)) return
      call read_gradient(work_dir//'/g_c1.json', e2, gc, error)
      if (allocated(error)) return
      call check(error, maxval(abs(gs - gc)) < TOL_G, "gradient differs from the C1 gradient on the same geometry by "// &
                 to_string(maxval(abs(gs - gc)), 'es10.2'))
      if (allocated(error)) return
      ! Cs in the standard frame: z is the mirror normal, so no force along z.
      call check(error, maxval(abs(gs([3, 6, 9]))) < 1.0e-10_dp, "the gradient has a component out of the mirror plane")
   end subroutine test_gradient

   subroutine test_report(error)
      type(error_type), allocatable, intent(out) :: error
      character(len=:), allocatable :: text
      integer :: rc

      call setup()
      call run_cli('hocl.xyz'//BASIS//' --symmetry auto --econv 1e-10 > '//work_dir//'/rep.out 2>&1', rc)
      call check(error, rc == 0, "the run failed")
      if (allocated(error)) return
      text = slurp(work_dir//'/rep.out')
      call check(error, index(text, 'INPUT frame') == 0, "an explicit auto must not claim the input frame")
      if (allocated(error)) return
      call check(error, index(text, 'requested auto, detected Cs, used Cs') > 0, "the groups are not reported")
      if (allocated(error)) return
      call check(error, index(text, 'STANDARD FRAME') > 0, "the output does not say the coordinates are in the standard frame")
      if (allocated(error)) return
      call check(error, index(text, 'geometry, standard frame (Angstrom)') > 0, "the standard-frame geometry is not printed")
      if (allocated(error)) return
      call check(error, index(text, "irrep  SO functions  occupied orbitals") > 0, "no per-irrep occupation table")
      if (allocated(error)) return
      call check(error, index(text, 'orbitals: index  irrep  energy (Eh)  occupation') > 0, "no labelled orbital list")
      if (allocated(error)) return
      call check(error, index(text, "     13      A""") > 0, "orbital 13 (the HOMO) should be an A"" orbital")
   end subroutine test_report

   subroutine test_off_unchanged(error)
      !! `--symmetry off` is the path symmetry never reaches: no word about
      !! symmetry in the output, no block in --json. (Before S17 this test
      !! compared a run without the flag with `off`; a plain run is now the
      !! default request, tested below.)
      type(error_type), allocatable, intent(out) :: error
      character(len=:), allocatable :: off, jplain
      integer :: rc
      type(json_file) :: json
      logical :: found

      call setup()
      call run_cli('hocl.xyz'//BASIS//' --grad --symmetry off --json '//work_dir//'/off.json > '//work_dir//'/off.out 2>&1', rc)
      call check(error, rc == 0, "the --symmetry off run failed")
      if (allocated(error)) return
      off = stable_text(work_dir//'/off.out')
      call check(error, index(off, 'symmetry') == 0 .and. index(off, 'STANDARD FRAME') == 0 .and. &
                 index(off, 'INPUT frame') == 0 .and. index(off, 'irrep') == 0, "a run with symmetry off mentions symmetry")
      if (allocated(error)) return
      call json%initialize()
      call json%load(filename=work_dir//'/off.json')
      call json%get('symmetry.group', jplain, found)
      call check(error, .not. found, "a run with symmetry off writes a symmetry block to --json")
      call json%destroy()
   end subroutine test_off_unchanged

   subroutine test_toml(error)
      type(error_type), allocatable, intent(out) :: error
      type(json_file) :: json
      character(len=:), allocatable :: sval
      real(dp) :: e_toml, e_flags, rval
      integer :: rc
      logical :: found

      call setup()
      call write_toml(work_dir//'/case/sym.toml', [character(len=96) :: &
                      '[molecule]', 'geometry = "hocl.xyz"', &
                      '[basis]', 'main = "basis_sets/cc-pvdz.json"', &
                      '[scf]', 'symmetry = "auto"', 'symmetry_tol = 1e-6', 'irrep_nelec = "A'//"'"//'=20,A'//BS//'"=6"', &
                      'energy_tol = 1e-12', 'commutator_tol = 1e-10', &
                      '[output]', 'json = "toml.json"', 'silent = true'])
      call run_cli_raw('cd '//work_dir//' && '//cli_exe//' case/sym.toml > toml.out 2>&1', rc)
      call check(error, rc == 0, "the TOML run failed:"//new_line('a')//slurp(work_dir//'/toml.out'))
      if (allocated(error)) return
      call run_cli('hocl.xyz'//BASIS//' --symmetry auto --symmetry-tol 1e-6 --irrep-nelec "A'//"'"//'=20,A'//BS//'"=6"'// &
                   TIGHT//' --json '//work_dir//'/flags.json > '//work_dir//'/flags.out 2>&1', rc)
      call check(error, rc == 0, "the flag run failed:"//new_line('a')//slurp(work_dir//'/flags.out'))
      if (allocated(error)) return
      call json%initialize()
      call json%load(filename=work_dir//'/case/toml.json')
      call json%get('total energy', e_toml, found)
      call json%get('input.scf.symmetry', sval, found)
      call check(error, found .and. sval == 'auto', "input.scf.symmetry should echo the file's auto")
      if (allocated(error)) return
      call json%get('input.scf.symmetry_tol', rval, found)
      call check(error, found .and. abs(rval - 1.0e-6_dp) < 1.0e-18_dp, "input.scf.symmetry_tol should echo 1e-6")
      if (allocated(error)) return
      call json%get('input.scf.irrep_nelec', sval, found)
      call check(error, found .and. sval == "A'=20,A""=6", "input.scf.irrep_nelec should echo the file's string")
      if (allocated(error)) return
      call json%get('symmetry.group', sval, found)
      call check(error, found .and. sval == 'Cs', "the file's symmetry request did not run")
      call json%destroy()
      if (allocated(error)) return
      call json%initialize()
      call json%load(filename=work_dir//'/flags.json')
      call json%get('total energy', e_flags, found)
      call json%destroy()
      call check(error, abs(e_toml - e_flags) < 1.0e-11_dp, "the file and the flags give different energies")
   end subroutine test_toml

   subroutine test_toml_type(error)
      type(error_type), allocatable, intent(out) :: error
      character(len=:), allocatable :: text
      integer :: rc

      call setup()
      call write_toml(work_dir//'/case/bad.toml', [character(len=64) :: &
                      '[molecule]', 'geometry = "hocl.xyz"', '[scf]', 'symmetry = 1'])
      call run_cli_raw('cd '//work_dir//' && '//cli_exe//' case/bad.toml > bad.out 2>&1', rc)
      call check(error, rc /= 0, "symmetry = 1 was accepted")
      if (allocated(error)) return
      text = slurp(work_dir//'/bad.out')
      call check(error, index(text, "'symmetry' must be a string") > 0, "the message does not name the key:"//new_line('a')//text)
      if (allocated(error)) return
      call write_toml(work_dir//'/case/bad.toml', [character(len=64) :: &
                      '[molecule]', 'geometry = "hocl.xyz"', '[scf]', 'symmetry_tol = "tight"'])
      call run_cli_raw('cd '//work_dir//' && '//cli_exe//' case/bad.toml > bad.out 2>&1', rc)
      call check(error, rc /= 0, "symmetry_tol = a string was accepted")
      if (allocated(error)) return
      text = slurp(work_dir//'/bad.out')
      call check(error, index(text, "'symmetry_tol' must be a number") > 0, "the message does not name the key")
   end subroutine test_toml_type

   subroutine test_skeleton_flag(error)
      !! --sym-skeleton forces the skeleton Fock build and --no-sym-skeleton
      !! (or symmetry_skeleton = false) the full build, and the two give the
      !! same SCF; either flag without a symmetry request is refused. Both are
      !! given explicitly because HOCl is a molecule the size rule declines,
      !! so a bare --symmetry auto would take the full build on both sides.
      !! Also the `--json` echo of the key, which is KIND_BOOL_TRI: it carries
      !! the flag that WAS given, and only that (the third state, neither flag,
      !! is checked in check_cli_input's test_echo).
      type(error_type), allocatable, intent(out) :: error
      type(json_file) :: json
      real(dp) :: e_on, e_off, e_toml
      logical :: found, echoed
      integer :: rc

      call setup()
      call run_cli('hocl.xyz'//BASIS//' --symmetry auto --sym-skeleton'//TIGHT//' --json '//work_dir//'/sk_on.json > '// &
                   work_dir//'/sk_on.out 2>&1', rc)
      call check(error, rc == 0, "--sym-skeleton failed:"//new_line('a')//slurp(work_dir//'/sk_on.out'))
      if (allocated(error)) return
      call run_cli('hocl.xyz'//BASIS//' --symmetry auto --no-sym-skeleton'//TIGHT//' --json '//work_dir// &
                   '/sk_off.json > '//work_dir//'/sk_off.out 2>&1', rc)
      call check(error, rc == 0, "--no-sym-skeleton failed:"//new_line('a')//slurp(work_dir//'/sk_off.out'))
      if (allocated(error)) return
      call json%initialize()
      call json%load(filename=work_dir//'/sk_on.json')
      call json%get('total energy', e_on, found)
      ! The echo must name the flag that was given, so that rerunning the echo
      ! as a TOML file reproduces this run's Fock build rather than falling
      ! back to the size rule.
      call json%get('input.scf.symmetry_skeleton', echoed, found)
      call json%destroy()
      call check(error, found .and. echoed, "--sym-skeleton must echo input.scf.symmetry_skeleton = true")
      if (allocated(error)) return
      call json%initialize()
      call json%load(filename=work_dir//'/sk_off.json')
      call json%get('total energy', e_off, found)
      call json%get('input.scf.symmetry_skeleton', echoed, found)
      call json%destroy()
      call check(error, found .and. .not. echoed, "--no-sym-skeleton must echo input.scf.symmetry_skeleton = false")
      if (allocated(error)) return
      call check(error, abs(e_on - e_off) < 1.0e-9_dp, "--no-sym-skeleton changed the energy by "// &
                 to_string(abs(e_on - e_off), 'es10.2'))
      if (allocated(error)) return
      ! Symmetry is on by default, so a bare --no-sym-skeleton is valid (the
      ! default request builds the full Fock matrix); it needs symmetry to be on.
      call setup_run_ok('hocl.xyz'//BASIS//' --no-sym-skeleton --silent', error)
      if (allocated(error)) return
      call refused('hocl.xyz'//BASIS//' --symmetry off --no-sym-skeleton', 'need symmetry', error)
      if (allocated(error)) return
      call refused('hocl.xyz'//BASIS//' --symmetry auto --sym-skeleton --no-sym-skeleton', 'contradict', error)
      if (allocated(error)) return
      ! The TOML key is the flag: symmetry_skeleton = false is --no-sym-skeleton.
      call write_toml(work_dir//'/case/sk.toml', [character(len=96) :: &
                      '[molecule]', 'geometry = "hocl.xyz"', &
                      '[basis]', 'main = "basis_sets/cc-pvdz.json"', &
                      '[scf]', 'symmetry = "auto"', 'symmetry_skeleton = false', &
                      'energy_tol = 1e-12', 'commutator_tol = 1e-10', &
                      '[output]', 'json = "sk_toml.json"', 'silent = true'])
      call run_cli_raw('cd '//work_dir//' && '//cli_exe//' case/sk.toml > sk_toml.out 2>&1', rc)
      call check(error, rc == 0, "the TOML run failed:"//new_line('a')//slurp(work_dir//'/sk_toml.out'))
      if (allocated(error)) return
      call json%initialize()
      call json%load(filename=work_dir//'/case/sk_toml.json')
      call json%get('total energy', e_toml, found)
      call json%destroy()
      call check(error, found .and. abs(e_toml - e_off) < 1.0e-9_dp, "the TOML run's energy differs")
      if (allocated(error)) return
      call json%initialize()
      call json%load(filename=work_dir//'/case/sk_toml.json')
      call json%get('input.scf.symmetry_skeleton', echoed, found)
      call json%destroy()
      call check(error, found .and. .not. echoed, &
                 "symmetry_skeleton = false in the file must echo back as false, not as the third state")
   end subroutine test_skeleton_flag

   subroutine test_explicit(error)
      type(error_type), allocatable, intent(out) :: error
      type(json_file) :: json
      character(len=:), allocatable :: sval
      character(len=:), allocatable :: text
      logical :: found
      integer :: rc

      call setup()
      call run_cli('hocl.xyz'//BASIS//' --symmetry cs'//TIGHT//' --json '//work_dir//'/cs.json > '//work_dir//'/cs.out 2>&1', rc)
      call check(error, rc == 0, "--symmetry cs failed:"//new_line('a')//slurp(work_dir//'/cs.out'))
      if (allocated(error)) return
      call json%initialize()
