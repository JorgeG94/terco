   function slurp(path) result(text)
      character(len=*), intent(in) :: path
      character(len=:), allocatable :: text
      character(len=1024) :: line
      integer :: u, ios
      text = ''
      open (newunit=u, file=path, status='old', action='read', iostat=ios)
      if (ios /= 0) return
      do
         read (u, '(a)', iostat=ios) line
         if (ios /= 0) exit
         text = text//trim(line)//new_line('a')
      end do
      close (u)
   end function slurp

   function stable_text(path, drop) result(text)
      !! A CLI output without the lines that change from run to run: the wall
      !! clock and the timing table, and the lines containing `drop`.
      character(len=*), intent(in) :: path
      character(len=*), intent(in), optional :: drop
      character(len=:), allocatable :: text
      character(len=1024) :: line
      integer :: u, ios
      text = ''
      open (newunit=u, file=path, status='old', action='read', iostat=ios)
      if (ios /= 0) return
      do
         read (u, '(a)', iostat=ios) line
         if (ios /= 0) exit
         if (index(line, 'wall time') > 0 .or. index(line, '(s)') > 0) cycle
         if (index(line, 'trc_run_hessian: ') == 1) cycle   ! per-displacement seconds
         if (present(drop)) then
            if (index(line, drop) > 0) cycle
         end if
         text = text//trim(line)//new_line('a')
      end do
      close (u)
   end function stable_text

   logical function same_text_to_noise(a, b, tol) result(same)
      !! Two stable_text outputs with the same lines and the same words, where
      !! a word that differs must be a number in both, within `tol`.
      character(len=*), intent(in) :: a, b
      real(dp), intent(in) :: tol
      integer :: ia, ib, ea, eb
      same = .false.
      ia = 1
      ib = 1
      do while (ia <= len(a) .and. ib <= len(b))
         ea = index(a(ia:), new_line('a')) + ia - 1
         eb = index(b(ib:), new_line('a')) + ib - 1
         if (ea < ia .or. eb < ib) return
         if (.not. same_line(a(ia:ea - 1), b(ib:eb - 1))) return
         ia = ea + 1
         ib = eb + 1
      end do
      same = (ia > len(a) .and. ib > len(b))
   contains
      logical function same_line(la, lb) result(ok)
         character(len=*), intent(in) :: la, lb
         integer :: pa, pb, qa, qb, ios_a, ios_b
         real(dp) :: va, vb
         ok = .false.
         if (la == lb) then
            ok = .true.
            return
         end if
         pa = 1
         pb = 1
         do
            do while (pa <= len(la))
               if (la(pa:pa) /= ' ') exit
               pa = pa + 1
            end do
            do while (pb <= len(lb))
               if (lb(pb:pb) /= ' ') exit
               pb = pb + 1
            end do
            if (pa > len(la) .or. pb > len(lb)) then
               ok = (pa > len(la) .and. pb > len(lb))
               return
            end if
            qa = index(la(pa:), ' ') + pa - 2
            if (qa < pa) qa = len(la)
            qb = index(lb(pb:), ' ') + pb - 2
            if (qb < pb) qb = len(lb)
            if (la(pa:qa) /= lb(pb:qb)) then
               read (la(pa:qa), *, iostat=ios_a) va
               read (lb(pb:qb), *, iostat=ios_b) vb
               if (ios_a /= 0 .or. ios_b /= 0) return
               if (abs(va - vb) > tol) return
            end if
            pa = qa + 1
            pb = qb + 1
         end do
      end function same_line
   end function same_text_to_noise

end module check_sym_cli_suite

