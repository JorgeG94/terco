   subroutine write_std_xyz(json_path, xyz_path, error)
      !! The geometry a symmetric run reports ("symmetry.geometry", Angstrom,
      !! standard frame) as an xyz file for a run without symmetry.
      character(len=*), intent(in) :: json_path, xyz_path
      type(error_type), allocatable, intent(out) :: error
      type(json_file) :: json
      real(dp), allocatable :: row(:)
      character(len=2), parameter :: SYM(3) = ['H ', 'O ', 'Cl']
      integer :: u, ia
      logical :: found

      call json%initialize()
      call json%load(filename=json_path)
      open (newunit=u, file=xyz_path, status='replace', action='write')
      write (u, '(a)') '3'
      write (u, '(a)') 'HOCl, standard frame, from --json symmetry.geometry'
      do ia = 1, 3
         call json%get('symmetry.geometry('//to_string(ia)//')', row, found)
         if (.not. found) then
            close (u)
            call json%destroy()
            call test_failed(error, 'no symmetry.geometry row '//to_string(ia)//' in '//json_path)
            return
         end if
         write (u, '(a,3(1x,es26.17e3))') SYM(ia), row
      end do
      close (u)
      call json%destroy()
   end subroutine write_std_xyz

   subroutine read_gradient(path, energy, gradient, error)
      character(len=*), intent(in) :: path
      real(dp), intent(out) :: energy
      real(dp), allocatable, intent(out) :: gradient(:)
      type(error_type), allocatable, intent(out) :: error
      type(json_file) :: json
      logical :: found
      real(dp), allocatable :: row(:)
      integer :: ia

      call json%initialize()
      call json%load(filename=path)
      call json%get('total energy', energy, found)
      allocate (gradient(0))
      do ia = 1, 3
         call json%get('gradient('//to_string(ia)//')', row, found)
         if (.not. found) then
            call json%destroy()
            call test_failed(error, 'no gradient row '//to_string(ia)//' in '//path)
            return
         end if
         gradient = [gradient, row]
      end do
      call json%destroy()
   end subroutine read_gradient

