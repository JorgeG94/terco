      if (allocated(error)) return
      call default_vs_off('water_rot.xyz', '-b basis_sets/cc-pvdz.json --func b3lyp --grid 5', 1.0e-9_dp, TOL_G_GRID5, 'C2v', error)
   end subroutine test_default_dft

