   subroutine refused(args, expect, error)
      !! A command line that must stop with `expect` in its output and no SCF.
      character(len=*), intent(in) :: args, expect
      type(error_type), allocatable, intent(out) :: error
      character(len=:), allocatable :: text
      integer :: rc

      call setup()
      call run_cli(args//' > '//work_dir//'/ref.out 2>&1', rc)
      text = slurp(work_dir//'/ref.out')
      call check(error, rc /= 0, "accepted: "//args)
      if (allocated(error)) return
      call check(error, index(text, expect) > 0, "'"//args//"' does not say '"//expect//"':"//new_line('a')//text)
      if (allocated(error)) return
      call check(error, index(text, 'TOTAL ENERGY') == 0, "an SCF result was printed for: "//args)
   end subroutine refused

