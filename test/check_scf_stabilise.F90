   subroutine test_mom_gate_unflagged(error)
      !! The swapped density as `dguess` WITHOUT `mom_follow_guess` (what SAD,
      !! SADQ and MINAO look like to the driver) is not followed from the first
      !! iteration: its commutator is above the 0.1 gate, so iteration 1 is
      !! aufbau and the run ends on the ground state. Checked on the density
      !! after one iteration, which is exact: the result carries that
      !! iteration's orbitals (its density is the one handed in), and flagged
      !! they are ordered by the swapped occupation while unflagged they equal
      !! the aufbau iteration.
      type(error_type), allocatable, intent(out) :: error
      type(trc_basis_t) :: bas
      type(trc_scf_options_t) :: o
      type(trc_scf_result_t) :: ground, flagged1, unflagged1, aufbau1, unflagged
      real(dp), allocatable :: dex(:, :, :), p_unflagged(:, :), p_aufbau(:, :)
      integer :: nocc, n
      call water_swapped(bas, nocc, ground, dex, error)
      if (allocated(error)) then
         call bas%release()
         return
      end if
      o%conv_energy = 1.0e-10_dp
      o%conv_diis = 1.0e-30_dp
      o%max_iteration = 1
      o%mom_follow_guess = .true.
      o%mom = .true.
      call trc_scf_run(bas, nocc, nocc, o, flagged1, dguess=dex)
      o%mom_follow_guess = .false.
      call trc_scf_run(bas, nocc, nocc, o, unflagged1, dguess=dex)
      o%mom = .false.
      call trc_scf_run(bas, nocc, nocc, o, aufbau1, dguess=dex)
      o%mom = .true.
      o%conv_diis = 1.0e-8_dp
      o%max_iteration = 100
      call trc_scf_run(bas, nocc, nocc, o, unflagged, dguess=dex)
      call bas%release()
      call check(error, maxval(abs(flagged1%eps - aufbau1%eps)) > 1.0e-3_dp, &
                 "precondition: a flagged guess must keep the swapped occupation in iteration 1")
      if (allocated(error)) return
      ! The occupied projector, not the orbitals themselves: two device
      ! eigensolves of the same matrix agree in eps to 1e-14 but not in the
      ! sign of each vector (measured on a V100: max |d cmo| of order 1).
      n = size(aufbau1%cmo, 1)
      allocate (p_unflagged(n, n), p_aufbau(n, n))
      p_unflagged = matmul(unflagged1%cmo(:, 1:nocc, 1), transpose(unflagged1%cmo(:, 1:nocc, 1)))
      p_aufbau = matmul(aufbau1%cmo(:, 1:nocc, 1), transpose(aufbau1%cmo(:, 1:nocc, 1)))
      call check(error, maxval(abs(unflagged1%eps - aufbau1%eps)) < 1.0e-12_dp .and. &
                 maxval(abs(p_unflagged - p_aufbau)) < 1.0e-12_dp, &
                 "an unflagged density was followed from iteration 1: max |d eps| from the aufbau iteration = "// &
                 to_string(maxval(abs(unflagged1%eps - aufbau1%eps)), "es10.2")//", max |d P_occ| = "// &
                 to_string(maxval(abs(p_unflagged - p_aufbau)), "es10.2")//", max |d cmo| = "// &
                 to_string(maxval(abs(unflagged1%cmo - aufbau1%cmo)), "es10.2"))
      if (allocated(error)) return
      call check(error, unflagged%converged, "mom run from an unflagged swapped density: "//trim(unflagged%message))
      if (allocated(error)) return
      call check(error, abs(unflagged%energy - ground%energy) < 1.0e-8_dp, &
                 "an unflagged swapped density should end on the ground state: E - E0 = "// &
                 to_string(unflagged%energy - ground%energy, "es10.2"))
   end subroutine test_mom_gate_unflagged

