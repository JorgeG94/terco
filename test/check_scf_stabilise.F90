   subroutine test_shift_criterion(error)
      type(error_type), allocatable, intent(out) :: error
      real(dp), parameter :: OLDER = 1.0e-2_dp
      call check(error, .not. scf_driver_shift_stalled(0.99_dp*SHIFT_STALL_FACTOR*OLDER, OLDER), &
                 "a best commutator below the factor is progress")
      if (allocated(error)) return
      call check(error, scf_driver_shift_stalled(1.01_dp*SHIFT_STALL_FACTOR*OLDER, OLDER), &
                 "a best commutator above the factor is a stall")
      if (allocated(error)) return
      call check(error, scf_driver_shift_stalled(OLDER, OLDER), "no improvement at all is a stall")
      if (allocated(error)) return
      call check(error, SHIFT_STALL_FACTOR > 0.0_dp .and. SHIFT_STALL_FACTOR < 1.0_dp .and. SHIFT_STALL_WINDOW >= 2, &
                 "the guard constants are out of range")
   end subroutine test_shift_criterion

   function first_stall(e) result(n)
      !! The first observation at which the guard must fire for the commutator
      !! sequence `e`, from the definition alone: the best of the last
      !! SHIFT_STALL_WINDOW values against the best of all the values before
      !! them. 0 if it never does.
      real(dp), intent(in) :: e(:)
      integer :: n, k
      n = 0
      do k = SHIFT_STALL_WINDOW + 1, size(e)
         if (minval(e(k - SHIFT_STALL_WINDOW + 1:k)) > SHIFT_STALL_FACTOR*minval(e(1:k - SHIFT_STALL_WINDOW))) then
            n = k
            return
         end if
      end do
   end function first_stall

   function observe_all(e, nfire) result(n)
      !! The observation at which a fresh guard fires on `e`, and how often it
      !! reported firing.
      real(dp), intent(in) :: e(:)
      integer, intent(out) :: nfire
      integer :: n, k
      type(scf_shift_guard_t) :: guard
      logical :: fired
      n = 0
      nfire = 0
      do k = 1, size(e)
         call guard%observe(e(k), fired)
         if (fired) then
            nfire = nfire + 1
            if (n == 0) n = k
         end if
      end do
   end function observe_all

   subroutine test_shift_guard_sequences(error)
      type(error_type), allocatable, intent(out) :: error
      real(dp) :: flat(40), parked(40), steady(80), slow(80), edge
      integer :: k, nfire, n
      type(scf_shift_guard_t) :: guard
      logical :: fired
      flat = 1.0e-3_dp
      ! Nothing is concluded before there is a window of values and one before it.
      n = observe_all(flat, nfire)
      call check(error, n == SHIFT_STALL_WINDOW + 1 .and. nfire == 1, &
                 "a constant commutator must fire once, on observation window + 1: "//to_string(n))
      if (allocated(error)) return
      ! Falling, then parked: the first stall from the definition, then a latch.
      parked = 0.2_dp
      parked(1:3) = [1.0_dp, 0.5_dp, 0.25_dp]
      n = observe_all(parked, nfire)
      call check(error, n > 0 .and. n == first_stall(parked) .and. nfire == 1, &
                 "a parked commutator fires on the observation the definition gives ("//to_string(first_stall(parked))// &
                 "), once, not "//to_string(n))
      if (allocated(error)) return
      ! A rate per iteration just inside and just outside the criterion over one window.
      edge = SHIFT_STALL_FACTOR**(1.0_dp/real(SHIFT_STALL_WINDOW, dp))
      steady = [(0.98_dp*edge)**(/(k, k=1, 80)/)]
      slow = [(1.02_dp*edge)**(/(k, k=1, 80)/)]
      n = observe_all(steady, nfire)
      call check(error, n == 0, "steady progress (just faster than the factor per window) must never fire: "//to_string(n))
      if (allocated(error)) return
      n = observe_all(slow, nfire)
      call check(error, n > 0 .and. n == first_stall(slow), &
                 "progress just slower than the factor per window must fire where the definition says")
      if (allocated(error)) return
      ! Once dropped nothing is observed and it never fires again.
      do k = 1, size(flat)
         call guard%observe(flat(k), fired)
      end do
      call check(error, guard%dropped .and. guard%n_seen == SHIFT_STALL_WINDOW + 1, "the guard must latch and stop counting")
   end subroutine test_shift_guard_sequences

   subroutine test_shift_now_scope(error)
      !! scf_driver_shift_now on synthetic commutators: only a shift that
      !! level_shift_until keeps on through DIIS is watched.
      type(error_type), allocatable, intent(out) :: error
      type(trc_scf_options_t) :: o
      type(scf_shift_guard_t) :: guard, other
      type(cdiis_t) :: history
      logical :: shift
      integer :: k
      o%level_shift = 1.0_dp
      o%level_shift_until = 1.0e-4_dp
      o%conv_diis = 1.0e-8_dp
      ! The damped start (DIIS off) is shifted whatever the commutator does, and not watched.
      do k = 1, 3*SHIFT_STALL_WINDOW
         call scf_driver_shift_now(o, .false., .false., 1.0e-3_dp, guard, history, .false., shift)
         call check(error, shift, "the damped start must stay shifted")
         if (allocated(error)) return
      end do
      call check(error, guard%n_seen == 0 .and. .not. guard%dropped, "the damped start must not feed the guard")
      if (allocated(error)) return
      ! Below the threshold: not shifted, not watched.
      call scf_driver_shift_now(o, .true., .false., 1.0e-5_dp, guard, history, .false., shift)
      call check(error, .not. shift .and. guard%n_seen == 0, "below level_shift_until the shift is off and unwatched")
      if (allocated(error)) return
      ! DIIS on, commutator parked above the threshold: shifted for one window, then dropped for good
      ! and the DIIS history restarted.
      history%n_used = 7
      do k = 1, SHIFT_STALL_WINDOW
         call scf_driver_shift_now(o, .true., .false., 1.0e-3_dp, guard, history, .false., shift)
         call check(error, shift .and. guard%n_seen == k, "the parked run must stay shifted for a window")
         if (allocated(error)) return
      end do
      call check(error, history%n_used == 7, "the history must be kept while the shift is on")
      if (allocated(error)) return
      call scf_driver_shift_now(o, .true., .false., 1.0e-3_dp, guard, history, .false., shift)
      call check(error, .not. shift .and. guard%dropped, "the stall must drop the shift")
      if (allocated(error)) return
      call check(error, history%n_used == 0, "dropping the shift must restart the DIIS history")
      if (allocated(error)) return
      do k = 1, 3
         call scf_driver_shift_now(o, .true., .true., 1.0e-3_dp, guard, history, .false., shift)
         call check(error, .not. shift, "the dropped shift must stay off")
         if (allocated(error)) return
      end do
      ! The damped-start shift is not the one dropped.
      call scf_driver_shift_now(o, .false., .false., 1.0e-3_dp, guard, history, .false., shift)
      call check(error, shift, "dropping level_shift_until must not turn off the damped-start shift")
      if (allocated(error)) return
      ! ADIIS counts as DIIS; a commutator that can converge, a zero shift and a zero threshold
      ! are never shifted nor watched.
      call scf_driver_shift_now(o, .false., .true., 1.0e-3_dp, other, history, .false., shift)
      call check(error, shift .and. other%n_seen == 1, "an ADIIS iteration is watched like a DIIS one")
      if (allocated(error)) return
      call scf_driver_shift_now(o, .true., .false., 1.0e-9_dp, other, history, .false., shift)
      call check(error, .not. shift .and. other%n_seen == 1, "an iteration that can converge is never shifted")
      if (allocated(error)) return
      o%level_shift_until = 0.0_dp
      call scf_driver_shift_now(o, .true., .false., 1.0e-3_dp, other, history, .false., shift)
      call check(error, .not. shift .and. other%n_seen == 1, "level_shift_until = 0: DIIS iterations are unshifted")
   end subroutine test_shift_now_scope

   subroutine capi_o3(h, until, error)
