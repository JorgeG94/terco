   subroutine test_mom_soscf_notes(error)
      !! After the second-order phase the run says the occupation is not
      !! aufbau exactly when the returned orbital energies are not in aufbau
      !! order, whichever way SOSCF went: (a) from the swapped density it
      !! descends (Newton minimises) and, measured, ends on the ground state,
      !! so there must be no such note (a note kept from the MOM iterations
      !! would be false); (b) from the converged excited state, with room for
      !! one Newton step only, it has not left it, and the note must survive
      !! SOSCF's rewrite of the orbital energies, as must the skipped gap
      !! check (no negative-gap warning).
      type(error_type), allocatable, intent(out) :: error
      type(trc_basis_t) :: bas
      type(trc_scf_options_t) :: o
      type(trc_scf_result_t) :: ground, held, from_swap, from_excited
      real(dp), allocatable :: dex(:, :, :)
      character(len=:), allocatable :: log_swap, log_excited
      character(len=*), parameter :: NOTE = "mom kept a non-aufbau occupation"
      integer :: nocc
      call water_swapped(bas, nocc, ground, dex, error)
      if (allocated(error)) then
         call bas%release()
         return
      end if
      o%conv_energy = 1.0e-10_dp
      o%conv_diis = 1.0e-8_dp
      o%max_iteration = 100
      o%mom = .true.
      o%mom_follow_guess = .true.
      call trc_scf_run(bas, nocc, nocc, o, held, dguess=dex)
      call mom_soscf_log(bas, nocc, 100, dex, from_swap, log_swap)
      call mom_soscf_log(bas, nocc, 2, held%dmat, from_excited, log_excited)
      call bas%release()
      call check(error, held%converged .and. from_swap%converged, "a run did not converge")
      if (allocated(error)) return
      call check(error, from_excited%eps(nocc, 1) > from_excited%eps(nocc + 1, 1), &
                 "precondition: one Newton step from the excited state must leave it non-aufbau")
      if (allocated(error)) return
      call check(error, index(log_excited, NOTE) > 0, "the non-aufbau note was lost after the second-order phase")
      if (allocated(error)) return
      call check(error, index(log_excited, "HOMO-LUMO gap is only") == 0, "a gap warning was given for a non-aufbau occupation")
      if (allocated(error)) return
      call check(error, (from_swap%eps(nocc, 1) > from_swap%eps(nocc + 1, 1)) .eqv. (index(log_swap, NOTE) > 0), &
                 "the non-aufbau note disagrees with the orbital energies (E - E0 = "// &
                 to_string(from_swap%energy - ground%energy, "f12.8")//")")
   end subroutine test_mom_soscf_notes

